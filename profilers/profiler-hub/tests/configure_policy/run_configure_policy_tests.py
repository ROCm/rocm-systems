# --------------------------------------------------------------------------- #
# Dependency table
# --------------------------------------------------------------------------- #


@dataclass(frozen=True)
class Dependency:
    """One gated dependency, as the gate and its upstream package define it."""

    # find_package() name -- also the config filename stem and directory name.
    package: str
    # cmake/<gate_file>.cmake, and the CACHE STRING in it holding the floor.
    gate_file: str
    version_var: str
    # COMPATIBILITY the *real* upstream package passes to
    # write_basic_package_version_file(). Not uniform across these five, and
    # getting it wrong makes the whole suite green against a world that does
    # not exist -- see README.md.
    compatibility: str
    targets: tuple[str, ...]
    # Extra INTERFACE_COMPILE_DEFINITIONS the gate reads off the target.
    definitions: tuple[str, ...] = ()
    # STATUS line the gate prints when it accepts. {version} is substituted.
    accept_pattern: str = ""
    # Fragment of the FATAL_ERROR the gate prints when it refuses.
    refuse_pattern: str = ""
    # Extra assertions on the refusal text: the message has to be actionable,
    # not merely present.
    refuse_must_mention: tuple[str, ...] = ()



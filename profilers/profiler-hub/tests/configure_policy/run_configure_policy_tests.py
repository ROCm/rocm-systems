"""Drive profiler-hub's dependency gate through every decision it can make.

The gate decides, per dependency, whether what is on CMAKE_PREFIX_PATH is
acceptable -- and refuses with a specific message when it is not. Those
refusals are the part nobody exercises: a CI job that has the dependencies
installed only ever walks the accept path, and a job that has none of them
fails at the first gate and never reaches the rest.

This runs the whole table instead, by staging *stand-in* packages: a
<Package>Config.cmake declaring INTERFACE IMPORTED targets plus a
<Package>ConfigVersion.cmake generated by CMake's own
write_basic_package_version_file(). find_package() cannot tell one from a real
installation, because a config-mode find_package() reads nothing else. No
downloads, no builds, no network -- see README.md for what that buys and what
it does not.

Nothing here modifies the project. The source tree is read-only to this script;
--source-dir exists so a deliberately-broken copy can be pointed at instead,
which is how the suite's own failure modes get checked.

Usage:
    python3 run_configure_policy_tests.py [--source-dir DIR] [--work-dir DIR]
                                          [--jobs N] [--verbose] [--only PAT]
"""


# --------------------------------------------------------------------------- #
# Version arithmetic
# --------------------------------------------------------------------------- #


def parse_version(text: str) -> tuple[int, int, int]:
    parts = [int(p) for p in text.split(".")[:3]]
    while len(parts) < 3:
        parts.append(0)
    return parts[0], parts[1], parts[2]


def format_version(version: tuple[int, int, int]) -> str:
    return ".".join(str(p) for p in version)


def below_floor(floor: tuple[int, int, int]) -> str:
    """The nearest version the gate must refuse for being too old."""
    major, minor, patch = floor
    if patch > 0:
        return format_version((major, minor, patch - 1))
    if minor > 0:
        return format_version((major, minor - 1, 0))
    if major > 0:
        return format_version((major - 1, 0, 0))
    raise ValueError("floor 0.0.0 has nothing below it")


def above_floor(floor: tuple[int, int, int]) -> str:
    """Newer than the floor, same major."""
    major, minor, _ = floor
    return format_version((major, minor + 1, 0))


def next_major(floor: tuple[int, int, int]) -> str:
    return format_version((floor[0] + 1, 0, 0))


def read_floor(source_dir: Path, dep: Dependency) -> tuple[int, int, int]:
    """Read the floor out of the gate file rather than duplicating it here.

    The floor is somebody else's to change. This suite tests the policy, not
    the number, so a legitimate floor bump must not turn it red.
    """
    gate = source_dir / "cmake" / dep.gate_file
    text = gate.read_text(encoding="utf-8")
    match = re.search(
        r"set\(\s*" + re.escape(dep.version_var) + r'\s+"([0-9][0-9.]*)"',
        text,
    )
    if not match:
        raise SystemExit(
            f"cannot read {dep.version_var} from {gate}: the gate file's shape "
            f"changed, so this suite no longer knows what floor it is testing"
        )
    return parse_version(match.group(1))


# --------------------------------------------------------------------------- #
# Cases
# --------------------------------------------------------------------------- #


@dataclass
class Case:
    name: str
    expect: str
    # package -> version, applied on top of the all-at-floor baseline.
    versions: dict[str, str] = field(default_factory=dict)
    # packages to leave out of the prefix entirely.
    absent: tuple[str, ...] = ()
    # package -> definitions tuple, overriding the table.
    definitions: dict[str, tuple[str, ...]] = field(default_factory=dict)
    # package -> pointer size baked into its version file, overriding the
    # consuming project's. Only used to drive the architecture check.
    pointer_sizes: dict[str, str] = field(default_factory=dict)
    extra_cmake_args: tuple[str, ...] = ()
    expect_stdout: tuple[str, ...] = ()
    expect_stderr: tuple[str, ...] = ()
    forbid_stdout: tuple[str, ...] = ()
    # Set only by the control case that is *supposed* to attempt a download.
    allow_fetch: bool = False
    why: str = ""


def build_cases(source_dir: Path) -> list[Case]:
    floors = {dep.package: read_floor(source_dir, dep) for dep in DEPENDENCIES}
    cases: list[Case] = []

    cases.append(
        Case(
            name="baseline_all_at_floor",
            expect=ACCEPT,
            expect_stdout=tuple(
                dep.accept_pattern.format(
                    version=re.escape(format_version(floors[dep.package]))
                )
                for dep in DEPENDENCIES
            ),
            why="every dependency exactly at its floor is the accept case",
        )
    )

    for dep in DEPENDENCIES:
        floor = floors[dep.package]
        floor_text = format_version(floor)
        refuse = dep.refuse_pattern.format(floor=re.escape(floor_text))

        cases.append(
            Case(
                name=f"{dep.package}_at_floor",
                expect=ACCEPT,
                versions={dep.package: floor_text},
                expect_stdout=(
                    dep.accept_pattern.format(version=re.escape(floor_text)),
                ),
                why="the floor itself is accepted, not just versions past it",
            )
        )

        above = above_floor(floor)
        cases.append(
            Case(
                name=f"{dep.package}_above_floor",
                expect=ACCEPT,
                versions={dep.package: above},
                expect_stdout=(dep.accept_pattern.format(version=re.escape(above)),),
                why="newer within the same major is accepted",
            )
        )

        below = below_floor(floor)
        cases.append(
            Case(
                name=f"{dep.package}_below_floor",
                expect=REFUSE,
                versions={dep.package: below},
                expect_stderr=(refuse,)
                + tuple(re.escape(m) for m in dep.refuse_must_mention),
                why="one patch below the floor is refused, and the refusal is actionable",
            )
        )

        cases.append(
            Case(
                name=f"{dep.package}_absent",
                expect=REFUSE,
                absent=(dep.package,),
                expect_stderr=(refuse,)
                + tuple(re.escape(m) for m in dep.refuse_must_mention),
                why="nothing on the prefix path is refused with the same message as too-old",
            )
        )

        # The interesting one. "or newer" in the refusal is not what the
        # version file actually implements for a SameMajorVersion package: a
        # newer *major* is refused, and refused with a message saying it is
        # not new enough.
        bumped = next_major(floor)
        same_major = dep.compatibility == "SameMajorVersion"
        cases.append(
            Case(
                name=f"{dep.package}_next_major",
                expect=REFUSE if same_major else ACCEPT,
                versions={dep.package: bumped},
                expect_stderr=(refuse,) if same_major else (),
                expect_stdout=(
                    ()
                    if same_major
                    else (dep.accept_pattern.format(version=re.escape(bumped)),)
                ),
                why=(
                    "upstream ships SameMajorVersion, so the next major is refused"
                    if same_major
                    else "upstream ships AnyNewerVersion, so the next major is accepted"
                ),
            )
        )

    # spdlog carries a second gate, after and independent of the version check:
    # an spdlog built against its own bundled fmt would put two fmt copies in
    # one binary. The check reads the imported target, so a stand-in can drive
    # it by simply not setting the definition.
    cases.append(
        Case(
            name="spdlog_without_fmt_external",
            expect=REFUSE,
            definitions={"spdlog": ()},
            expect_stderr=(
                r"profiler-hub requires an spdlog built with SPDLOG_FMT_EXTERNAL",
                re.escape("CMAKE_DISABLE_FIND_PACKAGE_spdlog=ON"),
            ),
            why="version-acceptable spdlog with the wrong fmt linkage is still refused",
        )
    )

    # rocpd is not a find_package() dependency -- it is a schema directory, and
    # its gate is three-way (in-tree / refuse / clone). The clone arm needs the
    # network and is deliberately not exercised; see README.md.
    cases.append(
        Case(
            name="rocpd_in_tree",
            expect=ACCEPT,
            expect_stdout=(r"Using in-tree rocprofiler-sdk-rocpd schema at",),
            forbid_stdout=(r"cloning from", r"Using cloned rocprofiler-sdk-rocpd"),
            why="the in-tree schema is used and nothing is cloned",
        )
    )
    cases.append(
        Case(
            name="rocpd_absent",
            expect=REFUSE,
            extra_cmake_args=("-DROCPD_SCHEMA_VERSION=0.0.0-no-such-version",),
            expect_stderr=(
                r"rocprofiler-sdk-rocpd schema directory not found",
                re.escape("PROFILER_HUB_FETCH_DEPENDENCIES=ON"),
            ),
            why="a schema version with no directory is refused rather than silently skipped",
        )
    )

    # An acceptable version built for the wrong architecture must still be
    # refused, and that check lives in the generated version file rather than
    # in our gate. This case exists because the stand-ins once skipped it
    # silently -- script mode leaves CMAKE_SIZEOF_VOID_P empty, and the
    # generated file then returns before the check runs. Without a case that
    # depends on it, that regression is invisible.
    cases.append(
        Case(
            name="fmt_wrong_architecture",
            expect=REFUSE,
            pointer_sizes={"fmt": "4"},
            expect_stderr=(
                DEPENDENCIES[0].refuse_pattern.format(
                    floor=re.escape(format_version(floors["fmt"]))
                ),
            ),
            why="right version, wrong pointer size, still refused",
        )
    )

    # The control for every other case's silence about the network. With
    # fetching ON and nothing to find, the gate is supposed to download -- and
    # under the block it cannot. That this one case dies on the network is what
    # makes the other cases' passing mean something.
    cases.append(
        Case(
            name="control_fetch_path_is_blocked",
            expect=REFUSE,
            absent=tuple(dep.package for dep in DEPENDENCIES),
            extra_cmake_args=("-DPROFILER_HUB_FETCH_DEPENDENCIES=ON",),
            allow_fetch=True,
            # Pin *where* it fails. A control that is allowed to fail anywhere
            # would keep passing after it stopped demonstrating anything.
            expect_stderr=(r"gitclone\.cmake", r"FetchContent\.cmake"),
            why="proves the network block is real, by taking the one path that needs it",
        )
    )

    return cases



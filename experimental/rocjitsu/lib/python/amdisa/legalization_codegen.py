"""Emit C++20 legalization tables from ``LegalizationGenerator`` output.

Generates:
- ``legalization_tables.h`` — shared header with ``LegEntry`` struct,
  ``Action`` enum, ``std::span``-based lookup, and per-pair table
  declarations.
- One ``.cpp`` file per (source, target) ISA pair containing the sorted
  ``LegEntry`` array.
"""

from __future__ import annotations

from pathlib import Path

from amdisa.legalization import LegalizationEntry


_COPYRIGHT = """\
// SPDX-License-Identifier: MIT
// Copyright (c) 2024-2026 Advanced Micro Devices, Inc. All rights reserved.
//
// AUTO-GENERATED by amdisa legalization codegen -- DO NOT EDIT
"""


def _action_enum(entry: LegalizationEntry) -> str:
    return {
        'identity': 'Action::Identity',
        'substitute': 'Action::Substitute',
        'lower': 'Action::Lower',
        'expand': 'Action::Expand',
        'illegal': 'Action::Illegal',
    }[entry.action.kind]


def _pair_name(src: str, dst: str) -> str:
    return f'{src}_{dst}'


def emit_all(
    output_dir: str | Path,
    pairs: list[tuple[str, str, list[LegalizationEntry]]],
) -> list[str]:
    """Write the shared header and per-pair .cpp files.

    Returns a list of generated file paths.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    generated: list[str] = []

    header_path = output_dir / 'legalization_tables.h'
    _emit_header(header_path, pairs)
    generated.append(str(header_path))

    for src, dst, entries in pairs:
        sorted_entries = sorted(entries, key=lambda e: (e.src_encoding_order, e.src_opcode))
        cpp_path = output_dir / f'legalize_{_pair_name(src, dst)}.cpp'
        _emit_table_cpp(cpp_path, src, dst, sorted_entries)
        generated.append(str(cpp_path))

    return generated


def _emit_header(
    path: Path,
    pairs: list[tuple[str, str, list[LegalizationEntry]]],
) -> None:
    lines = [_COPYRIGHT, '', '#pragma once', '',
             '#include <algorithm>',
             '#include <compare>',
             '#include <cstdint>',
             '#include <span>',
             '',
             'namespace rocjitsu {',
             '']

    # Action enum
    lines += [
        'enum class Action : uint8_t {',
        '    Identity   = 0,',
        '    Substitute = 1,',
        '    Lower      = 2,',
        '    Expand     = 3,',
        '    Illegal    = 4,',
        '};',
        '',
    ]

    # LegEntry struct with C++20 spaceship operator
    lines += [
        'struct LegEntry {',
        '    uint16_t src_opcode;',
        '    uint16_t src_encoding_id;',
        '    Action   action;',
        '    uint16_t target_opcode;',
        '',
        '    constexpr auto operator<=>(const LegEntry &rhs) const {',
        '        if (auto cmp = src_encoding_id <=> rhs.src_encoding_id; cmp != 0)',
        '            return cmp;',
        '        return src_opcode <=> rhs.src_opcode;',
        '    }',
        '    constexpr bool operator==(const LegEntry &rhs) const = default;',
        '};',
        '',
    ]

    # Per-pair extern declarations
    for src, dst, entries in pairs:
        name = _pair_name(src, dst)
        n = len(entries)
        lines.append(f'inline constexpr size_t kTable_{name}_size = {n};')
        lines.append(f'extern const LegEntry kTable_{name}[kTable_{name}_size];')

    lines.append('')

    # lookup function using std::span and std::lower_bound
    lines += [
        '/// Binary-search a sorted legalization table by (encoding_id, opcode).',
        '/// Returns nullptr if the (encoding_id, opcode) pair is not found.',
        'inline const LegEntry *lookup(',
        '    std::span<const LegEntry> table,',
        '    uint16_t encoding_id, uint16_t opcode) {',
        '    LegEntry key{.src_opcode = opcode, .src_encoding_id = encoding_id,',
        '                 .action = Action::Illegal, .target_opcode = 0};',
        '    auto it = std::lower_bound(table.begin(), table.end(), key);',
        '    if (it != table.end() && *it == key)',
        '        return &*it;',
        '    return nullptr;',
        '}',
        '',
    ]

    lines += [
        '}  // namespace rocjitsu',
        '',
    ]

    path.write_text('\n'.join(lines))


def _emit_table_cpp(
    path: Path,
    src: str, dst: str,
    entries: list[LegalizationEntry],
) -> None:
    name = _pair_name(src, dst)
    lines = [_COPYRIGHT, '',
             '#include "legalization_tables.h"', '',
             'namespace rocjitsu {', '',
             f'const LegEntry kTable_{name}[kTable_{name}_size] = {{']

    for e in entries:
        tgt = e.action.target_opcode if e.action.kind == 'substitute' else 0
        lines.append(
            f'    {{{e.src_opcode:>5}, {e.src_encoding_order:>3}, '
            f'{_action_enum(e):<20s}, {tgt:>5}}},  // {e.src_mnemonic}'
        )

    lines += [
        '};',
        '',
        '}  // namespace rocjitsu',
        '',
    ]

    path.write_text('\n'.join(lines))

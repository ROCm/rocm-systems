#!/usr/bin/env python3
"""Assert that a Catch2 binary registers exactly the test cases we expect.

A case behind an #if can leave a binary with no signal whatsoever -- not failed,
not skipped, simply absent -- so a fully green run can hide it. That is how
Unit_HRR_Regions_MemcpyFirstTouchMaterialization stayed invisible through a
106/106 gfx950 run: HRR_HAVE_HSA was never defined anywhere in the tree, so the
case compiled out and no report it could have appeared in ever existed.

This check asserts on the *compiled artifact* rather than on the source, which
is what makes it catch that class of problem. It fails in both directions: a
case that disappears is an error, and so is one that appears unannounced,
because an unreviewed addition is how a manifest silently stops meaning
anything.

Case names come from `--list-tests "*" --reporter xml`. The "*" is required --
without it Catch2 omits hidden `[.]` cases, which is most of the integration
suite. The XML reporter is used rather than the console listing because the
console form is a formatted table, and formatting is not a contract.

Usage:
    check_expected_cases.py --binary <exe> --manifest <file>
    check_expected_cases.py --binary <exe> --manifest <file> --update
"""

import argparse
import subprocess
import sys
import xml.etree.ElementTree as ET

HEADER = [
    "# Test cases expected to be present in this binary, one per line, sorted.",
    "# Generated by check_expected_cases.py --update; do not hand-edit casually.",
    "#",
    "# A diff here is a real finding either way. Cases vanish when a guard stops",
    "# being satisfied (a missing -D, a find_package that quietly failed), and",
    "# that vanishing is otherwise completely silent. Regenerate only when you",
    "# intended to add or remove a case, and say so in the commit message.",
]


def listed_cases(binary: str) -> list[str]:
    """Every case the binary registers, hidden ones included."""
    proc = subprocess.run(
        [binary, "--list-tests", "*", "--reporter", "xml"],
        capture_output=True, text=True,
    )
    if proc.returncode != 0:
        sys.exit(f"error: {binary} --list-tests failed ({proc.returncode})\n"
                 f"{proc.stderr.strip()}")
    try:
        root = ET.fromstring(proc.stdout)
    except ET.ParseError as exc:
        sys.exit(f"error: could not parse --list-tests XML from {binary}: {exc}")
    names = [e.text or "" for e in root.iter("Name")]
    if not names:
        sys.exit(f"error: {binary} listed no test cases at all -- that is itself "
                 f"the failure this check exists to catch")
    return sorted(names)


def read_manifest(path: str) -> list[str]:
    try:
        with open(path, encoding="utf-8") as fh:
            return sorted(ln.strip() for ln in fh
                          if ln.strip() and not ln.startswith("#"))
    except FileNotFoundError:
        sys.exit(f"error: manifest {path} not found; create it with --update")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--binary", required=True, help="Catch2 test executable")
    ap.add_argument("--manifest", required=True, help="expected-cases file")
    ap.add_argument("--update", action="store_true",
                    help="rewrite the manifest from the binary instead of checking")
    args = ap.parse_args()

    actual = listed_cases(args.binary)

    if args.update:
        with open(args.manifest, "w", encoding="utf-8") as fh:
            fh.write("\n".join(HEADER) + "\n")
            fh.write("\n".join(actual) + "\n")
        print(f"wrote {len(actual)} case names to {args.manifest}")
        return 0

    expected = read_manifest(args.manifest)
    missing = [n for n in expected if n not in set(actual)]
    unexpected = [n for n in actual if n not in set(expected)]

    if not missing and not unexpected:
        print(f"OK: {len(actual)} test cases present, matching {args.manifest}")
        return 0

    print(f"FAIL: {args.binary} does not match {args.manifest}", file=sys.stderr)
    print(f"  expected {len(expected)} cases, found {len(actual)}", file=sys.stderr)
    for n in missing:
        print(f"  MISSING (compiled out or deleted): {n}", file=sys.stderr)
    for n in unexpected:
        print(f"  UNEXPECTED (added without updating manifest): {n}", file=sys.stderr)
    if missing:
        print("\nA MISSING case is usually a guard that stopped being satisfied -- "
              "check that every -D its #if needs is still passed by CMake.",
              file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())

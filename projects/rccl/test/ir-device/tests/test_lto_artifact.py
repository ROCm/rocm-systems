# 7: the IR is well-formed
# --------------------------------------------------------------------------

@pytest.mark.ir_device
@pytest.mark.lto_bc
@pytest.mark.lto_artifact
def test_both_artifacts_pass_llvm_verifier(lto_bitcode_ir, paths):
    """Both artifacts are valid LLVM IR.

    Cheap, but not redundant: the LTO artifact is raw clang frontend output
    that skips the pre-link pass pipeline, so it has never been through the
    cleanups that normally run before anything else looks at it.
    """
    opt = _llvm_tool(paths.ROCM_PATH, "opt")
    for label, bc in (("plain", paths.BITCODE), ("lto", paths.LTO_BITCODE)):
        proc = subprocess.run(
            [opt, "-passes=verify", "-disable-output", bc],
            capture_output=True, universal_newlines=True,
        )
        assert proc.returncode == 0, (
            f"{label} artifact failed the LLVM verifier:\n{proc.stderr}"
        )

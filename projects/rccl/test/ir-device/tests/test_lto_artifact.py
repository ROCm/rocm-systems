@pytest.mark.ir_device
@pytest.mark.lto_bc
@pytest.mark.lto_artifact
def test_lto_artifact_has_no_optnone_or_noinline(lto_bitcode_ir, paths):
    """The LTO flags must not stamp optnone or noinline into the artifact.

    The whole point of the artifact is that the *downstream* link optimizes it.
    `optnone` forbids that outright, `noinline` forbids the inlining half, and
    both survive the LTO link. Checked across every function, not just the
    exported thunks: an internal callee pinned with `noinline` defeats deferral
    just as thoroughly.

    This is the regression guard on the compile flags. -O0 stamps both, and
    keeps stamping both when combined with -Xclang -disable-llvm-passes --
    measured, not assumed. Only `-O1 -Xclang -disable-llvm-passes`, what the
    build uses, stamps neither.

    `noinline` is asserted differentially, against the plain artifact rather
    than against zero, because a handful of functions are noinline in their own
    source and would be in any build: ROCm's device-library `__assert_fail` is
    the current (sole) example. The plain artifact is the control -- it is
    compiled from the same TU with the same headers and differs only in the
    flags under test, so anything noinline there is upstream's doing and
    anything noinline *only* in the LTO artifact is ours. `optnone` has no such
    exemption; nothing on this path has any business carrying it.
    """
    def census(ll_path):
        groups = _parse_attr_groups(ll_path)
        found = {"optnone": set(), "noinline": set()}
        for name, (_internal, attr_id, _n) in _parse_functions(ll_path).items():
            attrs = groups.get(attr_id, "")
            for a in found:
                if re.search(rf"\b{a}\b", attrs):
                    found[a].add(name)
        return found

    lto = census(lto_bitcode_ir.lto)
    plain = census(lto_bitcode_ir.plain)

    assert not lto["optnone"], (
        f"{len(lto['optnone'])} function(s) in librccl_device.lto.bc carry "
        "`optnone`, which permanently forbids the downstream link-time "
        "optimizer from touching them -- strictly worse than shipping "
        "optimized code. The LTO compile flags must be "
        "-O1 -Xclang -disable-llvm-passes; -O0 stamps optnone even with "
        f"-disable-llvm-passes. First few: {sorted(lto['optnone'])[:5]}"
    )

    introduced = sorted(lto["noinline"] - plain["noinline"])
    assert not introduced, (
        f"{len(introduced)} function(s) are `noinline` in "
        "librccl_device.lto.bc but not in librccl_device.bc, so the LTO flags "
        "introduced it. -O0, -fno-inline and -finline-hint-functions all do "
        f"this; none may be used here. First few: {introduced[:5]}"
    )


# --------------------------------------------------------------------------
# 5: deferral actually happened
# --------------------------------------------------------------------------

# Heavy thunks whose work is entirely in callees. In the plain artifact the
# inliner folds those callees in, so the body is enormous; in the LTO artifact
# the body is a short sequence of calls and the callees are separate functions
# for the downstream link to place. Thresholds are deliberately loose -- the
# measured ratio is ~290x on the first of these (12,048 vs 42 body lines) and
# the point is to catch a collapse back to ~1x, not to pin a number.
_DEFERRED_THUNKS = ("ncclIrLsaReduceSumCopy_F32", "ncclIrLsaBarrierSessionSync")


@pytest.mark.ir_device
@pytest.mark.lto_bc
@pytest.mark.lto_artifact
def test_lto_artifact_defers_inlining(lto_bitcode_ir):
    """librccl_device.lto.bc keeps its callees instead of folding them in.

    Before the pristine-IR change this failed in the most misleading way
    possible: the LTO artifact had 115 defines against the plain artifact's
    113, i.e. essentially everything had already been inlined and the two
    artifacts were the same thing. clang -O1 ran the full inliner before the
    artifact was ever written; dropping always_inline from the thunks'
    callees -- which is what the build used to rely on -- achieved nothing,
    because LLVM's "last call to a local function" bonus inlines an internal
    single-use callee regardless of inline attributes.
    """
    plain = _parse_functions(lto_bitcode_ir.plain)
    lto = _parse_functions(lto_bitcode_ir.lto)

    # Measured after the fix: 116 vs 4,569. A 10x floor leaves enormous room
    # for the artifact to change shape while still failing loudly if deferral
    # collapses (the pre-fix ratio was 1.02x).
    assert len(lto) > 10 * len(plain), (
        f"librccl_device.lto.bc defines only {len(lto)} functions against the "
        f"plain artifact's {len(plain)}; callees are being inlined before the "
        "artifact is written. Check that the LTO compile uses "
        "-Xclang -disable-llvm-passes and that its opt step is "
        "internalize,globaldce -- never inline."
    )

    for thunk in _DEFERRED_THUNKS:
        assert thunk in plain and thunk in lto, f"{thunk} missing from an artifact"
        plain_body = plain[thunk][2]
        lto_body = lto[thunk][2]
        assert lto_body * 4 < plain_body, (
            f"{thunk} has a {lto_body}-line body in librccl_device.lto.bc "
            f"against {plain_body} lines in librccl_device.bc; its callees "
            "have already been inlined, so there is nothing left to defer."
        )



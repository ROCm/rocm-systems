@pytest.mark.ir_device
@pytest.mark.lto_bc
@pytest.mark.lto_artifact
def test_export_surfaces_are_unmangled(lto_bitcode_ir, paths):
    """Every exported symbol in both artifacts is an unmangled ncclIr* name.

    Unmangled names come from `extern "C"` in NCCL_IR_EXPORT, not from any
    compile flag -- but they only *stay* unmangled if the LTO path internalizes
    the C++ helpers the header drags in. Without `opt --passes=internalize` the
    pristine artifact leaks every non-static header function as an external
    mangled symbol; it leaked one even before the IR went pristine.
    """
    for label, bc in (("plain", paths.BITCODE), ("lto", paths.LTO_BITCODE)):
        syms = _defined_text_symbols(paths.ROCM_PATH, bc)
        mangled = sorted(s for s in syms if s.startswith("_Z"))
        assert not mangled, (
            f"{label} artifact exports {len(mangled)} C++-mangled symbol(s); "
            "the LTO path must run opt --passes=internalize. "
            f"First few: {mangled[:5]}"
        )
        foreign = sorted(s for s in syms if not s.startswith("ncclIr"))
        assert not foreign, (
            f"{label} artifact exports {len(foreign)} symbol(s) outside the "
            f"ncclIr* namespace: {foreign[:10]}"
        )


@pytest.mark.ir_device
@pytest.mark.lto_bc
@pytest.mark.lto_artifact
def test_both_artifacts_export_the_same_surface(lto_bitcode_ir, paths):
    """The two artifacts are interchangeable from a consumer's point of view.

    They differ only in how much is inlined; a consumer that links one must be
    able to link the other without changing a single call. Any asymmetry means
    the two pipelines have drifted apart.
    """
    plain = _defined_text_symbols(paths.ROCM_PATH, paths.BITCODE)
    lto = _defined_text_symbols(paths.ROCM_PATH, paths.LTO_BITCODE)
    assert plain == lto, (
        "export surfaces diverged -- "
        f"only in .bc: {sorted(plain - lto)[:10]}; "
        f"only in .lto.bc: {sorted(lto - plain)[:10]}"
    )


@pytest.mark.ir_device
@pytest.mark.lto_bc
@pytest.mark.lto_artifact
def test_export_surface_matches_nccl_modulo_fp8(lto_bitcode_ir, paths):
    """Both artifacts export exactly NCCL's surface minus the fp8 entry points.

    99 of NCCL's 113. See NCCL_FP8_SUFFIXES above for why the 14 are absent and
    why that is not fixed at this layer.
    """
    expected = _expected_rccl_surface()
    assert len(expected) == 99, "NCCL surface table is self-inconsistent"
    for label, bc in (("plain", paths.BITCODE), ("lto", paths.LTO_BITCODE)):
        actual = _defined_text_symbols(paths.ROCM_PATH, bc)
        assert actual == expected, (
            f"{label} artifact surface drifted from NCCL's -- "
            f"missing: {sorted(expected - actual)[:10]}; "
            f"unexpected: {sorted(actual - expected)[:10]}"
        )



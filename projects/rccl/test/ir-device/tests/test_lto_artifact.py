# bindings/ir/util.h: NCCL_IR_TYPES and NCCL_IR_MULTIMEM_TYPES. The multimem
# list omits the 8-bit integer types.
NCCL_ALL_TYPE_SUFFIXES = (
    "I8", "U8", "I32", "U32", "I64", "U64",
    "F16", "F32", "F64", "BF16", "F8E4M3", "F8E5M2",
)
NCCL_MULTIMEM_TYPE_SUFFIXES = tuple(
    s for s in NCCL_ALL_TYPE_SUFFIXES if s not in ("I8", "U8")
)

NCCL_REDUCECOPY_FAMILIES = {
    "ncclLsaReduceSum": NCCL_ALL_TYPE_SUFFIXES,
    "ncclLsaCopy": NCCL_ALL_TYPE_SUFFIXES,
    "ncclLsaReduceSumCopy": NCCL_ALL_TYPE_SUFFIXES,
    "ncclLocalReduceSumCopy": NCCL_ALL_TYPE_SUFFIXES,
    "ncclMultimemReduceSum": NCCL_MULTIMEM_TYPE_SUFFIXES,
    "ncclMultimemCopy": NCCL_MULTIMEM_TYPE_SUFFIXES,
    "ncclMultimemReduceSumCopy": NCCL_MULTIMEM_TYPE_SUFFIXES,
}

# The one documented gap, 14 symbols across the 7 families above.
#
# This is NOT an IR-layer omission and must not be "fixed" here.
# src/include/nccl_device/impl/reduce_copy__types.h gates the fp8 OpSum
# specializations on __CUDA_FP8_TYPES_EXIST__, which neither RCCL nor ROCm ever
# defines, so the block is dead in every RCCL build -- RCCL's *device* API has
# no fp8 at all. (RCCL's host collectives do support ncclFloat8e4m3; different
# code path.) bindings/ir/util.h therefore defines NCCL_IR_FP8_TYPES empty on
# AMD. Closing the gap is device-API work, out of scope for LTO-IR enablement.
#
# If fp8 ever does land in the device API, these entry points appear on their
# own and this test flips green with no edit -- which is the point of expressing
# the gap as a subtraction from NCCL's surface rather than freezing RCCL's.
NCCL_FP8_SUFFIXES = ("F8E4M3", "F8E5M2")


def _nccl_surface():
    """NCCL's full 113-symbol export surface."""
    names = set(NCCL_SCALAR_EXPORTS)
    for family, suffixes in NCCL_REDUCECOPY_FAMILIES.items():
        names.update(f"{family}_{s}" for s in suffixes)
    return names


def _to_rccl_name(nccl_name):
    """Map an NCCL export name onto RCCL's.

    RCCL prefixes every entry point with `ncclIr` to keep the artifact's
    symbols distinct from the host library's. The session-size getters differ
    further: NCCL's `_C_size` suffix names the ncclXxxBarrierSession_C wrapper
    structs, which RCCL replaced with opaque storage, so RCCL spells them
    `...SessionSize`.
    """
    stem = nccl_name[len("nccl"):]
    if stem.endswith("_C_size"):
        stem = stem[: -len("_C_size")] + "Size"
    return "ncclIr" + stem


def _expected_rccl_surface():
    """RCCL's intended surface: NCCL's 113 minus the 14 fp8 entry points."""
    return {
        _to_rccl_name(n)
        for n in _nccl_surface()
        if not any(n.endswith("_" + s) for s in NCCL_FP8_SUFFIXES)
    }


def _llvm_tool(rocm_path, tool):
    path = os.path.join(rocm_path, "llvm", "bin", tool)
    if not os.path.isfile(path):
        pytest.skip(f"{tool} not found at {path} (set ROCM_PATH)")
    return path


def _defined_text_symbols(rocm_path, bitcode):
    """Names of every externally-visible defined function in `bitcode`."""
    out = subprocess.run(
        [_llvm_tool(rocm_path, "llvm-nm"), "--defined-only", bitcode],
        check=True, capture_output=True, universal_newlines=True,
    ).stdout
    return {
        line.split()[2]
        for line in out.splitlines()
        if len(line.split()) >= 3 and line.split()[1] == "T"
    }


def _parse_functions(ll_path):
    """Map function name -> (is_internal, attr_group_id, body_line_count).

    Parses textual LLVM IR rather than running a tool, so a failure points at
    a line a human can go read. `attr_group_id` is the `#N` reference on the
    define line, resolved against the `attributes #N = { ... }` table by
    _parse_attr_groups.
    """
    funcs = {}
    name = None
    internal = False
    attr_id = None
    count = 0
    for line in open(ll_path):
        if line.startswith("define"):
            m = re.search(r"@([\w.$]+|\"[^\"]+\")\(", line)
            name = m.group(1).strip('"') if m else None
            internal = line.startswith("define internal")
            a = re.search(r"#(\d+)\s*(?:!|\{|$)", line)
            attr_id = int(a.group(1)) if a else None
            count = 0
        elif name is not None and line.startswith("}"):
            funcs[name] = (internal, attr_id, count)
            name = None
        elif name is not None:
            count += 1
    return funcs


def _parse_attr_groups(ll_path):
    """Map attribute-group id -> its attribute string."""
    groups = {}
    for line in open(ll_path):
        m = re.match(r"attributes #(\d+) = \{(.*)\}", line.strip())
        if m:
            groups[int(m.group(1))] = m.group(2)
    return groups



"""Artifact-level checks on librccl_device.bc and librccl_device.lto.bc.

These are static analyses of the shipped bitcode — no kernel launch, so they
are independent of the ROCm vtable-dispatch codegen bug that forces the
consumer builds in conftest.py to use -O0. That -O0 is also why none of the
defects below were ever observed from the consumer side: at -O0 the downstream
LTO inliner does nothing, so the functional suite structurally cannot tell a
deferred-inlining artifact from a fully-inlined one.

What is asserted, and why each check exists:

  * The export surface is unmangled, and identical between the two artifacts.
    librccl_device.lto.bc used to leak one C++-mangled symbol
    (_ZN9ncclGin_CC1ERK11ncclDevCommji26ncclGinResourceSharingMode), because
    the LTO path ran no `opt` at all while the plain path ran
    internalize/inline/globaldce.

  * The surface matches NCCL's, symbol for symbol, modulo a known and
    documented fp8 gap (see NCCL_FP8_SUFFIXES below).

  * librccl_device.lto.bc really defers inlining — callees survive as separate
    functions instead of being folded into the thunks.

  * No thunk carries `optnone` or `noinline`. Both are poison for a
    deferred-inlining artifact: `optnone` permanently forbids the downstream
    link-time optimizer from touching the function, which is strictly worse
    than shipping optimized code. This is a direct regression guard on the
    compile flags — -O0, -O0 -Xclang -disable-llvm-passes, -fno-inline and
    -finline-hint-functions all stamp one or both; only
    `-O1 -Xclang -disable-llvm-passes` (what the build uses) stamps neither.

Zero-addrspace(3) is asserted by test_bitcode_artifacts_own_no_lds in
test_ir_device.py and is not duplicated here.

Measured on gfx950 / ROCm 7.2.4, before and after the pristine-IR change
(`-Xclang -disable-llvm-passes` + `opt --passes=internalize,globaldce` on the
LTO path). These numbers are where the thresholds below come from:

                      defined T  mangled  define  define internal  addrspace(3)   size
  .bc      (before)          96        0     113               17            0   2.1 MB
  .lto.bc  (before)          97        1     115               18            0   2.1 MB
  .bc      (after)           99        0     116               17            0   2.1 MB
  .lto.bc  (after)           99        0   4,569            4,471            0  12.3 MB

The "before" .lto.bc is the tell: 115 defines against the plain artifact's 113
means it was an *optimized* artifact wearing a deferred-inlining label. Per-thunk
bodies, after:

                                    .bc      .lto.bc
  ncclIrLsaReduceSumCopy_F32      12,048           42   <- work now behind calls
  ncclIrLsaBarrierSessionSync        258           24
  ncclIrBarrierSessionInit           207           96
"""


// ---------------------------------------------------------------------------
// The halving loop only runs when nNodes > 1, so this is where the knob changes the
// mapping on real hardware. Seeds and pool sizes are arch/NIC dependent, so this
// derives its expectation from the observed pool rather than a constant.
//
// Scope: this checks plumbing and invariants, not the divisor. The halving loop reads
// divUp(maxP2pPeers, NCCL_MAX_DEV_WORK_P2P_PER_BATCH), which is 1 for every value below
// 3, so small requests cannot be told apart here. MultiNode_SaturateDividesByMaxP2pPeers
// below is the case that pins an exact value.
// ---------------------------------------------------------------------------
TEST_F(MaxP2pPeersMPITest, MultiNode_PerPeerChannelsRespondToMaxP2pPeers)
{
    if(!validateTestPrerequisites(kMinProcessesForMPI,
                                  kNoProcessLimit,
                                  kNoPowerOfTwoRequired,
                                  /*min_nodes=*/2))
    {
        GTEST_SKIP() << "Requires >= 2 nodes so the per-peer halving loop runs";
    }

    unsetenv("NCCL_P2P_MAX_PEERS");
    if(!maxP2pPeersEnvCachedAs(NCCL_CONFIG_UNDEF_INT))
        GTEST_SKIP() << "NCCL_P2P_MAX_PEERS already cached this process; "
                        "run this test in its own mpirun invocation.";

    configured_value_ = kLeaveConfigUnset;
    ASSERT_MPI_EQ(ncclSuccess, createTestCommunicator());
    const int perpeer_default = getActiveCommunicator()->p2pnChannelsPerPeer;
    const int pool_default    = getActiveCommunicator()->p2pnChannels;
    cleanupTestCommunicator();

    configured_value_ = 2;
    ASSERT_MPI_EQ(ncclSuccess, createTestCommunicator());
    const int perpeer_limited = getActiveCommunicator()->p2pnChannelsPerPeer;
    const int pool_limited    = getActiveCommunicator()->p2pnChannels;

    TEST_INFO("p2pnChannelsPerPeer: default=%d (pool %d), maxP2pPeers=2 -> %d (pool %d)",
              perpeer_default, pool_default, perpeer_limited, pool_limited);

    // The requested value reached this comm intact.
    ASSERT_MPI_EQ(getActiveCommunicator()->p2pMaxPeers, 2);
    // The peer count must not move the channel pool itself.
    ASSERT_MPI_EQ(pool_limited, pool_default);
    // Fewer declared peers can only stop the reduction earlier, never later.
    ASSERT_MPI_TRUE(perpeer_limited >= perpeer_default);
    // ncclP2pChannelToPart cannot recover parts >= the pool.
    ASSERT_MPI_TRUE(perpeer_limited <= pool_limited);

    expectAllRanksAgree(perpeer_limited);
}

// ---------------------------------------------------------------------------
// The exact-value case. With RCCL_SATURATE_P2P_NCHANNELS on, the per-peer count is
// pow2Down(p2pnChannels / maxP2pPeers) outright, with no dependence on the topology
// seed, so the expected result follows from the observed pool alone. Dividing by
// nRanks instead lands on pool/nRanks, which differs whenever nRanks > 2, so this
// case fails if the divisor regresses.
// ---------------------------------------------------------------------------
TEST_F(MaxP2pPeersMPITest, MultiNode_SaturateDividesByMaxP2pPeers)
{
    ASSERT_MPI_TRUE(validateTestPrerequisites(kMinProcessesForMPI));

    // Needs a rank count the nRanks divisor would distinguish from 2.
    if(MPIEnvironment::world_size <= 2)
        GTEST_SKIP() << "Needs > 2 ranks for the nRanks divisor to differ from 2";

    unsetenv("NCCL_P2P_MAX_PEERS");
    if(!maxP2pPeersEnvCachedAs(NCCL_CONFIG_UNDEF_INT))
        GTEST_SKIP() << "NCCL_P2P_MAX_PEERS already cached this process; "
                        "run this test in its own mpirun invocation.";
    setenv("RCCL_SATURATE_P2P_NCHANNELS", "1", /*overwrite=*/1);
    if(rcclParamSaturateP2pNChannels() != 1)
        GTEST_SKIP() << "RCCL_SATURATE_P2P_NCHANNELS already cached this process; "
                        "run this test in its own mpirun invocation.";

    configured_value_ = 2;
    ASSERT_MPI_EQ(ncclSuccess, createTestCommunicator());
    const int perpeer = getActiveCommunicator()->p2pnChannelsPerPeer;
    int       pool    = getActiveCommunicator()->p2pnChannels;

    TEST_INFO("saturate on, maxP2pPeers=2: pool=%d p2pnChannelsPerPeer=%d", pool, perpeer);

    // Reduce before deciding: a per-rank skip here would leave the others in the
    // ASSERT_MPI_* allreduces below.
    int min_pool = 0;
    ASSERT_MPI_SUCCESS(MPI_Allreduce(&pool, &min_pool, 1, MPI_INT, MPI_MIN, MPI_COMM_WORLD));
    if(min_pool < 4) GTEST_SKIP() << "Pool too small for the halves to differ";

    ASSERT_MPI_EQ(getActiveCommunicator()->p2pMaxPeers, 2);
    // pow2Down(pool / 2) == pool / 2, the pool being a power of two by this point.
    ASSERT_MPI_EQ(perpeer, pool / 2);
    expectAllRanksAgree(perpeer);
}

// ---------------------------------------------------------------------------
// Data correctness under a limited peer count: a broken channel mapping shows up as
// wrong data or a hang, not an error code.
// ---------------------------------------------------------------------------
TEST_F(MaxP2pPeersMPITest, Functional_AlltoAll_WithMaxP2pPeers)
{
    ASSERT_MPI_TRUE(validateTestPrerequisites(kMinProcessesForMPI));

    configured_value_ = 2;

    ASSERT_MPI_EQ(ncclSuccess, createTestCommunicator());
    expectFunctionalAllToAll();
}


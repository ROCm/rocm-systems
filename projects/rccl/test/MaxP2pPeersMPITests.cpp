// Generated by NCCL_PARAM(MaxP2pPeers, ...) in src/init.cc. Used to detect a stale
// per-process cache so the env tests can SKIP rather than report a false failure.
int64_t ncclParamMaxP2pPeers();
// Likewise from RCCL_PARAM(SaturateP2pNChannels, ...) in src/graph/paths.cc.
int64_t rcclParamSaturateP2pNChannels();

namespace
{
// Sentinel meaning "leave the config field at its default (UNDEF)".
constexpr int kLeaveConfigUnset = NCCL_CONFIG_UNDEF_INT;
} // namespace

/**
 * @class MaxP2pPeersMPITest
 * @brief Multi-rank fixture that injects maxP2pPeers via config and/or the
 *        NCCL_P2P_MAX_PEERS env, then exposes the live communicator.
 *
 * Mirrors NChannelsPerNetPeerMPITests.cpp: overrides createTestCommunicator() while
 * reusing the base members, so getActiveCommunicator()/getActiveStream() keep working.
 */
class MaxP2pPeersMPITest : public MPITestBase
{
protected:
    // Config field to request. kLeaveConfigUnset leaves it UNDEF.
    int configured_value_ = kLeaveConfigUnset;

    // Returns the raw result so the rejection case can assert on ncclInvalidArgument.
    ncclResult_t tryCreateCommunicator()
    {
        int world_rank = MPIEnvironment::world_rank;
        int world_size = MPIEnvironment::world_size;

        if(world_rank == 0)
        {
            RCCL_TEST_CHECK(ncclGetUniqueId(&nccl_id_));
        }
        MPI_Bcast(&nccl_id_, sizeof(ncclUniqueId), MPI_BYTE, 0, MPI_COMM_WORLD);

        ncclConfig_t config = NCCL_CONFIG_INITIALIZER;
        config.maxP2pPeers  = configured_value_;

        // No group wrapper: an invalid config must surface its own error code.
        ncclResult_t res =
            ncclCommInitRankConfig(&test_comm_, world_size, nccl_id_, world_rank, &config);
        if(res != ncclSuccess)
        {
            test_comm_ = nullptr;
            MPI_Barrier(MPI_COMM_WORLD);
            return res;
        }

        auto comm_guard = makeScopeGuard(
            [this]()
            {
                if(test_comm_)
                {
                    (void)ncclCommDestroy(test_comm_);
                    test_comm_ = nullptr;
                }
            });

        HIP_TEST_CHECK(hipStreamCreate(&test_stream_));
        auto stream_guard = makeScopeGuard(
            [this]()
            {
                if(test_stream_)
                {
                    (void)hipStreamDestroy(test_stream_);
                    test_stream_ = nullptr;
                }
            });

        MPI_Barrier(MPI_COMM_WORLD);

        comm_guard.dismiss();
        stream_guard.dismiss();

        if(world_rank == 0)
        {
            TEST_INFO("Communicator created; config.maxP2pPeers=%d p2pMaxPeers=%d "
                      "p2pnChannels=%d p2pnChannelsPerPeer=%d",
                      test_comm_->config.maxP2pPeers, test_comm_->p2pMaxPeers,
                      test_comm_->p2pnChannels, test_comm_->p2pnChannelsPerPeer);
        }
        return ncclSuccess;
    }

    ncclResult_t createTestCommunicator() override { return tryCreateCommunicator(); }

    // All ranks resolved the same value, whatever it is. Every rank participates.
    void expectAllRanksAgree(int local_value)
    {
        int min_value = 0;
        int max_value = 0;
        ASSERT_MPI_SUCCESS(
            MPI_Allreduce(&local_value, &min_value, 1, MPI_INT, MPI_MIN, MPI_COMM_WORLD));
        ASSERT_MPI_SUCCESS(
            MPI_Allreduce(&local_value, &max_value, 1, MPI_INT, MPI_MAX, MPI_COMM_WORLD));
        ASSERT_MPI_EQ(min_value, max_value);
    }

    // The pair every resolution test checks: what the user asked for, what paths.cc will
    // divide by, and that the ranks agree on it. The two differ only when the field is
    // left UNDEF, where the divisor resolves to the communicator size.
    void expectResolvedMaxP2pPeers(int expectedConfig, int expectedResolved)
    {
        ASSERT_MPI_EQ(getActiveCommunicator()->config.maxP2pPeers, expectedConfig);
        ASSERT_MPI_EQ(getActiveCommunicator()->p2pMaxPeers, expectedResolved);
        expectAllRanksAgree(getActiveCommunicator()->p2pMaxPeers);
    }

    void expectResolvedMaxP2pPeers(int expected) { expectResolvedMaxP2pPeers(expected, expected); }

    // NCCL_PARAM caches per process, so an earlier test that set the variable pins it for
    // the rest of the binary and unsetenv cannot undo that. Tests needing a particular
    // cached state skip rather than report a failure that is really test ordering.
    bool maxP2pPeersEnvCachedAs(int expected) { return ncclParamMaxP2pPeers() == expected; }

    // Rank r sends its index to every peer, so it must receive [0..world_size-1].
    // The per-peer count feeds ncclP2pChannelForPart/ToPart, whose inverse breaks if
    // it exceeds the pool: wrong data or a hang here means the mapping aliased.
    void expectFunctionalAllToAll()
    {
        const int   world_size = MPIEnvironment::world_size;
        const int   world_rank = MPIEnvironment::world_rank;
        ncclComm_t  comm       = getActiveCommunicator();
        hipStream_t stream     = getActiveStream();
        ASSERT_MPI_TRUE(comm != nullptr && stream != nullptr);

        float* send_dev = nullptr;
        float* recv_dev = nullptr;
        ASSERT_MPI_EQ(hipMalloc(&send_dev, world_size * sizeof(float)), hipSuccess);
        auto send_guard = makeScopeGuard([&]() { (void)hipFree(send_dev); });
        ASSERT_MPI_EQ(hipMalloc(&recv_dev, world_size * sizeof(float)), hipSuccess);
        auto recv_guard = makeScopeGuard([&]() { (void)hipFree(recv_dev); });

        std::vector<float> host(world_size, static_cast<float>(world_rank));
        ASSERT_MPI_EQ(
            hipMemcpy(send_dev, host.data(), world_size * sizeof(float), hipMemcpyHostToDevice),
            hipSuccess);

        // Every check in this function must be collective: a rank returning early would
        // strand the others in ncclGroupEnd or in the allreduces below.
        ncclResult_t op_res = ncclGroupStart();
        for(int peer = 0; peer < world_size; ++peer)
        {
            ncclResult_t s_res = ncclSend(send_dev + peer, 1, ncclFloat, peer, comm, stream);
            ncclResult_t r_res = ncclRecv(recv_dev + peer, 1, ncclFloat, peer, comm, stream);
            if(op_res == ncclSuccess) op_res = s_res;
            if(op_res == ncclSuccess) op_res = r_res;
        }
        ncclResult_t end_res = ncclGroupEnd();
        if(op_res == ncclSuccess) op_res = end_res;
        ASSERT_MPI_EQ(op_res, ncclSuccess);
        ASSERT_MPI_EQ(hipStreamSynchronize(stream), hipSuccess);

        std::vector<float> result(world_size, -1.0f);
        ASSERT_MPI_EQ(
            hipMemcpy(result.data(), recv_dev, world_size * sizeof(float), hipMemcpyDeviceToHost),
            hipSuccess);

        bool local_ok = true;
        for(int i = 0; i < world_size; ++i)
        {
            if(result[i] != static_cast<float>(i))
            {
                local_ok = false;
                TEST_WARN("AllToAll mismatch at [%d]: got %f expected %d", i, result[i], i);
                break;
            }
        }
        ASSERT_MPI_TRUE(local_ok);
    }
};

// ---------------------------------------------------------------------------
// Config field honored across a real multi-rank communicator.
// ---------------------------------------------------------------------------
TEST_F(MaxP2pPeersMPITest, ConfigField_HonoredAcrossRanks)
{
    ASSERT_MPI_TRUE(validateTestPrerequisites(kMinProcessesForMPI));

    constexpr int kRequested = 4;
    if(MPIEnvironment::world_size < kRequested)
        GTEST_SKIP() << "Needs at least " << kRequested << " ranks to be distinguishable";
    configured_value_ = kRequested;

    ASSERT_MPI_EQ(ncclSuccess, createTestCommunicator());

    expectResolvedMaxP2pPeers(kRequested);
}

// ---------------------------------------------------------------------------
// Env honored across ranks. Asserts behavior, not a log string, so this is the
// authoritative check that the variable is spelled NCCL_P2P_MAX_PEERS.
// ---------------------------------------------------------------------------
TEST_F(MaxP2pPeersMPITest, Env_HonoredAcrossRanks)
{
    ASSERT_MPI_TRUE(validateTestPrerequisites(kMinProcessesForMPI));

    constexpr int kEnvValue = 4;
    if(MPIEnvironment::world_size < kEnvValue)
        GTEST_SKIP() << "Needs at least " << kEnvValue << " ranks to be distinguishable";
    setenv("NCCL_P2P_MAX_PEERS", std::to_string(kEnvValue).c_str(), /*overwrite=*/1);
    configured_value_ = kLeaveConfigUnset; // env alone drives the value

    if(ncclParamMaxP2pPeers() != kEnvValue)
        GTEST_SKIP() << "NCCL_P2P_MAX_PEERS already cached this process; "
                        "run this test in its own mpirun invocation.";

    ASSERT_MPI_EQ(ncclSuccess, createTestCommunicator());

    expectResolvedMaxP2pPeers(kEnvValue);
}


# Embeds tuner/*.csv into a C++ header so librccl.so ships built-in CSV tuner
# configs without the files being staged on disk.
#
# Usage:
#   python3 embed_tuner_configs.py <tuner_dir> <out_file>
#
# Follows the Python-in-CMake pattern established by src/device/generate.py.

import glob
import os
import sys

RAW_DELIM = "RCCLCSV"
RAW_TERMINATOR = f"){RAW_DELIM}\""


def embed(tuner_dir, out_file):
    csv_files = sorted(glob.glob(os.path.join(tuner_dir, "rccl_tuner*.csv")))

    entries = []
    for csv_path in csv_files:
        name = os.path.basename(csv_path)

        if '"' in name or "\\" in name:
            sys.exit(f"error: {csv_path}: filename contains a quote or backslash and cannot be embedded")

        try:
            with open(csv_path, "r", encoding="utf-8") as f:
                content = f.read()
        except UnicodeDecodeError as exc:
            sys.exit(f"error: {csv_path}: not valid UTF-8: {exc}")

        if RAW_TERMINATOR in content:
            sys.exit(
                f"error: {csv_path}: content contains the raw string terminator "
                f'"{RAW_TERMINATOR}" and cannot be embedded'
            )

        entries.append(f'  {{"{name}", R"{RAW_DELIM}({content}){RAW_DELIM}"}},')
        print(f"-- Embedding tuner config: {name}")

    count = len(csv_files)
    entries_block = "\n".join(entries)
    array_body = (entries_block + "\n") if entries_block else ""

    header = f"""\
/* Generated by tuner/embed_tuner_configs.py -- do not edit, do not commit. */
#ifndef RCCL_TUNER_EMBEDDED_CONFIGS_H_
#define RCCL_TUNER_EMBEDDED_CONFIGS_H_

/* {count} config(s) embedded from the source tree's tuner/ directory. */
struct RcclEmbeddedTunerConfig {{
  const char* name;
  const char* content;
}};

static const RcclEmbeddedTunerConfig kRcclEmbeddedTunerConfigs[] = {{
{array_body}  {{nullptr, nullptr}}, /* sentinel: array is never zero-length */
}};

#endif /* RCCL_TUNER_EMBEDDED_CONFIGS_H_ */
"""

    # Rewrite only on change so regeneration does not force a rebuild.
    old_header = ""
    if os.path.exists(out_file):
        with open(out_file, "r", encoding="utf-8") as f:
            old_header = f.read()

    if old_header != header:
        out_dir = os.path.dirname(out_file)
        if out_dir:
            os.makedirs(out_dir, exist_ok=True)
        with open(out_file, "w", encoding="utf-8") as f:
            f.write(header)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(f"usage: {sys.argv[0]} <tuner_dir> <out_file>")
    embed(tuner_dir=sys.argv[1], out_file=sys.argv[2])

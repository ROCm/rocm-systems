//! gfx1250 instructions decoded from AMD's machine-readable ISA, for words LLVM's disassembler rejects.
//!
//! LLVM's AMDGPU disassembler requires fields an instruction does not use to hold the values its own assembler writes
//! (for example `DIM`, `DMASK` and `VADDR4` of `tensor_load_to_lds`, or `OPSEL_HI` of
//! `v_wmma_f32_32x16x128_f4`). Code assembled by other tools leaves them zero, which the hardware ignores. The ISA
//! table identifies an instruction by its encoding's identifier bits, picks its variant (and so its length) by the
//! encoding conditions, and names its operands from the fields the ISA lists as operands, so unused fields never
//! matter. `isa_gfx1250.json` is generated by `scripts/gen_isa_table.py` from `amdgpu_isa_cdna5.xml`.

use std::collections::{HashMap, HashSet};
use std::sync::OnceLock;

use serde::Deserialize;
use serde_json::Value;

#[derive(Deserialize)]
struct RawEncoding {
    name: String,
    bits: u32,
    mask: String,
    ids: Vec<String>,
    fields: HashMap<String, Vec<(u32, u32)>>,
    conds: HashMap<String, Value>,
}

/// One operand of an instruction variant: field, operand type, size in bits, output, implicit.
type RawOperand = (String, String, u32, bool, bool);

#[derive(Deserialize)]
struct RawTable {
    encodings: Vec<RawEncoding>,
    names: Vec<String>,
    conditions: Vec<String>,
    operand_lists: Vec<Vec<RawOperand>>,
    /// `"<encoding>:<opcode>"` to variants `[name, encoding, condition, operand list]`.
    instructions: HashMap<String, Vec<(usize, usize, usize, usize)>>,
}

struct Encoding {
    name: String,
    bytes: usize,
    mask: u128,
    ids: HashSet<u128>,
    fields: HashMap<String, Vec<(u32, u32)>>,
    conds: HashMap<String, Value>,
}

struct Table {
    encodings: Vec<Encoding>,
    by_name: HashMap<String, usize>,
    raw: RawTable,
}

/// An instruction decoded from the ISA table.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Decoded {
    /// Lower-case ISA name, as LLVM spells mnemonics.
    pub name: String,
    pub len: usize,
    /// Operands in ISA order, registers spelled as LLVM does (`s[4:7]`, `ttmp9`, `v12`).
    pub operands: Vec<String>,
}

fn table() -> Option<&'static Table> {
    static TABLE: OnceLock<Option<Table>> = OnceLock::new();
    TABLE
        .get_or_init(|| {
            let raw: RawTable = serde_json::from_str(include_str!("isa_gfx1250.json")).ok()?;
            let encodings = raw
                .encodings
                .iter()
                .map(|e| {
                    Some(Encoding {
                        name: e.name.clone(),
                        bytes: e.bits as usize / 8,
                        mask: u128::from_str_radix(&e.mask, 16).ok()?,
                        ids: e
                            .ids
                            .iter()
                            .map(|i| u128::from_str_radix(i, 16).ok())
                            .collect::<Option<_>>()?,
                        fields: e.fields.clone(),
                        conds: e.conds.clone(),
                    })
                })
                .collect::<Option<Vec<_>>>()?;
            let by_name = encodings
                .iter()
                .enumerate()
                .map(|(i, e)| (e.name.clone(), i))
                .collect();
            Some(Table {
                encodings,
                by_name,
                raw,
            })
        })
        .as_ref()
}

fn extract(value: u128, ranges: &[(u32, u32)]) -> u128 {
    let mut out = 0;
    let mut shift = 0;
    for &(offset, count) in ranges {
        out |= ((value >> offset) & ((1u128 << count) - 1)) << shift;
        shift += count;
    }
    out
}

impl Table {
    /// Field `name` of encoding `enc` (conditions spell base encodings without the `ENC_` prefix).
    fn field(&self, enc: &str, name: &str) -> Option<&[(u32, u32)]> {
        [format!("ENC_{enc}"), enc.to_string()]
            .iter()
            .filter_map(|n| self.by_name.get(n))
            .find_map(|&i| self.encodings[i].fields.get(name).map(Vec::as_slice))
    }

    /// Evaluate a condition expression; `None` when it uses a form the table does not define.
    fn eval(&self, e: &Value, word: u128) -> Option<i128> {
        let items = e.as_array()?;
        let op = items.first()?.as_str()?;
        let arg = |i: usize| self.eval(items.get(i)?, word);
        let all = |want: bool| -> Option<i128> {
            for x in &items[1..] {
                if (self.eval(x, word)? != 0) != want {
                    return Some(!want as i128);
                }
            }
            Some(want as i128)
        };
        Some(match op {
            "lit" => items.get(1)?.as_i64()? as i128,
            "field" => extract(
                word,
                self.field(items.get(1)?.as_str()?, items.get(2)?.as_str()?)?,
            ) as i128,
            "==" => (arg(1)? == arg(2)?) as i128,
            "!=" => (arg(1)? != arg(2)?) as i128,
            "&&" => all(true)?,
            "||" => 1 - all(false)?,
            "!" => (arg(1)? == 0) as i128,
            ".within" | ".notwithin" => {
                let x = arg(1)?;
                let set = items.get(2)?.as_array()?;
                if set.first()?.as_str()? != "array" {
                    return None;
                }
                let mut hit = false;
                for v in &set[1..] {
                    hit |= self.eval(v, word)? == x;
                }
                (hit == (op == ".within")) as i128
            }
            _ => return None,
        })
    }

    fn render(&self, enc: &Encoding, word: u128, op: &RawOperand) -> Option<Option<String>> {
        let (field, ty, size, _, implicit) = op;
        if *implicit {
            return Some(match ty.as_str() {
                "OPR_EXEC" => Some("exec".into()),
                "OPR_VCC" => Some("vcc".into()),
                "OPR_SREG_M0" | "OPR_SDST_M0" => Some("m0".into()),
                _ => None,
            });
        }
        if field.is_empty() {
            return Some(None);
        }
        let value = extract(word, enc.fields.get(field)?) as u32;
        let regs = size.div_ceil(32).max(1);
        Some(Some(match ty.as_str() {
            "OPR_VGPR" => vgpr(value, regs),
            "OPR_SRC"
            | "OPR_SRC_VGPR"
            | "OPR_SRC_VGPR_OR_INLINE"
            | "OPR_SRC_SIMPLE"
            | "OPR_SRC_NOINLINE"
                if value >= 256 =>
            {
                vgpr(value - 256, regs)
            }
            "OPR_SRC"
            | "OPR_SRC_VGPR"
            | "OPR_SRC_VGPR_OR_INLINE"
            | "OPR_SRC_SIMPLE"
            | "OPR_SRC_NOINLINE"
            | "OPR_SSRC"
            | "OPR_SDST"
            | "OPR_SREG"
            | "OPR_SGPR"
            | "OPR_SDST_EXEC"
            | "OPR_SSRC_SPECIAL_SCC"
            | "OPR_SSRC_LANESEL"
            | "OPR_SSRC_BARRIER_ID"
            | "OPR_SREG_M0"
            | "OPR_SDST_M0" => scalar(value, regs),
            // Control flow is never decoded from the table: the analysis must see every branch.
            "OPR_LABEL" | "OPR_PC" => return None,
            _ => value.to_string(),
        }))
    }
}

fn vgpr(n: u32, regs: u32) -> String {
    if regs == 1 {
        format!("v{n}")
    } else {
        format!("v[{n}:{}]", n + regs - 1)
    }
}

/// A scalar source or destination operand code, spelled as LLVM does.
fn scalar(code: u32, regs: u32) -> String {
    let range = |name: &str, base: u32| {
        let n = code - base;
        if regs == 1 {
            format!("{name}{n}")
        } else {
            format!("{name}[{n}:{}]", n + regs - 1)
        }
    };
    match code {
        0..=105 => range("s", 0),
        106 => "vcc".into(),
        107 => "vcc_hi".into(),
        108..=123 => range("ttmp", 108),
        124 => "null".into(),
        125 => "m0".into(),
        126 => "exec".into(),
        127 => "exec_hi".into(),
        128..=192 => (code - 128).to_string(),
        193..=208 => format!("-{}", code - 192),
        _ => format!("src{code}"),
    }
}

/// Whether a condition tests a field of encoding `short` (a base encoding name without `ENC_`).
fn references(e: &Value, short: &str) -> bool {
    let Some(items) = e.as_array() else {
        return false;
    };
    if items.first().and_then(Value::as_str) == Some("field") {
        return items.get(1).and_then(Value::as_str) == Some(short);
    }
    items.iter().any(|x| references(x, short))
}

fn push(found: &mut Vec<Decoded>, name: String, len: usize, operands: Vec<String>) {
    let d = Decoded {
        name,
        len,
        operands,
    };
    if !found.contains(&d) {
        found.push(d);
    }
}

/// Decode the instruction at the start of `bytes`, if the ISA table identifies exactly one.
pub fn decode(bytes: &[u8]) -> Option<Decoded> {
    let t = table()?;
    let avail = bytes.len().min(16);
    let mut padded = [0u8; 16];
    padded[..avail].copy_from_slice(&bytes[..avail]);
    let word = u128::from_le_bytes(padded);
    let mut found: Vec<Decoded> = Vec::new();
    for base in t.encodings.iter().filter(|e| e.name.starts_with("ENC_")) {
        if base.bytes > avail {
            continue;
        }
        let low = word & (u128::MAX >> (128 - 8 * base.bytes));
        if !base.ids.contains(&(low & base.mask)) {
            continue;
        }
        let Some(opcode) = base.fields.get("OP").map(|r| extract(low, r)) else {
            continue;
        };
        let Some(variants) = t.raw.instructions.get(&format!("{}:{opcode}", base.name)) else {
            continue;
        };
        let mut listed = false;
        for &(name, enc, cond, ops) in variants {
            let target = &t.encodings[enc];
            if target.bytes > avail {
                continue;
            }
            let expr = target.conds.get(&t.raw.conditions[cond])?;
            if t.eval(expr, word)? == 0 {
                continue;
            }
            listed = true;
            let mut operands = Vec::new();
            for op in &t.raw.operand_lists[ops] {
                operands.extend(t.render(target, word, op)?);
            }
            push(
                &mut found,
                t.raw.names[name].to_lowercase(),
                target.bytes,
                operands,
            );
        }
        if listed {
            continue;
        }
        // The literal and DPP forms are not listed per instruction: they are encodings (`SOP2_INST_LITERAL`, ...)
        // whose conditions test the base encoding's fields, and they extend the base form by their extra dwords.
        let Some(&(name, _, _, ops)) = variants.first() else {
            continue;
        };
        let short = base.name.trim_start_matches("ENC_");
        for form in t.encodings.iter().filter(|e| !e.name.starts_with("ENC_")) {
            for expr in form.conds.values() {
                if !references(expr, short) || form.bytes > avail || t.eval(expr, word)? == 0 {
                    continue;
                }
                let mut operands = Vec::new();
                for op in &t.raw.operand_lists[ops] {
                    operands.extend(t.render(base, word, op)?);
                }
                push(
                    &mut found,
                    t.raw.names[name].to_lowercase(),
                    form.bytes,
                    operands,
                );
            }
        }
    }
    match found.as_slice() {
        [d] => Some(d.clone()),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn words(w: &[u32]) -> Vec<u8> {
        w.iter().flat_map(|x| x.to_le_bytes()).collect()
    }

    #[test]
    fn decodes_what_llvm_rejects_in_aiter_asm_kernels() {
        // tensor_load_to_lds with DIM, DMASK and VADDR4 zero, as AITER's f8gemm and f4gemm kernels encode it.
        let d = decode(&words(&[0xd0310000, 0x00200000, 0x7c7c2420, 0xbf800000])).unwrap();
        assert_eq!(d.name, "tensor_load_to_lds");
        assert_eq!(d.len, 12);
        assert_eq!(d.operands, ["s[32:35]", "s[36:43]", "null", "null"]);
        // v_wmma_f32_32x16x128_f4 with OPSEL_HI 3 and an inline-constant accumulator.
        let d = decode(&words(&[0xcc880064, 0x1a021108, 0xbf800000, 0xbf800000])).unwrap();
        assert_eq!(d.name, "v_wmma_f32_32x16x128_f4");
        assert_eq!(d.len, 8);
        assert_eq!(d.operands[0], "v[100:115]");
        assert!(d
            .operands
            .iter()
            .all(|o| !o.starts_with('s') && !o.starts_with("ttmp")));
    }

    #[test]
    fn agrees_with_llvm_where_llvm_decodes() {
        // s_and_b32 s15, ttmp6, 15
        let d = decode(&words(&[0x8b0f8f72])).unwrap();
        assert_eq!((d.name.as_str(), d.len), ("s_and_b32", 4));
        assert_eq!(d.operands, ["s15", "ttmp6", "15"]);
        // s_bfe_u32 s33, ttmp8, 0x50019: the literal makes it eight bytes.
        let d = decode(&words(&[0x9321ff74, 0x00050019])).unwrap();
        assert_eq!((d.name.as_str(), d.len), ("s_bfe_u32", 8));
        assert_eq!(&d.operands[..2], ["s33", "ttmp8"]);
    }

    #[test]
    fn refuses_branches_and_unknown_words() {
        assert!(
            decode(&words(&[0xbfa20003])).is_none(),
            "s_cbranch_scc1 is never table-decoded"
        );
        assert!(decode(&words(&[0xffffffff, 0xffffffff])).is_none());
        assert!(decode(&[]).is_none());
    }
}

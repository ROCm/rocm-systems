"""YAML metric equation formatter for rocprofiler-compute pre-commit hook."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any, List, Tuple

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from utils.equation_format import normalize_equation

# =============================================================================
# Configuration - Edit these to accommodate future YAML updates
# =============================================================================

# Metric library files, whose top-level keys are also kept sorted
METRIC_LIBRARY_PATTERN = "metric_library/gfx"

# INHERIT_KEY and REMOVE_TAG of src/utils/yaml_inherit_loader.py. They are repeated here
# because this hook runs with pip PyYAML only, and that module needs the vendored one.
INHERIT_KEY = "inherit"
REMOVE_TAG = "!remove"

# Path patterns that contain metric equations to check (substrings matched against path)
EQUATION_FILE_PATTERNS = [
    "analysis_configs/gfx",
    METRIC_LIBRARY_PATTERN,
]

# Path suffixes to exclude from equation checking
EQUATION_FILE_EXCLUDE_SUFFIXES = [
    "_template.yaml",
]

# Path patterns to skip entirely (substrings matched against path)
SKIP_FILE_PATTERNS = [
    "/build/",
    "profiling_config.yaml",
]

# YAML keys that contain metric equations ("formula" and "peak_empirical" in metric
# library files)
EQUATION_KEYS = {"value", "avg", "min", "max", "peak", "formula", "peak_empirical"}


def extract_metric_equations(
    data: dict[str, Any], path: str = ""
) -> list[tuple[str, str, str]]:
    """Extract (path, key, value) tuples for equation fields from YAML data."""
    equations = []

    if isinstance(data, dict):
        for key, value in data.items():
            current_path = f"{path}.{key}" if path else key
            if key in EQUATION_KEYS and isinstance(value, str):
                equations.append((current_path, key, value))
            elif isinstance(value, dict):
                equations.extend(extract_metric_equations(value, current_path))
            elif isinstance(value, list):
                for i, item in enumerate(value):
                    if isinstance(item, dict):
                        equations.extend(
                            extract_metric_equations(item, f"{current_path}[{i}]")
                        )
    return equations


def sort_top_level_keys(content: str) -> str:
    """Return content with its top-level blocks sorted by key, "inherit" first.

    A block is a top-level key line and the lines under it: indented lines and sequence
    items written at column 0. Comment and blank lines stay with the key that follows
    them, and a leading "---" stays first.
    """
    header = ""
    blocks: List[Tuple[str, str]] = []
    pending = ""
    for line in content.splitlines(keepends=True):
        if line.startswith("---") and not blocks:
            header += pending + line
            pending = ""
        elif line.startswith((" ", "\t", "-")) and blocks:
            key, text = blocks[-1]
            blocks[-1] = (key, text + pending + line)
            pending = ""
        elif not line.strip() or line.startswith("#"):
            pending += line
        else:
            blocks.append((line.split(":", 1)[0], pending + line))
            pending = ""
    ordered = sorted(blocks, key=lambda block: (block[0] != INHERIT_KEY, block[0]))
    if ordered == blocks:
        return content
    # A last block without a final newline must not run into the block after it.
    texts = [text if text.endswith("\n") else text + "\n" for _, text in ordered]
    return header + "".join(texts) + pending


def _should_check_equations(path: Path) -> bool:
    """Return True if the file contains metric equations to check."""
    path_str = str(path)
    for exclude_suffix in EQUATION_FILE_EXCLUDE_SUFFIXES:
        if path_str.endswith(exclude_suffix):
            return False
    for pattern in EQUATION_FILE_PATTERNS:
        if pattern in path_str:
            return True
    return False


def _should_skip_file(path: Path) -> bool:
    """Return True if the file should be skipped entirely."""
    path_str = str(path)
    for pattern in SKIP_FILE_PATTERNS:
        if pattern in path_str:
            return True
    try:
        with open(path, encoding="utf-8") as f:
            if "AUTOGENERATED" in f.readline().upper():
                return True
    except (OSError, UnicodeDecodeError):
        return True
    return False


class _EquationLoader(yaml.SafeLoader):
    """SafeLoader that accepts the metric library's REMOVE_TAG."""


_EquationLoader.add_constructor(REMOVE_TAG, lambda loader, node: None)


def _apply_fixes(content: str, equations: list[tuple[str, str, str]]) -> str:
    """Apply equation normalizations using regex to handle multi-line YAML."""
    result = content
    for _, _, original in equations:
        normalized = normalize_equation(original)
        if normalized != original:
            pattern = re.escape(original).replace(r"\ ", r"\s+")
            result = re.sub(pattern, normalized, result, count=1)
    return result


def _loads_the_same(content: str, rewritten: str) -> bool:
    """Return True if rewritten loads to the same data as content."""
    try:
        return yaml.load(rewritten, Loader=_EquationLoader) == yaml.load(
            content, Loader=_EquationLoader
        )
    except yaml.YAMLError:
        return False


def check_file(
    path: Path, fix: bool = False, show_diff: bool = False
) -> tuple[bool, list[str]]:
    """Check a YAML file for formatting issues. Returns (is_valid, issues)."""
    if _should_skip_file(path):
        return True, []

    try:
        with open(path, encoding="utf-8") as f:
            content = f.read()
        data = yaml.load(content, Loader=_EquationLoader)
    except (yaml.YAMLError, OSError) as e:
        return False, [f"Failed to parse YAML: {e}"]

    if data is None or not _should_check_equations(path):
        return True, []

    equations = extract_metric_equations(data)
    issues = []
    equations_to_fix = []

    for eq_path, key, value in equations:
        normalized = normalize_equation(value)
        if normalized != value:
            equations_to_fix.append((eq_path, key, value))
            issues.append(f"  {eq_path}: equation needs normalization")
            if show_diff:
                issues.append(f"    - {value}")
                issues.append(f"    + {normalized}")

    fixed = _apply_fixes(content, equations_to_fix)
    if METRIC_LIBRARY_PATTERN in str(path):
        ordered = sort_top_level_keys(fixed)
        if ordered != fixed and not _loads_the_same(fixed, ordered):
            return False, [
                "  top-level keys are not sorted, and sorting them changes what the "
                "file loads (an alias before its anchor?); sort them by hand"
            ]
        if ordered != fixed:
            issues.append("  top-level keys are not sorted")
            fixed = ordered

    if fix and fixed != content:
        with open(path, "w", encoding="utf-8") as f:
            f.write(fixed)
        return True, ["  Fixed:", *issues]

    return len(issues) == 0, issues


def main() -> int:
    parser = argparse.ArgumentParser(
        description="YAML metric equation formatter for rocprofiler-compute"
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="Check without modifying")
    mode.add_argument("--fix", action="store_true", help="Auto-fix in place")
    mode.add_argument("--diff", action="store_true", help="Show proposed changes")
    parser.add_argument("files", nargs="*", type=Path, help="Files to check")
    parser.add_argument("-v", "--verbose", action="store_true")

    args = parser.parse_args()
    files = args.files or [Path(line.strip()) for line in sys.stdin if line.strip()]

    if not files:
        print("No files to check")
        return 0

    all_valid = True
    total_issues = 0

    for file_path in files:
        if not file_path.exists() or file_path.suffix.lower() not in {".yaml", ".yml"}:
            continue

        is_valid, issues = check_file(file_path, fix=args.fix, show_diff=args.diff)

        if not is_valid:
            all_valid = False
            total_issues += len(issues)
            print(f"{file_path}:")
            for issue in issues:
                print(issue)
        elif args.verbose:
            print(f"{file_path}: OK")

    if not all_valid:
        print(f"\n{total_issues} formatting issue(s) found")
        return 1

    if args.verbose:
        print(f"\nAll {len(files)} files passed format checks")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Write the metric lock: what each metric library metric resolves to on each arch.

For every arch and metric, the lock lists the formula, unit and peaks after
inheritance, and the counters profile collects for the metric. A library edit thus
shows as a diff of metric_lock/ under every arch it reaches, with the counters it
adds or removes, and committing that diff confirms the edit was intended.
"""

from pathlib import Path
from typing import Any, Dict

from rocprof_compute_soc.metric_library import loader
from vendored import yaml

LOCK_DIR = Path(__file__).resolve().parent / "metric_lock"
# Metric fields the lock copies, in this order, when the metric has them.
LOCKED_FIELDS = ("formula", "unit", "peak", "peak_empirical")
HEADER = (
    "# Generated by tools/config_management/check_metric_config.py --fix;\n"
    "# do not edit. Review its diff: it is what a library edit changes on this arch.\n"
)


def arch_lock(metric_dir: Path, arch: str) -> Dict[str, Dict[str, Any]]:
    """Return arch's lock: each metric's locked fields and counters, by metric id.

    Args:
        metric_dir: The metric library tree.
        arch: A metric library arch, e.g. "gfx942" or "gfx115x".
    """
    library = loader.MetricLibrary.load(metric_dir, arch)
    lock = {}
    for metric_id, metric in sorted(library.metrics.items()):
        entry = {field: metric[field] for field in LOCKED_FIELDS if field in metric}
        entry["counters"] = sorted(library.get_counters_for_metrics([metric_id]))
        lock[metric_id] = entry
    return lock


def lock_text(lock: Dict[str, Dict[str, Any]]) -> str:
    """Return a lock as the text of its file, one line per field."""
    body = yaml.safe_dump(
        lock, sort_keys=False, default_flow_style=None, width=float("inf")
    )
    return HEADER + body


def write_lock(lock_dir: Path, metric_dir: Path) -> None:
    """Write every arch's lock file to lock_dir, replacing the lock files there."""
    lock_dir.mkdir(exist_ok=True)
    for path in lock_dir.glob("*.yaml"):
        path.unlink()
    for arch in loader.METRIC_LIBRARY_PARENT_ARCH:
        text = lock_text(arch_lock(metric_dir, arch))
        (lock_dir / f"{arch}.yaml").write_text(text, encoding="utf-8")

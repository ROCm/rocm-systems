"""Golden equivalence test: the metric library matches today's analysis configs.

For every arch with a metric library tree:
- every equation a row shows is a library formula, except DISPLAY_VARIANTS;
- every library formula is shown by some row;
- the library's counters equal detect_counters() with no filter;
- the built-in variables equal get_build_in_vars().

The reference is today's tree, read by the production loaders in the same run, so no
snapshot files are needed. Runs in ctest and as a pre-commit hook.
"""

import re
from pathlib import Path
from types import SimpleNamespace

import pytest

import config
from rocprof_compute_soc.soc_base import OmniSoC_Base
from tools.format_yaml import normalize_equation
from utils.metric_library import (
    METRIC_LIBRARY_PARENT_ARCH,
    default_metric_library_dir,
    load_metric_library,
)
from utils.mi_gpu_spec import mi_gpu_specs
from utils.utils_common import MEMBW_ANALYSIS_PANEL_ID, load_panel_configs
from utils.utils_counter_defs import get_build_in_vars

ANALYSIS_CONFIGS = (
    Path(config.rocprof_compute_home) / "rocprof_compute_soc" / "analysis_configs"
)
METRIC_LIBRARY = default_metric_library_dir()
ARCHS = [
    arch for arch in METRIC_LIBRARY_PARENT_ARCH if (METRIC_LIBRARY / arch).is_dir()
]
# Any arch of a canonical config arch gives the same gpu series.
SERIES_ARCH = {"gfx115x": "gfx1151"}
# A row's equation comes from the first of these columns it has.
MAIN_FORMS = ("avg", "value", "expr")
ROUND_RE = re.compile(r"^\s*ROUND\((.*),\s*\d+\s*\)\s*$", re.DOTALL)
# Rows showing a metric in another display form (positional id -> label): a Bytes/s
# scale (the library keeps GB/s) or the same equation rewritten.
_CDNA_DISPLAY_VARIANTS = {
    "3.1.16": "VL1_L2 Read BW",
    "3.1.17": "VL1_L2 Write BW",
    "3.1.18": "VL1_L2 Atomic BW",
    "3.1.21": "sL1D_L2 Read BW",
    "3.1.24": "IL1_L2 Read BW",
    "3.1.26": "L2-Fabric Read BW",
    "3.1.27": "L2-Fabric Write and Atomic BW",
    "4.1.9": "L2 Cache Bandwidth",
    "4.1.11": "LDS Bandwidth",
}
# Time in seconds (Bytes/s rows) and in nanoseconds (GB/s).
SECONDS_SCALE = "/(SUM(End_Timestamp-Start_Timestamp)/1e9)"
NANOSECONDS = "/SUM(End_Timestamp-Start_Timestamp)"
DISPLAY_VARIANTS = {"gfx908": _CDNA_DISPLAY_VARIANTS}


def gpu_series(arch):
    return mi_gpu_specs.get_gpu_series(SERIES_ARCH.get(arch, arch))


def comparable(equation):
    """Return equation in format_yaml.py form without display ROUND(); None if empty.

    Many analysis_configs rows are unformatted (format_yaml.py skips AUTOGENERATED).
    """
    if equation is None or str(equation) == "None":
        return None
    match = ROUND_RE.match(str(equation))
    return re.sub(
        r"\s+", "", normalize_equation(match.group(1) if match else str(equation))
    )


def in_gb_per_second(equation):
    """Rescale a Bytes/s form (time / 1e9) to GB/s."""
    return equation.replace(SECONDS_SCALE, NANOSECONDS)


def row_equations(arch):
    """Yield (positional id, label, equation) for each equation shown on arch."""
    panel_configs = load_panel_configs([str(ANALYSIS_CONFIGS / arch)])
    for panel in panel_configs.values():
        for source in panel["data source"]:
            table = source.get("metric_table")
            if table is None:
                continue
            rows = {
                k: v for k, v in table["metric"].items() if k != "placeholder_range"
            }
            for index, (label, row) in enumerate(rows.items()):
                legacy_id = f"{table['id'] // 100}.{table['id'] % 100}.{index}"
                forms = [form for form in MAIN_FORMS if form in row][:1] or list(row)
                for form in forms:
                    yield legacy_id, label, comparable(row[form])


def library_formulas(arch):
    library = load_metric_library(METRIC_LIBRARY, arch)
    return {
        comparable(metric["formula"])
        for metric in library.metrics.values()
        if metric["formula"] is not None
    }


def make_soc(arch, membw_analysis):
    args = SimpleNamespace(
        config_dir=ANALYSIS_CONFIGS,
        filter_blocks=[],
        membw_analysis=membw_analysis,
        roof_only=False,
        set_selected=None,
    )
    machine_specs = SimpleNamespace(
        gpu_arch=SERIES_ARCH.get(arch, arch),
        gpu_series=gpu_series(arch),
        l2_banks=16,
        num_xcd=1,
        rocminfo_lines=None,
    )
    soc = OmniSoC_Base(args, machine_specs)
    soc.set_arch(SERIES_ARCH.get(arch, arch))
    return soc


# =============================================================================
# Tests
# =============================================================================


@pytest.mark.parametrize("arch", ARCHS)
def test_every_row_equation_is_a_library_formula(arch: str) -> None:
    formulas = library_formulas(arch)
    variants = DISPLAY_VARIANTS.get(arch, {})
    missing = []
    for legacy_id, label, equation in row_equations(arch):
        if legacy_id in variants:
            assert label == variants[legacy_id], f"{legacy_id} is now {label!r}"
            continue
        if equation is not None and equation not in formulas:
            missing.append(f"{legacy_id} {label}: {equation}")
    assert missing == []


@pytest.mark.parametrize("arch", ARCHS)
def test_every_library_formula_is_shown(arch: str) -> None:
    variants = DISPLAY_VARIANTS.get(arch, {})
    shown = set()
    for legacy_id, _, equation in row_equations(arch):
        shown.add(equation)
        if legacy_id in variants and equation:
            shown.add(in_gb_per_second(equation))
    assert library_formulas(arch) - shown == set()


@pytest.mark.parametrize("arch", ARCHS)
def test_counters_match_with_no_filter(arch: str) -> None:
    has_membw_panel = any(
        (ANALYSIS_CONFIGS / arch).glob(f"{MEMBW_ANALYSIS_PANEL_ID}_*.yaml")
    )
    soc = make_soc(arch, membw_analysis=has_membw_panel)
    expected, _ = soc.detect_counters()
    library = load_metric_library(METRIC_LIBRARY, arch)
    actual = soc._expand_tcc_template_counters(
        library.get_counters_for_metrics(list(library.metrics), gpu_series(arch))
    )
    assert actual == expected


@pytest.mark.parametrize("arch", ARCHS)
def test_builtin_vars_match(arch: str) -> None:
    library = load_metric_library(METRIC_LIBRARY, arch)
    actual = {
        name: comparable(variable["formula"])
        for name, variable in library.variables.items()
    }
    expected = {
        name: comparable(formula)
        for name, formula in get_build_in_vars(gpu_series(arch)).items()
    }
    assert actual == expected


def test_every_arch_tree_is_compared() -> None:
    """Archs come from the tree, so a new arch is compared automatically."""
    assert ARCHS, f"no metric library tree under {METRIC_LIBRARY}"

#!/usr/bin/env bash
# Regenerates graph_scheduler_blob.h from graph_scheduler_kernel.hip.
# Compiles the scheduler kernels for each supported gfx target, unbundles the
# clang offload bundle down to the raw single-arch code object (ELF), and emits
# the embedded C byte arrays that rocdevice.cpp loads via
# hsa_code_object_reader_create_from_memory.
set -euo pipefail

ROCM="${ROCM_PATH:-/opt/rocm}"
HIPCC="$ROCM/bin/hipcc"
BUNDLER="$ROCM/llvm/bin/clang-offload-bundler"
HERE="$(cd "$(dirname "$0")" && pwd)"
SRC="$HERE/graph_scheduler_kernel.hip"
OUT="$HERE/graph_scheduler_blob.h"
ARCHES=(gfx942 gfx950)

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

emit_array() {
  # $1 = arch, $2 = raw ELF path
  local arch="$1" elf="$2"
  local name="graph_scheduler_${arch}_unbundled_hsaco"
  python3 - "$name" "$elf" <<'PY'
import sys
name, path = sys.argv[1], sys.argv[2]
data = open(path, 'rb').read()
out = [f"unsigned char {name}[] = {{"]
line = "  "
for i, b in enumerate(data):
    line += f"0x{b:02x}, "
    if (i % 12) == 11:
        out.append(line.rstrip())
        line = "  "
if line.strip():
    out.append(line.rstrip())
out.append("};")
out.append(f"unsigned int {name}_len = {len(data)};")
print("\n".join(out))
PY
}

{
  echo "// Auto-generated by gen_scheduler_blob.sh. Do not edit by hand."
  echo "// Regenerate after changing graph_scheduler_kernel.hip."
  echo
  for arch in "${ARCHES[@]}"; do
    echo ">> building $arch" >&2
    "$HIPCC" --genco --offload-arch="$arch" ${EXTRA_FLAGS:-} "$SRC" -o "$TMP/$arch.bundle" >&2
    "$BUNDLER" --type=o --unbundle \
      --input="$TMP/$arch.bundle" \
      --output="$TMP/$arch.hsaco" \
      --targets="hipv4-amdgcn-amd-amdhsa--$arch" >&2
    emit_array "$arch" "$TMP/$arch.hsaco"
    echo
  done
} > "$OUT"

echo "Wrote $OUT" >&2

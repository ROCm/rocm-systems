#!/usr/bin/env bash
# Regenerates graph_scheduler_source.h from graph_scheduler_kernel.hip.
#
# Unlike the prebuilt-blob approach (gen_scheduler_blob.sh), this embeds the
# kernel *source* as a C string. rocdevice.cpp compiles it at device-init time
# for the running GPU's ISA via comgr (see Device::compileGraphSchedulerSource),
# exactly like the blit kernels are compiled from BlitLinearSourceCode. That
# removes the manual per-arch blob regeneration and makes the GPU-resident graph
# scheduler work on any supported architecture, not just the baked ones.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
SRC="${1:-$HERE/graph_scheduler_kernel.hip}"
OUT="${2:-$HERE/graph_scheduler_source.h}"

{
  echo "// Auto-generated by gen_scheduler_source.sh. Do not edit by hand."
  echo "// Regenerate after changing graph_scheduler_kernel.hip."
  echo "#pragma once"
  echo "// Device-side GPU graph scheduler kernels, compiled at runtime via comgr."
  echo "// Included at file scope inside namespace amd::roc (see rocdevice.cpp)."
  echo "static const char GraphSchedulerSourceCode[] = R\"GRAPHSCHED("
  # comgr compiles HIP with -nogpuinc (no auto HIP headers), so define the HIP
  # attribute macros ourselves. The kernels use only compiler builtins
  # (__builtin_amdgcn_*, __atomic_*), never HIP runtime helpers, so these macros
  # are all that is needed. Guarded so a real HIP header include is harmless.
  echo "#ifndef __device__"
  echo "#define __device__ __attribute__((device))"
  echo "#endif"
  echo "#ifndef __global__"
  echo "#define __global__ __attribute__((global))"
  echo "#endif"
  echo "#ifndef __shared__"
  echo "#define __shared__ __attribute__((shared))"
  echo "#endif"
  echo "#ifndef __constant__"
  echo "#define __constant__ __attribute__((constant))"
  echo "#endif"
  echo "#ifndef __host__"
  echo "#define __host__ __attribute__((host))"
  echo "#endif"
  cat "$SRC"
  echo ")GRAPHSCHED\";"
} > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT") lines)" >&2

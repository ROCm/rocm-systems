"""
Embeds the blit kernel code objects in one header: a byte array per target and the table
roc::FindOfflineBlitProgram searches (BlitKernelElf, declared in rocm/rocblitelf.hpp).

Usage:
  gen_blit_elf.py <out.hpp> <tag> <elf> <wave64> <wgp> <preload> <gws> <images> [<tag> ...]
"""

import sys

FIELDS = 7


def main():
    args = sys.argv[2:]
    if len(sys.argv) < 2 + FIELDS or len(args) % FIELDS != 0:
        print(__doc__)
        sys.exit(1)

    arrays = []
    entries = []
    for i in range(0, len(args), FIELDS):
        tag, elf_path, wave64, wgp, preload, gws, images = args[i:i + FIELDS]
        with open(elf_path, "rb") as f:
            data = f.read()
        rows = []
        for j in range(0, len(data), 16):
            rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[j:j + 16]) + ",")
        arrays.append(f"alignas(8) const uint8_t kBlitElf_{tag}[] = {{\n" + "\n".join(rows) +
                      "\n};")
        flag = lambda v: "true" if v == "1" else "false"
        entries.append(f"    {{kBlitElf_{tag}, sizeof(kBlitElf_{tag}), {flag(wave64)}, "
                       f"{flag(wgp)}, {flag(preload)}, {flag(gws)}, {flag(images)}}},")

    out = (
        "// Generated by gen_blit_elf.py; do not edit.\n"
        "// Blit kernel code objects built offline, one per target.\n"
        "#pragma once\n\n"
        "namespace amd::roc {\n"
        "namespace {\n\n" + "\n\n".join(arrays) + "\n\n"
        "const BlitKernelElf kBlitKernelElfs[] = {\n" + "\n".join(entries) + "\n};\n\n"
        "}  // namespace\n"
        "}  // namespace amd::roc\n")
    with open(sys.argv[1], "w") as f:
        f.write(out)


if __name__ == "__main__":
    main()

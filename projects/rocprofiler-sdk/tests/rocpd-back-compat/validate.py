def test_otf2_no_graph_launch_locations(old_schema, output_root):
    """OTF2 trace must not contain 'HIP Graph Launch' locations for pre-latest schemas."""
    pytest.importorskip("otf2", reason="otf2 package not installed")

    # Check if the schema is 3.0.2 and newer, then call the present test instead
    if tuple(map(int, old_schema.split("."))) >= (3, 0, 2):
        print(
            f"Schema {old_schema} is newer than 3.0.2, calling test_otf2_graph_launch_locations_latest instead"
        )
        return test_otf2_graph_launch_locations_latest(output_root, old_schema)

    # Otherwise, check for the absence of the changes
    otf2_path = output_root / old_schema / "otf2" / "out_results.otf2"
    assert (
        otf2_path.exists()
    ), f"OTF2 output not found for schema {old_schema}: {otf2_path}"
    hip_graph_locs = [
        n for n in _otf2_location_names(otf2_path) if "HIP Graph Launch" in n
    ]
    assert not hip_graph_locs, (
        f"Unexpected 'HIP Graph Launch' OTF2 locations for schema {old_schema}: "
        f"{hip_graph_locs}"
    )



import csv
import json
import os

import pytest

from rocprofiler_sdk.pytest_utils import collapse_dict_list
from rocprofiler_sdk.pytest_utils.dotdict import dotdict


def pytest_addoption(parser):
    parser.addoption(
        "--json-input",
        action="store",
        help="Path to JSON output file generated by rocprofv3.",
    )
    parser.addoption(
        "--rocpd-input",
        action="store",
        help="Path to rocPD SQLite database generated by rocprofv3.",
    )
    parser.addoption(
        "--rocpd2csv-kernel-input",
        action="store",
        help="Path to kernel CSV generated by rocpd2csv.",
    )
    parser.addoption(
        "--rocpd2csv-agent-input",
        action="store",
        help="Path to agent CSV generated by rocpd2csv.",
    )
    parser.addoption(
        "--rocpd2csv-pc-sampling-input",
        action="store",
        help="Path to the PC sampling CSV generated by rocpd2csv.",
    )
    parser.addoption(
        "--rocpd-disasm-input",
        action="store",
        help="Path to a rocPD database produced with --pc-sampling-decode-instructions.",
    )


@pytest.fixture
def json_data(request):
    filename = request.config.getoption("--json-input")
    if not filename or not os.path.isfile(filename):
        pytest.skip("JSON input not found")

    with open(filename, "r", encoding="utf-8") as inp:
        return dotdict(collapse_dict_list(json.load(inp)))


@pytest.fixture
def rocpd_connection(request):
    filename = request.config.getoption("--rocpd-input")
    if not filename or not os.path.isfile(filename):
        pytest.skip("rocPD input database not found")

    from rocpd.importer import RocpdImportData

    with RocpdImportData(filename) as conn:
        yield conn



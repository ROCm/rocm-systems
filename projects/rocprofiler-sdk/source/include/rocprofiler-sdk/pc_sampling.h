    /// @brief A unit used to specify the sampling interval.
    /// @var min_interval
    /// @brief The highest possible frequency for generating samples
    /// (i.e. the smallest interval value accepted by
    /// ::rocprofiler_configure_pc_sampling_service_v2).
    /// @var max_interval

# Assemble every "=== name" section of fixtures.asm with LLVM's gfx950 assembler and
# write fixtures.inc (words + asm). Fixture authoring only: the tests never run LLVM.
#   usage: regen_fixtures.sh [path/to/llvm-mc] [path/to/llvm-objcopy]
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
mc=${1:-/opt/rocm/llvm/bin/llvm-mc}
objcopy=${2:-/opt/rocm/llvm/bin/llvm-objcopy}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
out="$here/fixtures.inc"
{
  echo "// Generated by regen_fixtures.sh from fixtures.asm. Do not edit."
  echo "// Assembler: $("$mc" --version | grep -m1 -i 'llvm version' | sed 's/^ *//')"
  echo "// Target: amdgcn-amd-amdhsa -mcpu=gfx950"
} > "$out"
names=$(grep -E '^=== ' "$here/fixtures.asm" | sed 's/^=== //')
for name in $names; do
  awk -v n="$name" '
    /^=== / { on = ($2 == n); next }
    on && !/^#/ && NF { print }
  ' "$here/fixtures.asm" > "$tmp/$name.s"
  "$mc" -triple=amdgcn-amd-amdhsa -mcpu=gfx950 -filetype=obj "$tmp/$name.s" -o "$tmp/$name.o"
  "$objcopy" -O binary --only-section=.text "$tmp/$name.o" "$tmp/$name.bin"
  {
    echo ""
    sed 's|^|// |' "$tmp/$name.s"
    printf 'inline const std::vector<uint32_t> k_%s = {' "$name"
    od -An -v -t x4 -w4 "$tmp/$name.bin" | awk '{printf "%s0x%s", (NR>1?", ":""), $1}'
    echo "};"
  } >> "$out"
done
echo "wrote $out"

# Collection


def collect(repo, base, head, tests_glob, targets):
    """Changed functions (with their before/after bodies) and skipped ones (with reasons).
    @p targets maps an llc target to how it is run ("native" or "proxy")."""
    revs = [base] if head == WORKTREE else [base, head]
    names = git(repo, "diff", "--name-only", *revs, "--", TEST_DIR).split()
    files = [n for n in names if n.endswith(".ll") and Path(n).match(tests_glob)]
    jobs, skipped, stats = (
        [],
        [],
        {
            "changed_test_files": len(files),
            "autogenerated": 0,
            "with_target_run": 0,
            "untested_targets": {},
        },
    )
    for path in files:
        old, new = show(repo, base, path), show(repo, head, path)
        if old is None or new is None:
            skipped.append({"file": path, "reason": "test added or removed"})
            continue
        if NOTE not in old.split("\n", 1)[0] or NOTE not in new.split("\n", 1)[0]:
            skipped.append(
                {"file": path, "reason": "not autogenerated by update_llc_test_checks"}
            )
            continue
        stats["autogenerated"] += 1
        first = new.split("\n", 1)[0] + old.split("\n", 1)[0]
        if "--filter" in first:
            skipped.append(
                {"file": path, "reason": "UTC_ARGS --filter: CHECK bodies are partial"}
            )
            continue
        old_runs, new_runs = run_lines(old), run_lines(new)
        runs = [r for r in new_runs if r in old_runs]
        parsed = [(i, r, parse_run(r)) for i, r in enumerate(runs)]
        parsed = [(i, r, p) for i, r, p in parsed if p]
        targeted = [(i, r, p) for i, r, p in parsed if p[0] in targets]
        if any(
            (parse_run(r) or [None])[0] in targets
            for r in new_runs + old_runs
            if r not in runs
        ):
            skipped.append(
                {"file": path, "reason": "a RUN line for a tested target changed"}
            )
        all_prefixes = sorted({p for _, _, (_, ps, _) in parsed for p in ps})
        ob, nb = check_bodies(old, all_prefixes), check_bodies(new, all_prefixes)
        new_fns = functions_ir(new)
        # Changed functions on targets this tool does not execute (reported as counts).
        for _, _, (target, prefixes, _) in parsed:
            if target in targets:
                continue
            for fn in new_fns:
                o = next((ob[p][fn] for p in prefixes if fn in ob.get(p, {})), None)
                n = next((nb[p][fn] for p in prefixes if fn in nb.get(p, {})), None)
                if o is not None and n is not None and o != n:
                    key = target or "generic (no -mcpu)"
                    stats["untested_targets"][key] = (
                        stats["untested_targets"].get(key, 0) + 1
                    )
        if not targeted:
            continue
        stats["with_target_run"] += 1
        for ri, run, (target, prefixes, llc) in targeted:
            for fn in new_fns:

                def body_of(bodies):
                    for p in prefixes:
                        if fn in bodies.get(p, {}):
                            return p, bodies[p][fn]
                    return None, None

                op, obody = body_of(ob)
                np_, nbody = body_of(nb)
                if obody is None or nbody is None:
                    if obody != nbody:
                        skipped.append(
                            {
                                "file": path,
                                "run": ri,
                                "function": fn,
                                "reason": "CHECK body missing on one side",
                            }
                        )
                    continue
                if obody == nbody:
                    continue
                entry = {
                    "file": path,
                    "run": ri,
                    "run_line": run,
                    "function": fn,
                    "prefix": np_,
                    "llc": llc,
                    "target": target,
                    "proxy": targets[target] == "proxy",
                }
                if ir_identity(old, fn) != ir_identity(new, fn):
                    skipped.append({**entry, "reason": "IR of the function changed"})
                    continue
                ou = [unescape_check(l) for l in obody]
                nu = [unescape_check(l) for l in nbody]
                if None in ou or None in nu:
                    skipped.append(
                        {**entry, "reason": "CHECK lines contain FileCheck patterns"}
                    )
                    continue
                define = new_fns[fn][0]
                cc, ret = signature(define)
                if cc and cc != "amdgpu_kernel":
                    skipped.append(
                        {**entry, "reason": f"calling convention {cc} not modelled"}
                    )
                    continue
                rv = 0 if cc == "amdgpu_kernel" else type_dwords(ret)
                notes = []
                if rv is None:
                    rv = 32
                    notes.append(
                        f"return type '{ret}' not sized: all 32 return VGPRs observed"
                    )
                elif ret in SUBDWORD or re.search(r"x (i16|half|bfloat)>$", ret):
                    notes.append(
                        "16-bit return: the high halves of return VGPRs are compared"
                    )
                jobs.append(
                    {
                        **entry,
                        "kind": "kernel" if cc == "amdgpu_kernel" else "function",
                        "return_type": ret,
                        "return_vgprs": rv,
                        "mode": function_mode(define, attribute_groups(new)),
                        "notes": notes,
                        "old_body": ou,
                        "new_body": nu,
                    }
                )
    return jobs, skipped, stats


# --------------------------------------------------------------------------------------
# Running


def slug(s):
    s = re.sub(r"[^\w.-]+", "_", s)
    return (
        s if len(s) < 80 else s[:60] + "_" + hashlib.sha1(s.encode()).hexdigest()[:10]
    )


def run_one(job, out, tool, llvm_bin, cases, seed):
    d = (
        out
        / "functions"
        / slug(Path(job["file"]).stem)
        / f"run{job['run']}-{slug(job['function'])}"
    )
    if d.exists():
        shutil.rmtree(d)
    d.mkdir(parents=True)
    old_body, new_body = job["old_body"], job["new_body"]
    if job["target"] in GFX9_OLD_CACHE_SYNTAX:
        old_body = [translate_cache_policy(l) for l in old_body]
        new_body = [translate_cache_policy(l) for l in new_body]
    (d / "before.s").write_text(synthesize(job["function"], old_body))
    (d / "after.s").write_text(synthesize(job["function"], new_body))
    row = {k: v for k, v in job.items() if k not in ("old_body", "new_body")}
    row["dir"] = str(d)
    argv = [
        str(tool),
        "analyze",
        "--old",
        str(d / "before.s"),
        "--new",
        str(d / "after.s"),
        "--kernel",
        job["function"],
        "--out",
        str(d / "case"),
        "--return-vgprs",
        str(job["return_vgprs"]),
        "--function-mode",
        hex(job["mode"]),
    ]
    if llvm_bin:
        argv += ["--llvm-bin", str(llvm_bin)]
    an = subprocess.run(argv, capture_output=True, text=True)
    (d / "analyze.log").write_text(an.stdout + an.stderr)
    row["analyze_exit"] = an.returncode
    if an.returncode:
        text = (an.stderr or an.stdout).strip()
        # A listing gfx950 cannot assemble (an instruction or register alignment another
        # target allows) is outside what can be executed, not a harness failure.
        row["status"] = "UNSUPPORTED" if "llvm-mc failed" in text else "ERROR"
        lines = [l for l in text.splitlines() if "error:" in l]
        row["detail"] = (
            lines[0].split("error:", 1)[1].strip() if lines else text[-400:]
        )[:300]
        return row
    te = subprocess.run(
        [
            str(tool),
            "test",
            "--case",
            str(d / "case"),
            "--cases",
            str(cases),
            "--seed",
            str(seed),
            "--no-case-log",
        ],
        capture_output=True,
        text=True,
    )
    (d / "test.log").write_text(te.stdout + te.stderr)
    row["test_exit"] = te.returncode
    try:
        res = json.loads((d / "case" / "results.json").read_text())
        case = json.loads((d / "case" / "case.json").read_text())
    except (OSError, ValueError) as e:
        row["status"] = "ERROR"
        row["detail"] = f"no results: {e}; {te.stderr.strip()[-300:]}"
        return row
    o = res["overall"]
    row["status"] = o["test_status"]
    row["contract"] = o["contract_status"]
    row["coverage"] = o["coverage_scope"]
    row["hunks"] = len(case.get("changes", []))
    row["unresolved"] = [f"{u['kind']}: {u['what']}" for u in res.get("unresolved", [])]
    row["regions"] = []
    for g in res.get("regions", []):
        r = {
            "id": g["region"],
            "status": g["test_status"],
            "contract": g["contract_status"],
            "valid": g.get("counts", {}).get("valid_pairs", 0),
        }
        if g.get("first_mismatch"):
            r["first_mismatch"] = g["first_mismatch"].get("detail", "")
        if g.get("expansion"):
            r["expansion"] = g["expansion"].get("resolution", "")
            if g["expansion"].get("resolved_by"):
                r["resolved_by"] = g["expansion"]["resolved_by"]
        if g.get("reason"):
            r["reason"] = g["reason"][:300]
        row["regions"].append(r)
    return row


def verdict(row):
    if row.get("status") == "ERROR":
        return "error"
    if row.get("status") == "LOCAL_MISMATCH":
        return "mismatch"
    if (
        row.get("status") in ("NO_MISMATCH_FOUND", "NO_SEMANTIC_DIFF")
        and row.get("coverage") == "COMPLETE_FOR_DECLARED_SCOPE"
    ):
        return "pass"
    return "inconclusive"


def report(out, meta, rows, skipped, stats):
    counts = {}
    for r in rows:
        counts[verdict(r)] = counts.get(verdict(r), 0) + 1
    lines = [
        f"# rj_isa_diff_pr: {meta['repo']} {meta['base'][:12]}..{meta['head'][:12]}",
        "",
        f"- changed test files under {TEST_DIR}: {stats['changed_test_files']} "
        f"({stats['autogenerated']} autogenerated by update_llc_test_checks, "
        f"{stats['with_target_run']} with a tested RUN line: "
        f"native {', '.join(t for t, k in meta['targets'].items() if k == 'native')}; "
        f"proxy {', '.join(t for t, k in meta['targets'].items() if k == 'proxy') or 'none'})",
        f"- changed functions compared: {len(rows)} "
        f"({sum(1 for r in rows if r.get('proxy'))} through a proxy target) — "
        + ", ".join(f"{v} {k}" for k, v in sorted(counts.items())),
        f"- changed functions skipped: {sum(1 for s in skipped if 'function' in s)}; "
        f"files skipped: {sum(1 for s in skipped if 'function' not in s)}",
        "- changed functions on targets not executed: "
        + (
            ", ".join(f"{t} {n}" for t, n in sorted(stats["untested_targets"].items()))
            or "none"
        ),
        "",
        "| verdict | test | run (target) | function | status | contract | regions (valid cases) |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in sorted(
        rows, key=lambda r: (verdict(r) == "pass", r["file"], r["run"], r["function"])
    ):
        regs = ", ".join(
            f"{g['id']} {g['status']}({g['valid']})"
            + (f" -> {g['resolved_by']} passes" if g.get("resolved_by") else "")
            for g in r.get("regions", [])
        )
        tgt = r["target"] + (" proxy" if r.get("proxy") else "")
        lines.append(
            f"| {verdict(r)} | {Path(r['file']).name} | {r['run']} ({tgt}) | {r['function']} | "
            f"{r.get('status', '')} | {r.get('contract', '')} | {regs} |"
        )
    detail = [r for r in rows if verdict(r) != "pass"]
    if detail:
        lines += ["", "## Not passing", ""]
        for r in detail:
            lines.append(
                f"- **{r['function']}** ({Path(r['file']).name}, run {r['run']}): "
                f"{r.get('status')} — {r['dir']}"
            )
            for g in r.get("regions", []):
                if g.get("first_mismatch") or g.get("reason"):
                    lines.append(
                        f"  - {g['id']}: {g.get('first_mismatch') or g.get('reason')}"
                        + (
                            f" [expansion {g['expansion']}]"
                            if g.get("expansion")
                            else ""
                        )
                    )
            for u in r.get("unresolved", [])[:6]:
                lines.append(f"  - unresolved: {u[:240]}")
            if r.get("detail"):
                lines.append(f"  - {r['detail'][:300]}")
            for n in r.get("notes", []):
                lines.append(f"  - note: {n}")
    if skipped:
        lines += ["", "## Skipped", ""]
        for s in skipped:
            where = Path(s["file"]).name + (
                f" run {s['run']} {s['function']}" if "function" in s else ""
            )
            lines.append(f"- {where}: {s['reason']}")
    text = "\n".join(lines) + "\n"
    (out / "report.md").write_text(text)
    return text, counts


def main(argv=None):
    ap = argparse.ArgumentParser(
        description=__doc__.split("\n\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__.split("\n\n", 1)[1],
    )
    ap.add_argument(
        "--repo", default=".", help="llvm-project git checkout (any worktree)"
    )
    ap.add_argument("--base", help="revision before the change")
    ap.add_argument(
        "--head",
        help="revision after the change, or WORKTREE for the checkout's "
        "files (e.g. tests just regenerated, not committed)",
    )
    ap.add_argument(
        "--pr", type=int, help="GitHub PR number: fetch it and use its merge base"
    )
    ap.add_argument("--remote", default="https://github.com/llvm/llvm-project.git")
    ap.add_argument("--out", required=True, help="output directory")
    ap.add_argument(
        "--tool",
        default=str(Path(__file__).resolve().parent / "rj_isa_diff"),
        help="rj_isa_diff executable",
    )
    ap.add_argument(
        "--llvm-bin", help="directory with llvm-mc and ld.lld (assembler only)"
    )
    ap.add_argument("--cases", type=int, default=5000, help="random cases per region")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    ap.add_argument("--tests", default="*.ll", help="glob on test paths (default *.ll)")
    ap.add_argument(
        "--proxy-targets",
        default=DEFAULT_PROXY_TARGETS,
        help="comma-separated llc targets whose listings are assembled and run as "
        "gfx950 (default %(default)s; empty: gfx950 only)",
    )
    ap.add_argument(
        "--list", action="store_true", help="only list what would be compared"
    )
    a = ap.parse_args(argv)
    try:
        if a.pr:
            base, head = resolve_pr(a.repo, a.pr, a.remote)
        elif a.base and a.head:
            base = git(a.repo, "rev-parse", a.base).strip()
            head = (
                a.head
                if a.head == WORKTREE
                else git(a.repo, "rev-parse", a.head).strip()
            )
        else:
            ap.error("give --base and --head, or --pr")
        out = Path(a.out)
        out.mkdir(parents=True, exist_ok=True)
        targets = {t: "native" for t in NATIVE_TARGETS}
        targets.update(
            {t: "proxy" for t in a.proxy_targets.split(",") if t and t not in targets}
        )
        jobs, skipped, stats = collect(a.repo, base, head, a.tests, targets)
    except RuntimeError as e:
        print(f"error: {e}", file=sys.stderr)
        return 3
    meta = {
        "repo": str(Path(a.repo).resolve()),
        "base": base,
        "head": head,
        "targets": targets,
        "cases": a.cases,
        "seed": a.seed,
        "tool": a.tool,
    }
    print(
        f"{base[:12]}..{head[:12]}: {stats['changed_test_files']} changed AMDGPU tests, "
        f"{stats['autogenerated']} autogenerated, {stats['with_target_run']} with a tested "
        f"RUN line; {len(jobs)} changed functions to compare, "
        f"{sum(1 for s in skipped if 'function' in s)} skipped",
        flush=True,
    )
    if a.list:
        for j in jobs:
            print(
                f"  {j['file']} run {j['run']} ({j['target']}) {j['function']} ({j['kind']}, "
                f"{len(j['old_body'])}/{len(j['new_body'])} lines)"
            )
        for s in skipped:
            print(f"  skip {s['file']} {s.get('function', '')}: {s['reason']}")
        return 0
    if not Path(a.tool).exists():
        print(
            f"error: rj_isa_diff not found at {a.tool} (pass --tool)", file=sys.stderr
        )
        return 3
    rows = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, a.jobs)) as pool:
        futs = {
            pool.submit(run_one, j, out, a.tool, a.llvm_bin, a.cases, a.seed): j
            for j in jobs
        }
        for f in concurrent.futures.as_completed(futs):
            r = f.result()
            rows.append(r)
            print(
                f"  {verdict(r):12s} {Path(r['file']).name} run {r['run']} {r['function']}: "
                f"{r.get('status')} {r.get('contract', '')}",
                flush=True,
            )
    (out / "summary.json").write_text(
        json.dumps(
            {"meta": meta, "stats": stats, "functions": rows, "skipped": skipped},
            indent=1,
        )
    )
    text, counts = report(out, meta, rows, skipped, stats)
    print(text)
    print(f"wrote {out / 'report.md'} and {out / 'summary.json'}")
    if counts.get("error"):
        return 3
    if counts.get("mismatch"):
        return 1
    if counts.get("inconclusive") or any("function" in s for s in skipped):
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())

def llc_function_bodies(asm, names):
    """{function: [lines]} from llc output: the lines from a function's label to its end
    (`.Lfunc_end` or `; -- End function`), without directives other than labels."""
    bodies, cur = {}, None
    for line in asm.splitlines():
        s = line.strip()
        lab = s.split(";")[0].strip()  # labels may carry a comment ("f: ; @f")
        if cur is None:
            if lab.endswith(":") and lab[:-1] in names:
                cur = lab[:-1]
                bodies[cur] = []
            continue
        if lab.startswith(".Lfunc_end") or s.startswith("; -- End function"):
            cur = None
            continue
        if not s or (lab.startswith(".") and not lab.endswith(":")):
            continue
        bodies[cur].append(s)
    return bodies


def escape_check(line):
    """update_llc_test_checks' escaping of '[[' and '{{' runs."""
    return re.sub(
        r"\[\[+|\{\{+",
        lambda m: "{{" + "".join("\\" + c for c in m.group(0)) + "}}",
        line,
    )


def llc_texts(text, path, llc_before, llc_after, targets):
    """Two synthetic autogenerated tests holding @p text's IR and, under one prefix per RUN
    line, the bodies llc_before and llc_after emit for it. (None, None) without a RUN line
    this tool runs."""
    names = set(functions_ir(text))
    stripped = re.sub(r"^(\s*;\s*)RUN:", r"\1ORIG-RUN:", text, flags=re.M)
    heads, checks = [[], []], [[], []]
    with tempfile.TemporaryDirectory(prefix="rj_isa_diff_llc_") as tmp:
        src = Path(tmp) / Path(path).name
        src.write_text(text)
        for i, run in enumerate(run_lines(text)):
            p = parse_run(run)
            if not p or p[0] not in targets:
                continue
            llc = p[2]
            if not re.match(r"^\s*(\S*/)?llc(\s|$)", llc):
                continue  # the input comes from another tool (opt | llc)
            if "%t" in llc or "%S" in llc or "%p" in llc:
                continue  # needs files earlier RUN lines make (split-file, opt > %t.bc)
            prefix = f"RJLLC{i}"
            for side, binary in enumerate((llc_before, llc_after)):
                cmd = re.sub(
                    r"^\s*(\S*/)?llc", lambda m: shlex.quote(str(binary)), llc, count=1
                )
                cmd = cmd.replace("%s", shlex.quote(str(src)))
                if " -o " not in f" {cmd} ":
                    cmd += " -o -"
                res = subprocess.run(
                    cmd, shell=True, capture_output=True, text=True, timeout=300
                )
                if res.returncode:
                    raise RuntimeError(
                        f"{binary} failed on {path} RUN {i}: {res.stderr[-300:]}"
                    )
                heads[side].append(
                    f"; RUN: {llc} < %s | FileCheck -check-prefixes={prefix} %s"
                )
                for fn, body in llc_function_bodies(res.stdout, names).items():
                    checks[side].append(f"; {prefix}-LABEL: {fn}:")
                    checks[side] += [
                        f"; {prefix}-NEXT: {escape_check(l)}" for l in body
                    ]
    if not heads[0]:
        return None, None
    return tuple(
        "; "
        + NOTE
        + "\n"
        + "\n".join(heads[s])
        + "\n"
        + "\n".join(checks[s])
        + "\n"
        + stripped
        for s in (0, 1)
    )


def corpus_files(paths):
    """The LLVM IR files named by @p paths: files, or directories searched recursively for
    .ll and .llir (Triton's cache) files."""
    out = []
    for p in map(Path, paths):
        out += sorted([*p.rglob("*.ll"), *p.rglob("*.llir")]) if p.is_dir() else [p]
    return out


def corpus_text(path, mcpus, args=""):
    """A corpus file's IR with one llc RUN line per CPU (its own RUN lines are kept);
    @p args are extra llc options (e.g. Triton's -O3)."""
    extra = f" {args.strip()}" if args.strip() else ""
    runs = "".join(
        f"; RUN: llc -mtriple=amdgcn-amd-amdhsa -mcpu={c}{extra} < %s | FileCheck %s\n"
        for c in mcpus
    )
    return runs + Path(path).read_text()


def all_test_names(repo, head, tests_glob):
    """Every AMDGPU CodeGen test at @p head matching the glob."""
    if head == WORKTREE:
        root = Path(repo)
        names = [str(p.relative_to(root)) for p in (root / TEST_DIR).rglob("*.ll")]
    else:
        names = git(repo, "ls-tree", "-r", "--name-only", head, "--", TEST_DIR).split()
    return sorted(n for n in names if n.endswith(".ll") and Path(n).match(tests_glob))


def collect(
    repo,
    base,
    head,
    tests_glob,
    targets,
    llc_pair=None,
    all_tests=False,
    corpus=(),
    corpus_mcpus=(),
    corpus_args="",
    jobs_n=8,
):
    """Changed functions (with their before/after bodies) and skipped ones (with reasons).
    @p targets maps an llc target to how it is run ("native" or "proxy"). With @p llc_pair,
    @p all_tests adds every test (not only changed ones) and @p corpus adds .ll files from
    outside the repository, compiled for @p corpus_mcpus."""
    revs = [base] if head == WORKTREE else [base, head]
    names = git(repo, "diff", "--name-only", *revs, "--", TEST_DIR).split()
    files = [n for n in names if n.endswith(".ll") and Path(n).match(tests_glob)]
    jobs, skipped, stats = (
        [],
        [],
        {
            "changed_test_files": len(files),
            "autogenerated": 0,
            "with_target_run": 0,
            "untested_targets": {},
            "comment_only": 0,
        },
    )
    # (path, old text, new text): changed tests first, then (with two llc builds) the
    # unchanged tests and the corpus, whose IR is the same on both sides.
    sources = [(path, show(repo, base, path), show(repo, head, path)) for path in files]
    extra_paths = set()
    if llc_pair and all_tests:
        extra = [
            n for n in all_test_names(repo, head, tests_glob) if n not in set(files)
        ]
        extra_paths.update(extra)
        stats["unchanged_tests"] = len(extra)
        sources += [(n, None, show(repo, head, n)) for n in extra]
    if llc_pair and corpus:
        cfiles = corpus_files(corpus)
        stats["corpus_files"] = len(cfiles)
        for f in cfiles:
            text = corpus_text(f, corpus_mcpus, corpus_args)
            sources.append((str(Path(f).resolve()), text, text))
            extra_paths.add(str(Path(f).resolve()))
    compiled = {}
    if llc_pair:
        # Both sides compile head's IR, one with each llc; the compiles run in parallel.
        def compile_one(item):
            path, _, new = item
            if new is None:
                return path, None
            try:
                return path, llc_texts(new, path, llc_pair[0], llc_pair[1], targets)
            except RuntimeError as e:
                return path, e

        with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, jobs_n)) as pool:
            compiled = dict(pool.map(compile_one, sources))
    for path, old, new in sources:
        if llc_pair and new is not None:
            res = compiled.get(path)
            if isinstance(res, RuntimeError):
                if path in extra_paths:
                    # Not part of the change: counted, not a skip.
                    stats["extra_llc_failed"] = stats.get("extra_llc_failed", 0) + 1
                    continue
                skipped.append(
                    {"file": path, "reason": f"llc failed: {str(res)[:200]}"}
                )
                continue
            old, new = res
            if old is None and path in extra_paths:
                # Not part of the change: nothing this tool runs, not a skip.
                stats["extra_without_tested_run"] = (
                    stats.get("extra_without_tested_run", 0) + 1
                )
                continue
            if old is None:
                skipped.append(
                    {"file": path, "reason": "no llc RUN line for a tested target"}
                )
                continue
        if old is None or new is None:
            skipped.append({"file": path, "reason": "test added or removed"})
            continue
        if NOTE not in old.split("\n", 1)[0] or NOTE not in new.split("\n", 1)[0]:
            skipped.append(
                {"file": path, "reason": "not autogenerated by update_llc_test_checks"}
            )
            continue
        stats["autogenerated"] += 1
        first = new.split("\n", 1)[0] + old.split("\n", 1)[0]
        if "--filter" in first:
            skipped.append(
                {"file": path, "reason": "UTC_ARGS --filter: CHECK bodies are partial"}
            )
            continue
        old_runs, new_runs = run_lines(old), run_lines(new)
        runs = [r for r in new_runs if r in old_runs]
        parsed = [(i, r, parse_run(r)) for i, r in enumerate(runs)]
        parsed = [(i, r, p) for i, r, p in parsed if p]
        # (index, label, (target, prefixes, llc), old prefixes, old llc)
        targeted = [(i, r, p, p[1], p[2]) for i, r, p in parsed if p[0] in targets]
        # A RUN line whose llc flags changed: compare it with its old form when the target,
        # check prefixes and wave size are the same and no FP-semantics flag changed.
        old_only = [r for r in old_runs if r not in runs]
        new_only = [r for r in new_runs if r not in runs]
        unpaired = 0
        for k, nr in enumerate(new_only):
            np_ = parse_run(nr)
            if not np_ or np_[0] not in targets:
                continue
            match = None
            for orun in old_only:
                op_ = parse_run(orun)
                if (
                    op_
                    and op_[0] == np_[0]
                    and sorted(op_[1]) == sorted(np_[1])
                    and run_wave_size(op_[0], run_features(op_[2]))
                    == run_wave_size(np_[0], run_features(np_[2]))
                    and not FP_FLAG.search(
                        " ".join(set(op_[2].split()) ^ set(np_[2].split()))
                    )
                ):
                    match = (orun, op_)
                    break
            if match is None:
                unpaired += 1
                continue
            old_only.remove(match[0])
            targeted.append((len(runs) + k, nr, np_, match[1][1], match[1][2]))
            stats["flag_changes"] = stats.get("flag_changes", 0) + 1
        unpaired += sum(1 for r in old_only if (parse_run(r) or [None])[0] in targets)
        if unpaired:
            skipped.append(
                {"file": path, "reason": "a RUN line for a tested target changed"}
            )
        all_prefixes = sorted(
            {p for _, _, (_, ps, _) in parsed for p in ps}
            | {p for t in targeted for p in t[2][1] + t[3]}
        )
        ob, nb = check_bodies(old, all_prefixes), check_bodies(new, all_prefixes)
        new_fns = functions_ir(new)
        # Changed functions on targets this tool does not execute (reported as counts).
        for _, _, (target, prefixes, _) in parsed:
            if target in targets:
                continue
            for fn in new_fns:
                o = next((ob[p][fn] for p in prefixes if fn in ob.get(p, {})), None)
                n = next((nb[p][fn] for p in prefixes if fn in nb.get(p, {})), None)
                if o is not None and n is not None and o != n:
                    key = target or "generic (no -mcpu)"
                    stats["untested_targets"][key] = (
                        stats["untested_targets"].get(key, 0) + 1
                    )
        if not targeted:
            continue
        stats["with_target_run"] += 1
        for ri, run, (target, prefixes, llc), old_prefixes, old_llc in targeted:
            for fn in new_fns:

                def body_of(bodies, prefs):
                    for p in prefs:
                        if fn in bodies.get(p, {}):
                            return p, bodies[p][fn]
                    return None, None

                op, obody = body_of(ob, old_prefixes)
                np_, nbody = body_of(nb, prefixes)
                if obody is None or nbody is None:
                    if obody != nbody:
                        skipped.append(
                            {
                                "file": path,
                                "run": ri,
                                "function": fn,
                                "reason": "CHECK body missing on one side",
                            }
                        )
                    continue
                if obody == nbody:
                    continue
                if code_lines(obody) == code_lines(nbody):
                    stats["comment_only"] += 1  # same code: nothing to test
                    continue
                entry = {
                    "file": path,
                    "run": ri,
                    "run_line": run,
                    "function": fn,
                    "prefix": np_,
                    "llc": llc,
                    "target": target,
                    "proxy": targets[target] == "proxy",
                }
                if old_llc != llc:
                    entry["old_llc"] = old_llc
                if ir_identity(old, fn) != ir_identity(new, fn):
                    skipped.append({**entry, "reason": "IR of the function changed"})
                    continue
                ou = [unescape_check(l) for l in obody]
                nu = [unescape_check(l) for l in nbody]
                if None in ou or None in nu:
                    skipped.append(
                        {**entry, "reason": "CHECK lines contain FileCheck patterns"}
                    )
                    continue
                define = new_fns[fn][0]
                cc, ret = signature(define)
                if cc and cc not in ("amdgpu_kernel", "amdgpu_gfx") + GRAPHICS_CC:
                    skipped.append(
                        {**entry, "reason": f"calling convention {cc} not modelled"}
                    )
                    continue
                kernel = cc == "amdgpu_kernel"
                shader = cc in GRAPHICS_CC
                ext = re.search(r"define\s+[^@]*\b(zeroext|signext)\b[^@]*@", define)
                shader_ret = shader_returns(ret, bool(ext)) if shader else None
                if shader and shader_ret is None:
                    skipped.append(
                        {**entry, "reason": f"shader return type '{ret}' not modelled"}
                    )
                    continue
                feats = run_features(llc)
                wave = run_wave_size(target, feats)
                run_as = target if targets[target] == "native" else PROXY_CPU
                if run_as in WAVE32_ONLY and wave != 32:
                    skipped.append({**entry, "reason": f"wave{wave} on {run_as}"})
                    continue
                rv = 0 if kernel else shader_ret[1] if shader else type_dwords(ret)
                notes = []
                if rv is None:
                    rv = 32
                    notes.append(
                        f"return type '{ret}' not sized: all 32 return VGPRs observed"
                    )
                masks = (
                    []
                    if kernel
                    else shader_ret[2] if shader else return_masks(define, ret)
                )
                # Defined VGPRs at the entry: kernels v0-v2 (workitem IDs), functions
                # their VGPR arguments; the rest is undefined until written.
                ev = 3 if kernel else argument_vgprs(define, 136 if shader else 32)
                if shader and ev is not None and cc == "amdgpu_cs":
                    ev = max(ev, 3)  # workitem IDs
                # Kernels: user (at most 16) and system (at most 5) SGPRs.
                es = 24 if kernel else argument_sgprs(define, new_fns[fn][1], target)
                if shader:
                    # User SGPRs, then the system SGPRs the hardware adds after them.
                    n = inreg_dwords(define)
                    es = None if n is None else min(n + 8, 106)
                if ev is None:
                    notes.append("argument types not sized: v0-v31 treated as defined")
                jobs.append(
                    {
                        **entry,
                        "kind": (
                            "kernel" if kernel else "shader" if shader else "function"
                        ),
                        "cc": (
                            "shader" if shader else "gfx" if cc == "amdgpu_gfx" else "c"
                        ),
                        "return_sgprs": shader_ret[0] if shader else 0,
                        "return_sgpr_masks": shader_ret[3] if shader else [],
                        "return_type": ret,
                        "return_vgprs": rv,
                        "return_masks": masks,
                        "entry_vgprs": ev,
                        "entry_sgprs": es,
                        "poison_kinds": poison_kinds(new, fn),
                        "mode": function_mode(
                            define, attribute_groups(new), run_as, shader
                        ),
                        "run_as": run_as,
                        "wave_size": wave,
                        "mattr": ",".join(f for f in feats if "wavefrontsize" not in f),
                        "old_mattr": ",".join(
                            f for f in run_features(old_llc) if "wavefrontsize" not in f
                        ),
                        "notes": notes,
                        "old_body": ou,
                        "new_body": nu,
                    }
                )
    return jobs, skipped, stats



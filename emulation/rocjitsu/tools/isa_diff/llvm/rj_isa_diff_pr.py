def git(repo, *args, check=True):
    p = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)
    if check and p.returncode:
        raise RuntimeError(f"git {' '.join(args)}: {p.stderr.strip()}")
    return p.stdout


WORKTREE = "WORKTREE"


def show(repo, rev, path):
    if rev == WORKTREE:
        f = Path(repo) / path
        return f.read_text(errors="replace") if f.exists() else None
    p = subprocess.run(
        ["git", "-C", str(repo), "show", f"{rev}:{path}"], capture_output=True
    )
    return p.stdout.decode("utf-8", "replace") if p.returncode == 0 else None


def resolve_pr(repo, pr, remote):
    """Fetch the PR head and the main branch (FETCH_HEAD only, no refs are written); the
    base is their merge base, as in the PR's diff on GitHub."""
    git(repo, "fetch", "--quiet", remote, f"pull/{pr}/head")
    head = git(repo, "rev-parse", "FETCH_HEAD").strip()
    git(repo, "fetch", "--quiet", remote, "main")
    main = git(repo, "rev-parse", "FETCH_HEAD").strip()
    base = git(repo, "merge-base", head, main).strip()
    return base, head



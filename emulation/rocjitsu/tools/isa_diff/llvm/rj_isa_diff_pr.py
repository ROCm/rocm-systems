# The simulator executes gfx950 (CDNA4). Listings for other GFX9 targets share its
# encodings: CDNA3 (gfx940-gfx942) also its syntax; older GFX9 targets (Vega, CDNA1/2) name
# the cache-policy bits glc/slc/scc, which gfx940 renamed sc0/nt/sc1 (same bits; no
# functional effect), so those names are translated. Proxy listings are assembled and
# executed as gfx950 and labelled "proxy"; instructions gfx950 lacks fail to assemble and
# are reported. Other targets differ in encoding and are only counted.

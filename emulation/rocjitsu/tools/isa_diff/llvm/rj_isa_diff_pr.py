# RUN lines and CHECK bodies


def run_lines(text):
    """RUN commands with continuations joined, in file order."""
    runs, cur = [], None
    for line in text.splitlines():
        m = re.match(r"^\s*;\s*RUN:(.*)$", line)
        if not m:
            if cur is not None:
                runs.append(cur)
                cur = None
            continue
        part = m.group(1).rstrip()
        cur = (cur + " " if cur is not None else "") + part.rstrip("\\").strip()
        if not part.endswith("\\"):
            runs.append(cur)
            cur = None
    if cur is not None:
        runs.append(cur)
    return [" ".join(r.split()) for r in runs]


def parse_run(run):
    """(target, prefixes, llc_args) for an `llc ... | FileCheck ...` RUN line, else None."""
    if "llc" not in run.split("|")[0] and " llc " not in f" {run} ":
        return None
    stages = [s.strip() for s in run.split("|")]
    llc = next((s for s in stages if re.search(r"(^|\s|/)llc(\s|$)", s)), None)
    fc = next((s for s in stages if re.search(r"(^|\s|/)FileCheck(\s|$)", s)), None)
    if not llc or not fc or "-filetype=obj" in llc or "--filetype=obj" in llc:
        return None
    toks = llc.split()
    target = None
    for i, t in enumerate(toks):
        v = None
        if re.match(r"^--?mcpu=", t):
            v = t.split("=", 1)[1]
        elif t in ("-mcpu", "--mcpu") and i + 1 < len(toks):
            v = toks[i + 1]
        if v:
            target = v
        m = re.match(r"^--?mtriple=amdgpu(\d+)\.(\w\w)-", t)
        if m and not target:
            target = f"gfx{m.group(1)}{m.group(2)}"
    prefixes = []
    ftoks = fc.split()
    for i, t in enumerate(ftoks):
        m = re.match(r"^--?check-prefix(es)?(?:=(.*))?$", t)
        if not m:
            continue
        val = (
            m.group(2)
            if m.group(2) is not None
            else (ftoks[i + 1] if i + 1 < len(ftoks) else "")
        )
        prefixes += [p for p in val.split(",") if p]
    return target, prefixes or ["CHECK"], llc


def check_bodies(text, prefixes):
    """{prefix: {function: [lines]}} from update_llc_test_checks output."""
    alt = "|".join(re.escape(p) for p in sorted(set(prefixes), key=len, reverse=True))
    rx = re.compile(rf"^\s*;\s*({alt})(-LABEL|-NEXT|-EMPTY)?:(.*)$")
    bodies = {}
    current = {}
    for line in text.splitlines():
        m = rx.match(line)
        if not m:
            continue
        prefix, suffix, rest = m.group(1), m.group(2), m.group(3)
        if suffix == "-LABEL":
            name = rest.strip()
            if name.endswith(":"):
                name = name[:-1]
            current[prefix] = name
            bodies.setdefault(prefix, {})[name] = []
            continue
        name = current.get(prefix)
        if name is None:
            continue
        bodies[prefix][name].append("" if suffix == "-EMPTY" else rest.strip())
    return bodies


ESCAPED = re.compile(r"\{\{(.*?)\}\}")


def unescape_check(line):
    """Undo update_llc_test_checks' escaping of '[[' / '{{' runs; None if the line holds a
    FileCheck pattern or variable (the asm cannot be rebuilt)."""

    def repl(m):
        lit = re.sub(r"\\(.)", r"\1", m.group(1))
        if not re.fullmatch(r"\[+|\{+", lit):
            raise ValueError
        return lit

    try:
        out = ESCAPED.sub(repl, line)
    except ValueError:
        return None
    if "[[" in ESCAPED.sub("", line) or "{{" in ESCAPED.sub("", line):
        return None
    return out



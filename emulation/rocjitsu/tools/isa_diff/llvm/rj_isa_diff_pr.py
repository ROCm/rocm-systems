"""rj_isa_diff_pr: test an LLVM change on the AMDGPU lit tests it updates, in one command.

An LLVM patch that changes AMDGPU code generation regenerates the CHECK lines of the
affected tests with utils/update_llc_test_checks.py. Those CHECK lines hold the complete
assembly of every test function, before the patch (base revision) and after it (head
revision). This driver reads both versions of each changed test from git, rebuilds the old
and new assembly of every function whose body changed, and runs `rj_isa_diff analyze` and
`rj_isa_diff test` on each pair. LLVM is neither built nor run; an assembler (llvm-mc and
ld.lld, e.g. from ROCm) turns the listings into code objects.

    rj_isa_diff_pr --repo ~/llvm-project --base BASE --head HEAD --out DIR
    rj_isa_diff_pr --repo ~/llvm-project --pr 237629 --out DIR   # fetches the PR
    rj_isa_diff_pr --repo . --base HEAD --head WORKTREE --out DIR  # uncommitted tests

A function is compared only when everything else is equal: the test is autogenerated
by update_llc_test_checks.py on both sides (without --filter), the RUN line is unchanged and
targets a GPU RocJITsu executes (CDNA1-4: gfx908, gfx90a, gfx940-gfx942, gfx950; RDNA1-4:
gfx1010-gfx1036, gfx1100-gfx1153, gfx1200/gfx1201; gfx1250/gfx1251), at the RUN line's
wave size and target features, or a proxy (Vega listings run as gfx908, labelled "proxy"),
the function's IR (body, attributes, referenced globals) is unchanged, and
its CHECK lines contain no FileCheck patterns. Every other changed function is listed with
the reason it was skipped. Callable functions get their return size and entry MODE from
the IR (`--return-vgprs`, `--function-mode`); kernels are tested as their body (the CHECK
lines carry no kernel descriptor).

Exit status: 0 every compared function passed and nothing changed was skipped; 1 a local
mismatch; 2 inconclusive, partial or skipped functions; 3 harness error.
"""


def generation(target):
    """GFX generation of a target name (gfx90a -> 9, gfx1100 -> 11), or 0."""
    if target in NATIVE_TARGETS:
        return NATIVE_TARGETS[target]
    m = re.match(r"^gfx(\d+)", target or "")
    if not m:
        return 0
    digits = m.group(1)
    return int(digits[0]) if len(target) == 6 else int(digits[:2])


def run_features(llc):
    """The -mattr features of an llc command, comma-joined, in order."""
    toks = llc.split()
    feats = []
    for i, t in enumerate(toks):
        m = re.match(r"^--?mattr=(.*)$", t)
        if m:
            feats += [f for f in m.group(1).split(",") if f]
        elif t in ("-mattr", "--mattr") and i + 1 < len(toks):
            feats += [f for f in toks[i + 1].split(",") if f]
    return feats


def run_wave_size(target, feats):
    """The wave size an llc RUN line compiles for: the last wavefrontsize feature, else the
    target's default (wave64 on GFX9, wave32 from GFX10)."""
    wave = 64 if generation(target) < 10 else 32
    for f in feats:
        m = re.match(r"^([+-])wavefrontsize(32|64)$", f)
        if m:
            size = int(m.group(2))
            wave = size if m.group(1) == "+" else (64 if size == 32 else 32)
    return wave


def parse_run(run):
    """(target, prefixes, llc_args) for an `llc ... | FileCheck ...` RUN line, else None."""
    if "llc" not in run.split("|")[0] and " llc " not in f" {run} ":
        return None
    stages = [s.strip() for s in run.split("|")]
    llc = next((s for s in stages if re.search(r"(^|\s|/)llc(\s|$)", s)), None)
    fc = next((s for s in stages if re.search(r"(^|\s|/)FileCheck(\s|$)", s)), None)
    if not llc or not fc or "-filetype=obj" in llc or "--filetype=obj" in llc:
        return None
    toks = llc.split()
    target = None
    for i, t in enumerate(toks):
        v = None
        if re.match(r"^--?mcpu=", t):
            v = t.split("=", 1)[1]
        elif t in ("-mcpu", "--mcpu") and i + 1 < len(toks):
            v = toks[i + 1]
        if v:
            target = v
        m = re.match(r"^--?mtriple=amdgpu(\d+)\.(\w\w)-", t)
        if m and not target:
            target = f"gfx{m.group(1)}{m.group(2)}"
    prefixes = []
    ftoks = fc.split()
    for i, t in enumerate(ftoks):
        m = re.match(r"^--?check-prefix(es)?(?:=(.*))?$", t)
        if not m:
            continue
        val = (
            m.group(2)
            if m.group(2) is not None
            else (ftoks[i + 1] if i + 1 < len(ftoks) else "")
        )
        prefixes += [p for p in val.split(",") if p]
    return target, prefixes or ["CHECK"], llc


def check_bodies(text, prefixes):
    """{prefix: {function: [lines]}} from update_llc_test_checks output."""
    alt = "|".join(re.escape(p) for p in sorted(set(prefixes), key=len, reverse=True))
    rx = re.compile(rf"^\s*;\s*({alt})(-LABEL|-NEXT|-EMPTY)?:(.*)$")
    bodies = {}
    current = {}
    for line in text.splitlines():
        m = rx.match(line)
        if not m:
            continue
        prefix, suffix, rest = m.group(1), m.group(2), m.group(3)
        if suffix == "-LABEL":
            name = rest.strip()
            if name.endswith(":"):
                name = name[:-1]
            current[prefix] = name
            bodies.setdefault(prefix, {})[name] = []
            continue
        name = current.get(prefix)
        if name is None:
            continue
        bodies[prefix][name].append("" if suffix == "-EMPTY" else rest.strip())
    return bodies


ESCAPED = re.compile(r"\{\{(.*?)\}\}")


def code_lines(body):
    """A CHECK body without what cannot change behaviour: comment lines, trailing comments
    and whitespace. Inline-asm blocks (;;#ASMSTART ... ;;#ASMEND) are kept whole: their
    comment text is what the block defines and uses."""
    out, in_asm = [], False
    for line in body:
        t = line.strip()
        if t == ";;#ASMSTART":
            in_asm = True
        if in_asm:
            out.append(" ".join(t.split()))
            if t == ";;#ASMEND":
                in_asm = False
            continue
        t = t.split(";", 1)[0].strip()
        if t:
            out.append(" ".join(t.split()))
    return out


def unescape_check(line):
    """Undo update_llc_test_checks' escaping of '[[' / '{{' runs; None if the line holds a
    FileCheck pattern or variable (the asm cannot be rebuilt)."""

    def repl(m):
        lit = re.sub(r"\\(.)", r"\1", m.group(1))
        if not re.fullmatch(r"\[+|\{+", lit):
            raise ValueError
        return lit

    try:
        out = ESCAPED.sub(repl, line)
    except ValueError:
        return None
    if "[[" in ESCAPED.sub("", line) or "{{" in ESCAPED.sub("", line):
        return None
    return out



SYMREF = re.compile(
    r"([A-Za-z_.$][\w.$]*)@(?:rel32|abs32|gotpcrel|gotpcrel32|rel64|abs64)"
)


def translate_cache_policy(line):
    """glc/slc/scc -> sc0/nt/sc1 on vector memory instructions (older GFX9 syntax)."""
    code = line.split(";")[0]
    if not MEMORY_MNEMONIC.match(code.strip()):
        return line
    rest = line[len(code) :]
    for old, new in (("glc", "sc0"), ("slc", "nt"), ("scc", "sc1")):
        code = re.sub(rf"(?<![\w.]){old}(?![\w.])", new, code)
    return code + rest


def synthesize(name, body):
    """A complete listing for one function from its CHECK body. Symbols the body refers to
    but does not define (callees, globals, constant pools) get placeholder data definitions,
    so the object links; instructions they patch stay relocated (and unsupported in a
    region)."""
    labels = set(re.findall(r"^\s*([A-Za-z_.$][\w.$]*):", "\n".join(body), re.M))
    refs = sorted(
        {m.group(1) for l in body for m in SYMREF.finditer(l.split(";")[0])}
        - labels
        - {name}
    )
    lines = [
        "\t.text",
        f"\t.globl\t{name}",
        "\t.p2align\t8",
        f"\t.type\t{name},@function",
        f"{name}:",
    ]
    lines += [
        l if l.endswith(":") and not l.startswith(";") else "\t" + l for l in body
    ]
    lines += [".Lrj_func_end:", f"\t.size\t{name}, .Lrj_func_end-{name}"]
    if refs:
        lines += ['\t.section\t.rodata,"a",@progbits', "\t.p2align\t4"]
        for r in refs:
            lines += [f"{r}:", "\t.zero\t16"]
    return "\n".join(lines) + "\n"



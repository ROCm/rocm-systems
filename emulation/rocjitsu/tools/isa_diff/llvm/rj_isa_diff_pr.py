def functions_ir(text):
    """{name: (define_line, body_without_comments)}."""
    out = {}
    for m in re.finditer(
        r"^define\b([^\n]*?)@(\"[^\"]+\"|[\w.$-]+)\s*\(([^\n]*)\n(.*?)^\}",
        text,
        re.S | re.M,
    ):
        name = m.group(2).strip('"')
        body = "\n".join(
            l for l in m.group(4).splitlines() if not l.lstrip().startswith(";")
        )
        out[name] = (m.group(0).splitlines()[0], body)
    return out


def attribute_groups(text):
    return {
        m.group(1): m.group(2)
        for m in re.finditer(r"^attributes #(\d+) = \{(.*)\}", text, re.M)
    }


def referenced_globals(text, body):
    names = set(re.findall(r"@([\w.$-]+)", body))
    defs = []
    for n in sorted(names):
        m = re.search(rf"^@{re.escape(n)}\s*=.*$", text, re.M)
        if m:
            defs.append(m.group(0))
        m = re.search(rf"^declare\b[^\n]*@{re.escape(n)}\(.*$", text, re.M)
        if m:
            defs.append(m.group(0))
    return defs


def ir_identity(text, name):
    fns = functions_ir(text)
    if name not in fns:
        return None
    define, body = fns[name]
    groups = attribute_groups(text)
    attrs = [f"#{g} = {groups.get(g, '?')}" for g in re.findall(r"#(\d+)", define)]
    return "\n".join(
        [define, body, *attrs, *referenced_globals(text, define + "\n" + body)]
    )


SCALAR_DWORDS = {
    "void": 0,
    "i1": 1,
    "i8": 1,
    "i16": 1,
    "i32": 1,
    "half": 1,
    "bfloat": 1,
    "float": 1,
    "i64": 2,
    "double": 2,
}
SUBDWORD = {"i1", "i8", "i16", "half", "bfloat"}


def type_dwords(t):
    """Return-value VGPRs of an IR type under the AMDGPU C calling convention, or None."""
    t = t.strip()
    if t in SCALAR_DWORDS:
        return SCALAR_DWORDS[t]
    m = re.fullmatch(
        r"[ib](\d+)", t
    )  # iN, and LLVM's byte types bN: promoted to dwords
    if m:
        return (int(m.group(1)) + 31) // 32
    m = re.fullmatch(r"ptr(?: addrspace\((\d+)\))?", t)
    if m:
        return 1 if m.group(1) in ("3", "5", "6") else 2
    m = re.fullmatch(r"<(\d+) x (.+)>", t)
    if m:
        n, el = int(m.group(1)), m.group(2).strip()
        if el in ("i16", "half", "bfloat"):
            return (n + 1) // 2
        if el == "i8":  # each element in its own register (promoted to i16)
            return n
        e = type_dwords(el)
        return None if e is None or el == "i1" else n * e
    m = re.fullmatch(r"\[(\d+) x (.+)\]", t)
    if m:
        e = type_dwords(m.group(2))
        return None if e is None else int(m.group(1)) * e
    m = re.fullmatch(r"\{(.*)\}", t)
    if m:
        total = 0
        depth, cur = 0, ""
        for ch in m.group(1) + ",":
            if ch in "<[{(":
                depth += 1
            elif ch in ">]})":
                depth -= 1
            if ch == "," and depth == 0:
                e = type_dwords(cur)
                if e is None:
                    return None
                total += e
                cur = ""
            else:
                cur += ch
        return total
    return None


def signature(define):
    """(calling convention, return type) from a define line."""
    m = re.match(r"define\s+(.*?)@", define)
    words = m.group(1).split() if m else []
    cc = next(
        (w for w in words if w.startswith("amdgpu_") or w in ("fastcc", "coldcc")), ""
    )
    skip = {
        "internal",
        "private",
        "hidden",
        "protected",
        "dso_local",
        "weak",
        "linkonce_odr",
        "weak_odr",
        "external",
        "noundef",
        "signext",
        "zeroext",
        "inreg",
        "nofpclass",
        "local_unnamed_addr",
        "unnamed_addr",
        cc,
    }
    rest = " ".join(w for w in words if w not in skip)
    rest = re.sub(
        r"\b(?:noundef|signext|zeroext|nonnull|nofpclass\([^)]*\)|range\([^)]*\)|"
        r"align \d+|dereferenceable\(\d+\))\s*",
        "",
        rest,
    ).strip()
    return cc, rest


def split_top(text):
    """Split on commas outside (), <>, [] and {}."""
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch in "(<[{":
            depth += 1
        elif ch in ")>]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


ARG_ATTR = re.compile(
    r"\b(noundef|signext|zeroext|nonnull|noalias|nocapture|readonly|readnone|writeonly|"
    r"returned|immarg|captures\([^)]*\)|nofpclass\([^)]*\)|range\([^)]*\)|align \d+|"
    r"dereferenceable(_or_null)?\(\d+\)|noundef)\s*"
)


def argument_vgprs(define):
    """VGPRs the non-inreg arguments occupy (v0..), or None if a type is not sized."""
    m = re.search(r"@[^(]+\((.*)\)[^)]*$", define)
    if not m:
        return None
    total = 0
    for arg in split_top(m.group(1)):
        if not arg or arg == "...":
            continue
        if re.search(r"\binreg\b", arg):
            continue  # SGPR argument
        if re.search(r"\b(byval|byref|sret|preallocated)\b", arg):
            return None
        t = ARG_ATTR.sub("", arg)
        t = re.sub(r"\s+%[\w.$-]+$", "", t).strip()
        n = type_dwords(t)
        if n is None:
            return None
        total += n
    return min(total, 32)


SPECIAL_INPUT = re.compile(
    r"@llvm\.amdgcn\.(dispatch\.ptr|queue\.ptr|implicitarg\.ptr|kernarg\.segment\.ptr|"
    r"dispatch\.id|workgroup\.id|lds\.kernel\.id)|\bcall\b(?![^\n]*(@llvm\.|\basm\b))|"
    r"\balloca\b"
)


def architected_flat_scratch(target):
    """gfx940-gfx950, GFX11 and GFX12 address scratch without the private segment buffer."""
    return (
        target in ("gfx940", "gfx941", "gfx942", "gfx950") or generation(target) >= 11
    )


def argument_sgprs(define, body, target):
    """SGPRs defined at a function's entry: its inreg arguments, after the special inputs
    and the private segment buffer (s0-s15) when it may use them: special-input
    intrinsics, calls, stack objects, or a target without architected flat scratch. None
    if an argument type is not sized."""
    m = re.search(r"@[^(]+\((.*)\)[^)]*$", define)
    if not m:
        return None
    total = 0
    for arg in split_top(m.group(1)):
        if not arg or not re.search(r"\binreg\b", arg):
            continue
        t = ARG_ATTR.sub("", arg.replace("inreg", ""))
        t = re.sub(r"\s+%[\w.$-]+$", "", t).strip()
        n = type_dwords(t)
        if n is None:
            return None
        total += n
    special = SPECIAL_INPUT.search(body) or not architected_flat_scratch(target)
    return min(total + (16 if special else 0), 30)


def return_masks(define, ret):
    """Observed bits of each return VGPR when the return type is narrower than its
    registers (no zeroext/signext): [] when every bit is defined."""
    m = re.match(r"define\s+(.*?)@", define)
    if m and re.search(r"\b(zeroext|signext)\b", m.group(1)):
        return []
    t = ret.strip()
    n = re.fullmatch(r"[ib](\d+)", t)
    if n and int(n.group(1)) % 32:
        bits = int(n.group(1))
        return [0xFFFFFFFF] * (bits // 32) + [(1 << (bits % 32)) - 1]
    if t in ("half", "bfloat"):
        return [0xFFFF]
    v = re.fullmatch(r"<(\d+) x (i16|half|bfloat)>", t)
    if v and int(v.group(1)) % 2:
        return [0xFFFFFFFF] * (int(v.group(1)) // 2) + [0xFFFF]
    v = re.fullmatch(r"<(\d+) x i8>", t)
    if v:  # one byte per register
        return [0xFF] * int(v.group(1))
    return []


# IR constructs whose poison/UB conditions --poison-filter can witness at machine level.
POISON_PATTERNS = [
    ("shift", r"=\s*(shl|lshr|ashr)\b"),
    ("exact", r"\b(lshr|ashr)\s+exact\b"),
    ("nsw", r"\bnsw\b"),
    ("nuw", r"\bnuw\b"),
    ("fptoint", r"=\s*fpto[su]i\b"),
    ("ctz", r"@llvm\.(ctlz|cttz)\.[\w.]+\([^)]*,\s*i1\s+true\s*\)"),
    ("disjoint", r"\bor\s+disjoint\b"),
    ("nnan", r"\b(nnan|fast)\b|nofpclass\([^)]*nan|\"no-nans-fp-math\"=\"true\""),
    ("ninf", r"\b(ninf|fast)\b|nofpclass\([^)]*inf|\"no-infs-fp-math\"=\"true\""),
]


def poison_kinds(text, name):
    """Poison-filter kinds the function's IR calls for (its body, signature and attribute
    groups)."""
    fns = functions_ir(text)
    if name not in fns:
        return []
    define, body = fns[name]
    groups = attribute_groups(text)
    attrs = " ".join(groups.get(g, "") for g in re.findall(r"#(\d+)", define))
    blob = define + "\n" + body + "\n" + attrs
    return [k for k, rx in POISON_PATTERNS if re.search(rx, blob)]


def denorm_bits(mode):
    """MODE denormal field (bit0 inputs kept, bit1 outputs kept) for an LLVM mode string."""
    flush = ("preservesign", "preserve-sign", "positivezero", "positive-zero")
    parts = [p.strip() for p in mode.replace(",", "|").split("|") if p.strip()]
    out = parts[0] if parts else "ieee"
    inp = parts[1] if len(parts) > 1 else out
    return (0 if inp in flush else 1) | (0 if out in flush else 2)


def function_mode(define, groups, target=None):
    """MODE at entry: denormal modes from the function's attributes, DX10_CLAMP and IEEE on
    (unless "amdgpu-ieee"="false"; GFX12 has neither bit)."""
    attrs = (
        " ".join(groups.get(g, "") for g in re.findall(r"#(\d+)", define))
        + " "
        + define
    )
    f32 = f64 = 3
    m = re.search(r"denormal_fpenv\(([^)]*)\)", attrs)
    if m:
        for item in m.group(1).split(","):
            item = item.strip()
            if item.startswith("float:"):
                f32 = denorm_bits(item[len("float:") :])
            elif item:
                f64 = f32 = denorm_bits(item)
        # A later "float:" overrides the default for f32 only.
        for item in m.group(1).split(","):
            if item.strip().startswith("float:"):
                f32 = denorm_bits(item.strip()[len("float:") :])
    m = re.search(r'"denormal-fp-math"="([^"]*)"', attrs)
    if m:
        f64 = f32 = denorm_bits(m.group(1))
    m = re.search(r'"denormal-fp-math-f32"="([^"]*)"', attrs)
    if m:
        f32 = denorm_bits(m.group(1))
    ieee = 0 if re.search(r'"amdgpu-ieee"="false"', attrs) else 1
    if generation(target) >= 12:
        return (f32 << 4) | (f64 << 6)
    return (f32 << 4) | (f64 << 6) | (1 << 8) | (ieee << 9)



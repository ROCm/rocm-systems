# IR: function text, attributes, return size, MODE


def functions_ir(text):
    """{name: (define_line, body_without_comments)}."""
    out = {}
    for m in re.finditer(
        r"^define\b([^\n]*?)@(\"[^\"]+\"|[\w.$-]+)\s*\(([^\n]*)\n(.*?)^\}",
        text,
        re.S | re.M,
    ):
        name = m.group(2).strip('"')
        body = "\n".join(
            l for l in m.group(4).splitlines() if not l.lstrip().startswith(";")
        )
        out[name] = (m.group(0).splitlines()[0], body)
    return out


def attribute_groups(text):
    return {
        m.group(1): m.group(2)
        for m in re.finditer(r"^attributes #(\d+) = \{(.*)\}", text, re.M)
    }


def referenced_globals(text, body):
    names = set(re.findall(r"@([\w.$-]+)", body))
    defs = []
    for n in sorted(names):
        m = re.search(rf"^@{re.escape(n)}\s*=.*$", text, re.M)
        if m:
            defs.append(m.group(0))
        m = re.search(rf"^declare\b[^\n]*@{re.escape(n)}\(.*$", text, re.M)
        if m:
            defs.append(m.group(0))
    return defs


META_DEF = re.compile(r"^!([A-Za-z_.][\w.$-]*|\d+)\s*=.*$", re.M)
META_REF = re.compile(r"!([A-Za-z_.][\w.$-]*|\d+)")


def metadata_closure(text, seeds):
    """Definitions of the metadata @p seeds reference, transitively (names without a
    definition, such as attachment kinds like !range, become '!name = ?')."""
    defs = {m.group(1): m.group(0) for m in META_DEF.finditer(text)}
    todo, seen, out = list(META_REF.findall(seeds)), set(), []
    while todo:
        n = todo.pop()
        if n in seen:
            continue
        seen.add(n)
        line = defs.get(n)
        out.append(line if line is not None else f"!{n} = ?")
        if line is not None:
            todo += META_REF.findall(line.split("=", 1)[1])
    return sorted(out)


def ir_identity(text, name):
    """Everything that decides a function's semantics: its text, the attribute groups it
    and its callees use (call-site attributes included), the globals and declarations it
    references, the metadata they reference (transitively), and module-level information
    (datalayout, triple, named metadata such as module flags, module asm)."""
    fns = functions_ir(text)
    if name not in fns:
        return None
    define, body = fns[name]
    refs = referenced_globals(text, define + "\n" + body)
    used = define + "\n" + body + "\n" + "\n".join(refs)
    groups = attribute_groups(text)
    attrs = [
        f"#{g} = {groups.get(g, '?')}" for g in sorted(set(re.findall(r"#(\d+)", used)))
    ]
    module = [
        l
        for l in text.splitlines()
        if re.match(r"^(target (datalayout|triple)|module asm|source_filename)\b", l)
    ]
    named = [m.group(0) for m in META_DEF.finditer(text) if not m.group(1)[0].isdigit()]
    meta = metadata_closure(text, used + "\n" + "\n".join(named))
    return "\n".join([define, body, *attrs, *refs, *module, *meta])


SCALAR_DWORDS = {
    "void": 0,
    "i1": 1,
    "i8": 1,
    "i16": 1,
    "i32": 1,
    "half": 1,
    "bfloat": 1,
    "float": 1,
    "i64": 2,
    "double": 2,
}
SUBDWORD = {"i1", "i8", "i16", "half", "bfloat"}


def type_dwords(t):
    """Return-value VGPRs of an IR type under the AMDGPU C calling convention, or None."""
    t = t.strip()
    if t in SCALAR_DWORDS:
        return SCALAR_DWORDS[t]
    m = re.fullmatch(
        r"[ib](\d+)", t
    )  # iN, and LLVM's byte types bN: promoted to dwords
    if m:
        return (int(m.group(1)) + 31) // 32
    m = re.fullmatch(r"ptr(?: addrspace\((\d+)\))?", t)
    if m:
        return 1 if m.group(1) in ("3", "5", "6") else 2
    m = re.fullmatch(r"<(\d+) x (.+)>", t)
    if m:
        n, el = int(m.group(1)), m.group(2).strip()
        if el in ("i16", "half", "bfloat"):
            return (n + 1) // 2
        if el == "i8":  # each element in its own register (promoted to i16)
            return n
        e = type_dwords(el)
        return None if e is None or el == "i1" else n * e
    m = re.fullmatch(r"\[(\d+) x (.+)\]", t)
    if m:
        e = type_dwords(m.group(2))
        return None if e is None else int(m.group(1)) * e
    m = re.fullmatch(r"\{(.*)\}", t)
    if m:
        total = 0
        depth, cur = 0, ""
        for ch in m.group(1) + ",":
            if ch in "<[{(":
                depth += 1
            elif ch in ">]})":
                depth -= 1
            if ch == "," and depth == 0:
                e = type_dwords(cur)
                if e is None:
                    return None
                total += e
                cur = ""
            else:
                cur += ch
        return total
    return None


# Graphics shader calling conventions (CC_SI_SHADER / RetCC_SI_Shader): inreg arguments in
# s0.., the others in v0..; integer return values in s0..s43, floating-point ones in v0..
# The listing returns to the shader epilog by falling off its end.
GRAPHICS_CC = (
    "amdgpu_ps",
    "amdgpu_vs",
    "amdgpu_gs",
    "amdgpu_hs",
    "amdgpu_es",
    "amdgpu_ls",
    "amdgpu_cs",
)


def shader_returns(ret, extended=False):
    """(return SGPRs, return VGPRs, VGPR masks, SGPR masks) of a shader's return type, or
    None. Narrow integers (i1/i8/i16) define only their bits unless @p extended
    (zeroext/signext)."""
    t = ret.strip()
    if t == "void":
        return 0, 0, [], []
    elems = split_top(t[1:-1]) if t.startswith("{") and t.endswith("}") else [t]
    sg, vg, masks, smasks = 0, 0, [], []

    def add(el):
        nonlocal sg, vg
        el = el.strip()
        m = re.fullmatch(r"<(\d+) x (.+)>", el)
        if m:
            n, e = int(m.group(1)), m.group(2).strip()
            if e in ("half", "bfloat"):  # packed pairs in VGPRs
                vg += (n + 1) // 2
                masks.extend([0xFFFFFFFF] * (n // 2) + ([0xFFFF] if n % 2 else []))
                return True
            if e == "i16":  # v2i16 in SGPRs
                sg += (n + 1) // 2
                smasks.extend([0xFFFFFFFF] * (n // 2) + ([0xFFFF] if n % 2 else []))
                return True
            return all(add(e) for _ in range(n))
        if el in ("i32", "i16", "i8", "i1"):
            sg += 1
            bits = {"i32": 32, "i16": 16, "i8": 8, "i1": 1}[el]
            smasks.append(0xFFFFFFFF if extended or bits == 32 else (1 << bits) - 1)
            return True
        if el == "i64":
            sg += 2
            smasks.extend([0xFFFFFFFF] * 2)
            return True
        if el == "float":
            vg += 1
            masks.append(0xFFFFFFFF)
            return True
        if el in ("half", "bfloat"):
            vg += 1
            masks.append(0xFFFF)
            return True
        if el == "double":
            vg += 2
            masks.extend([0xFFFFFFFF] * 2)
            return True
        return False

    if not all(add(e) for e in elems) or sg > 44 or vg > 136:
        return None
    return (
        sg,
        vg,
        masks if any(m != 0xFFFFFFFF for m in masks) else [],
        smasks if any(m != 0xFFFFFFFF for m in smasks) else [],
    )


def inreg_dwords(define):
    """Dwords of the inreg arguments, or None if a type is not sized."""
    m = re.search(r"@[^(]+\((.*)\)[^)]*$", define)
    if not m:
        return None
    total = 0
    for arg in split_top(m.group(1)):
        if not arg or not re.search(r"\binreg\b", arg):
            continue
        t = ARG_ATTR.sub("", arg.replace("inreg", ""))
        t = re.sub(r"\s+%[\w.$-]+$", "", t).strip()
        n = type_dwords(t)
        if n is None:
            return None
        total += n
    return total


def signature(define):
    """(calling convention, return type) from a define line."""
    m = re.match(r"define\s+(.*?)@", define)
    words = m.group(1).split() if m else []
    cc = next(
        (w for w in words if w.startswith("amdgpu_") or w in ("fastcc", "coldcc")), ""
    )
    skip = {
        "internal",
        "private",
        "hidden",
        "protected",
        "dso_local",
        "weak",
        "linkonce_odr",
        "weak_odr",
        "external",
        "noundef",
        "signext",
        "zeroext",
        "inreg",
        "nofpclass",
        "local_unnamed_addr",
        "unnamed_addr",
        cc,
    }
    rest = " ".join(w for w in words if w not in skip)
    rest = re.sub(
        r"\b(?:noundef|signext|zeroext|nonnull|nofpclass\([^)]*\)|range\([^)]*\)|"
        r"align \d+|dereferenceable\(\d+\))\s*",
        "",
        rest,
    ).strip()
    return cc, rest


def split_top(text):
    """Split on commas outside (), <>, [] and {}."""
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch in "(<[{":
            depth += 1
        elif ch in ")>]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


ARG_ATTR = re.compile(
    r"\b(noundef|signext|zeroext|nonnull|noalias|nocapture|readonly|readnone|writeonly|"
    r"returned|immarg|captures\([^)]*\)|nofpclass\([^)]*\)|range\([^)]*\)|align \d+|"
    r"dereferenceable(_or_null)?\(\d+\)|noundef)\s*"
)


def argument_vgprs(define, limit=32):
    """VGPRs the non-inreg arguments occupy (v0..), or None if a type is not sized."""
    m = re.search(r"@[^(]+\((.*)\)[^)]*$", define)
    if not m:
        return None
    total = 0
    for arg in split_top(m.group(1)):
        if not arg or arg == "...":
            continue
        if re.search(r"\binreg\b", arg):
            continue  # SGPR argument
        if re.search(r"\b(byval|byref|sret|preallocated)\b", arg):
            return None
        t = ARG_ATTR.sub("", arg)
        t = re.sub(r"\s+%[\w.$-]+$", "", t).strip()
        n = type_dwords(t)
        if n is None:
            return None
        total += n
    return min(total, limit)



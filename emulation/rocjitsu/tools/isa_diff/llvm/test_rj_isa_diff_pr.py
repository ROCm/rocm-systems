"""End-to-end test of rj_isa_diff_pr on a synthetic llvm-project history.

Builds a two-commit git repository holding one autogenerated-style AMDGPU test whose
CHECK lines change between the commits, runs the driver on it, and checks each function's
verdict: NaN equivalence, undefined values, a narrow return value, poison triage, and a
real difference.

    test_rj_isa_diff_pr.py --tool build/.../rj_isa_diff --driver build/.../rj_isa_diff_pr
                           [--llvm-bin /opt/rocm/llvm/bin]
"""

import argparse
import importlib.machinery
import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path

NOTE = (
    "; NOTE: Assertions have been autogenerated by utils/update_llc_test_checks.py "
    "UTC_ARGS: --version 5\n"
    "; RUN: llc -mtriple=amdgcn -mcpu=gfx950 < %s | FileCheck -check-prefixes=GFX950 %s\n\n"
)


def function(signature, name, body, ir):
    lines = [
        f"define {signature} {{",
        f"; GFX950-LABEL: {name}:",
        "; GFX950:       ; %bb.0:",
    ]
    lines += [
        f"; GFX950-NEXT:    {l}"
        for l in ["s_waitcnt vmcnt(0) expcnt(0) lgkmcnt(0)", *body]
    ]
    lines += [f"  {l}" for l in ir] + ["}", ""]
    return "\n".join(lines)


def gfx11_file(head, wave64):
    """A GFX11 test (gfx1100; wave64 through -mattr), compared natively."""
    attr = " -mattr=+wavefrontsize64" if wave64 else ""
    note = (
        "; NOTE: Assertions have been autogenerated by utils/update_llc_test_checks.py "
        "UTC_ARGS: --version 5\n"
        f"; RUN: llc -mtriple=amdgcn -mcpu=gfx1100{attr} < %s | FileCheck -check-prefixes=GFX11 %s\n\n"
    )

    def fn(signature, name, body, ir):
        lines = [
            f"define {signature} {{",
            f"; GFX11-LABEL: {name}:",
            "; GFX11:       ; %bb.0:",
        ]
        lines += [
            f"; GFX11-NEXT:    {l}"
            for l in ["s_waitcnt vmcnt(0) expcnt(0) lgkmcnt(0)", *body]
        ]
        return "\n".join(lines + [f"  {l}" for l in ir] + ["}", ""])

    ret = "s_setpc_b64 s[30:31]"
    store = ["v_mov_b32_e32 v4, 0", "global_store_b32 v4, v0, s[0:1]", ret]
    if wave64:
        fns = [
            # A real difference at wave64: add became sub.
            fn(
                "void @w64_bug(i32 %a, i32 %b, ptr addrspace(1) inreg %p)",
                "w64_bug",
                [
                    (
                        "v_sub_nc_u32_e32 v0, v0, v1"
                        if head
                        else "v_add_nc_u32_e32 v0, v0, v1"
                    )
                ]
                + store,
                [
                    "%s = add i32 %a, %b",
                    "store i32 %s, ptr addrspace(1) %p",
                    "ret void",
                ],
            )
        ]
    else:
        fns = [
            # fadd commutes; a wave32 select (vcc_lo) carries the NaN's provenance.
            fn(
                "void @w32_fsel(float %a, float %b, i32 %c, i32 %d, ptr addrspace(1) inreg %p)",
                "w32_fsel",
                [
                    "v_add_f32_e32 v0, v1, v0" if head else "v_add_f32_e32 v0, v0, v1",
                    "v_cmp_lt_u32_e32 vcc_lo, v2, v3",
                    "v_cndmask_b32_e32 v0, v2, v0, vcc_lo",
                ]
                + store,
                [
                    "%s = fadd float %a, %b",
                    "%k = icmp ult i32 %c, %d",
                    "%cf = bitcast i32 %c to float",
                    "%r = select i1 %k, float %s, float %cf",
                    "store float %r, ptr addrspace(1) %p",
                    "ret void",
                ],
            ),
            # A pixel shader returning i16 in s0: only the low 16 bits are defined, so
            # zero- and sign-extension are both right.
            fn(
                "amdgpu_ps i16 @ps_i16(i32 inreg %a)",
                "ps_i16",
                [
                    "s_sext_i32_i16 s0, s0" if head else "s_and_b32 s0, s0, 0xffff",
                    "; return to shader part epilog",
                ],
                ["%t = trunc i32 %a to i16", "ret i16 %t"],
            ),
            # A pixel shader returning a float in v0: add became sub.
            fn(
                "amdgpu_ps float @ps_bug(float %a, float %b)",
                "ps_bug",
                [
                    "v_sub_f32_e32 v0, v0, v1" if head else "v_add_f32_e32 v0, v0, v1",
                    "; return to shader part epilog",
                ],
                ["%s = fadd float %a, %b", "ret float %s"],
            ),
            # <4 x i8> returns one byte in each of v0-v3; the temporary is dead.
            fn(
                "<4 x i8> @i8vec_ret(i32 %a)",
                "i8vec_ret",
                [
                    "v_mov_b32_e32 v6, v0" if head else "v_mov_b32_e32 v5, v0",
                    "v_lshrrev_b32_e32 v1, 8, v0",
                    "v_lshrrev_b32_e32 v2, 16, v0",
                    "v_lshrrev_b32_e32 v3, 24, v0",
                    ret,
                ],
                ["%v = bitcast i32 %a to <4 x i8>", "ret <4 x i8> %v"],
            ),
        ]
    return note + "\n".join(fns)


def dup_file(head, wrong):
    """dup.ll: function dup_fn; at head commuted (equivalent) or turned into a sub."""
    note = (
        "; NOTE: Assertions have been autogenerated by utils/update_llc_test_checks.py "
        "UTC_ARGS: --version 5\n"
        "; RUN: llc -mtriple=amdgcn -mcpu=gfx950 < %s | FileCheck -check-prefixes=D %s\n\n"
    )
    op = (
        ("v_sub_u32_e32 v0, v0, v1" if wrong else "v_add_u32_e32 v0, v1, v0")
        if head
        else "v_add_u32_e32 v0, v0, v1"
    )
    body = ["s_waitcnt vmcnt(0) expcnt(0) lgkmcnt(0)", op, "s_setpc_b64 s[30:31]"]
    lines = [
        "define i32 @dup_fn(i32 %a, i32 %b) {",
        "; D-LABEL: dup_fn:",
        "; D:       ; %bb.0:",
    ]
    lines += [f"; D-NEXT:    {l}" for l in body]
    lines += ["  %s = add i32 %a, %b", "  ret i32 %s", "}", ""]
    return note + "\n".join(lines)


def flags_file(head):
    """A gfx950 test whose RUN line changes -O level between the revisions."""
    opt = "-O3" if head else "-O1"
    note = (
        "; NOTE: Assertions have been autogenerated by utils/update_llc_test_checks.py "
        "UTC_ARGS: --version 5\n"
        f"; RUN: llc -mtriple=amdgcn -mcpu=gfx950 {opt} < %s | FileCheck -check-prefixes=FL %s\n\n"
    )
    body = [
        "s_waitcnt vmcnt(0) expcnt(0) lgkmcnt(0)",
        "v_add_u32_e32 v0, v1, v0" if head else "v_add_u32_e32 v0, v0, v1",
        "s_setpc_b64 s[30:31]",
    ]
    lines = [
        "define i32 @flag_add(i32 %a, i32 %b) {",
        "; FL-LABEL: flag_add:",
        "; FL:       ; %bb.0:",
    ]
    lines += [f"; FL-NEXT:    {l}" for l in body]
    lines += ["  %s = add i32 %a, %b", "  ret i32 %s", "}", ""]
    return note + "\n".join(lines)


def store(op):
    return [
        op,
        "v_mov_b32_e32 v4, 0",
        "global_store_dword v4, v0, s[0:1]",
        "s_waitcnt vmcnt(0)",
        "s_setpc_b64 s[30:31]",
    ]


def test_file(head):
    """The test at the base (head=False) or head revision."""
    fns = [
        # fadd commutes: with two NaN inputs the hardware returns the first operand's NaN.
        function(
            "void @fadd_ab(float %a, float %b, ptr addrspace(1) inreg %p)",
            "fadd_ab",
            store("v_add_f32_e32 v0, v1, v0" if head else "v_add_f32_e32 v0, v0, v1"),
            [
                "%s = fadd float %a, %b",
                "store float %s, ptr addrspace(1) %p",
                "ret void",
            ],
        ),
        # The third element is undefined: old stores what v2 holds, new stores 0.
        function(
            "void @undef_elt(<2 x i32> %a, ptr addrspace(1) inreg %p)",
            "undef_elt",
            (["v_mov_b32_e32 v2, 0"] if head else [])
            + [
                "v_mov_b32_e32 v4, 0",
                "global_store_dwordx3 v4, v[0:2], s[0:1]",
                "s_waitcnt vmcnt(0)",
                "s_setpc_b64 s[30:31]",
            ],
            [
                "%v = shufflevector <2 x i32> %a, <2 x i32> poison, "
                "<3 x i32> <i32 0, i32 1, i32 poison>",
                "store <3 x i32> %v, ptr addrspace(1) %p",
                "ret void",
            ],
        ),
        # A half return: the high half of v0 is undefined.
        function(
            "half @half_ret(float %a)",
            "half_ret",
            ["v_cvt_f16_f32_e32 v0, v0"]
            + (["v_or_b32_e32 v0, 0x12340000, v0"] if head else [])
            + ["s_setpc_b64 s[30:31]"],
            ["%h = fptrunc float %a to half", "ret half %h"],
        ),
        # add nsw: a saturating add agrees with the wrapping one unless the add overflows.
        function(
            "void @nsw_add(i32 %a, i32 %b, ptr addrspace(1) inreg %p)",
            "nsw_add",
            store("v_add_i32 v0, v0, v1 clamp" if head else "v_add_u32_e32 v0, v0, v1"),
            [
                "%s = add nsw i32 %a, %b",
                "store i32 %s, ptr addrspace(1) %p",
                "ret void",
            ],
        ),
        # A NaN's bits flow through an integer operation before the store.
        function(
            "void @fadd_bits(float %a, float %b, ptr addrspace(1) inreg %p)",
            "fadd_bits",
            [
                "v_add_f32_e32 v0, v1, v0" if head else "v_add_f32_e32 v0, v0, v1",
                "v_and_b32_e32 v0, 0xffff, v0",
            ]
            + store("")[1:],
            [
                "%s = fadd float %a, %b",
                "%i = bitcast float %s to i32",
                "%m = and i32 %i, 65535",
                "store i32 %m, ptr addrspace(1) %p",
                "ret void",
            ],
        ),
        # An undefined scalar: the IR stores undef; the garbage SGPR was reallocated.
        function(
            "void @sgpr_undef(ptr addrspace(1) inreg %p)",
            "sgpr_undef",
            store("v_mov_b32_e32 v0, s41" if head else "v_mov_b32_e32 v0, s40"),
            ["store i32 undef, ptr addrspace(1) %p", "ret void"],
        ),
        # Only a comment changed (a block name): nothing to test.
        function(
            "void @comment_only(i32 %a, ptr addrspace(1) inreg %p)",
            "comment_only",
            store(
                "v_add_u32_e32 v0, 1, v0 ; head" if head else "v_add_u32_e32 v0, 1, v0"
            ),
            ["%s = add i32 %a, 1", "store i32 %s, ptr addrspace(1) %p", "ret void"],
        ),
        # u is undefined: old stores (u & 1) * 3 (0 or 3), new stores 1. Per-bit masking
        # accepts it, so it is reported as pass-masked, not pass.
        function(
            "void @undef_and3(ptr addrspace(1) inreg %p)",
            "undef_and3",
            (
                store("v_mov_b32_e32 v0, 1")
                if head
                else ["v_and_b32_e32 v0, 1, v0"] + store("v_mul_u32_u24_e32 v0, 3, v0")
            ),
            [
                "%u = freeze i32 poison",
                "%a = and i32 %u, 1",
                "%m = mul i32 %a, 3",
                "store i32 %m, ptr addrspace(1) %p",
                "ret void",
            ],
        ),
        # The IR is the same text, but the !range it loads under changed: not compared.
        function(
            "void @range_md(ptr addrspace(1) inreg %p)",
            "range_md",
            store("v_mov_b32_e32 v0, 7" if head else "v_mov_b32_e32 v0, 3"),
            [
                "%v = load i32, ptr addrspace(1) %p, !range !0",
                "store i32 %v, ptr addrspace(1) %p",
                "ret void",
            ],
        ),
        # A shift by y & 31 (never poison in the IR; llc drops the AND, the hardware masks
        # the amount). Head adds bit 5 of the amount: wrong for every y with bit 5 set. The
        # shift filter must not explain this away: the IR has no poison shift.
        function(
            "void @masked_shift(i32 %x, i32 %y, ptr addrspace(1) inreg %p)",
            "masked_shift",
            (
                [
                    "v_lshlrev_b32_e32 v0, v1, v0",
                    "v_lshrrev_b32_e32 v2, 5, v1",
                    "v_and_b32_e32 v2, 1, v2",
                    "v_xor_b32_e32 v0, v0, v2",
                ]
                if head
                else ["v_lshlrev_b32_e32 v0, v1, v0"]
            )
            + store("v_mov_b32_e32 v0, v0")[1:],
            [
                "%n = and i32 %y, 31",
                "%r = shl i32 %x, %n",
                "store i32 %r, ptr addrspace(1) %p",
                "ret void",
            ],
        ),
        # A real difference: add became sub.
        function(
            "void @real_bug(i32 %a, i32 %b, ptr addrspace(1) inreg %p)",
            "real_bug",
            store("v_sub_u32_e32 v0, v0, v1" if head else "v_add_u32_e32 v0, v0, v1"),
            ["%s = add i32 %a, %b", "store i32 %s, ptr addrspace(1) %p", "ret void"],
        ),
    ]
    meta = "!0 = !{i32 0, i32 8}\n" if head else "!0 = !{i32 0, i32 4}\n"
    return NOTE + "\n".join(fns) + "\n" + meta


def git(repo, *args):
    subprocess.run(
        ["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@t", *args],
        check=True,
        capture_output=True,
    )


def run(driver, repo, out, tool, llvm_bin, *extra):
    argv = [
        sys.executable,
        str(driver),
        "--repo",
        str(repo),
        "--base",
        "HEAD~1",
        "--head",
        "HEAD",
        "--out",
        str(out),
        "--tool",
        str(tool),
        "--cases",
        "300",
        "--jobs",
        "4",
        *extra,
    ]
    if llvm_bin:
        argv += ["--llvm-bin", llvm_bin]
    p = subprocess.run(argv, capture_output=True, text=True)
    summary = json.loads((out / "summary.json").read_text())
    return (
        p.returncode,
        {f["function"]: f for f in summary["functions"]},
        p.stdout + p.stderr,
    )


def load_driver(path):
    """The driver as a module (it has no .py suffix in the build tree), for verdict()."""
    loader = importlib.machinery.SourceFileLoader("rj_isa_diff_pr", str(path))
    module = importlib.util.module_from_spec(
        importlib.util.spec_from_loader(loader.name, loader)
    )
    loader.exec_module(module)
    return module


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tool", required=True)
    ap.add_argument("--driver", required=True)
    ap.add_argument("--llvm-bin")
    a = ap.parse_args()
    failures = []
    with tempfile.TemporaryDirectory(prefix="rj_isa_diff_pr_test_") as tmp:
        repo = Path(tmp) / "llvm-project"
        test = repo / "llvm/test/CodeGen/AMDGPU/rj_selftest.ll"
        test.parent.mkdir(parents=True)
        git(repo, "init", "-q")
        w32 = test.parent / "rj_selftest_w32.ll"
        w64 = test.parent / "rj_selftest_w64.ll"
        flags = test.parent / "rj_selftest_flags.ll"
        flags.write_text(flags_file(False))
        # Two tests named dup.ll in different directories, with the same function: one
        # equivalent, one wrong. Each needs its own result directory.
        dups = [test.parent / "dupa" / "dup.ll", test.parent / "dupb" / "dup.ll"]
        for k, p in enumerate(dups):
            p.parent.mkdir()
            p.write_text(dup_file(False, k == 1))
        test.write_text(test_file(head=False))
        w32.write_text(gfx11_file(False, False))
        w64.write_text(gfx11_file(False, True))
        git(repo, "add", ".")
        git(repo, "commit", "-q", "-m", "base")
        test.write_text(test_file(head=True))
        w32.write_text(gfx11_file(True, False))
        w64.write_text(gfx11_file(True, True))
        flags.write_text(flags_file(True))
        for k, p in enumerate(dups):
            p.write_text(dup_file(True, k == 1))
        git(repo, "commit", "-q", "-am", "head")

        code, rows, log = run(a.driver, repo, Path(tmp) / "out", a.tool, a.llvm_bin)
        drv = load_driver(a.driver)
        for body, want_poison in (
            ("%n = and i32 %y, 31\n%r = shl i32 %x, %n", False),
            ("%r = lshr exact i64 %x, 63", False),
            ("%n = and i32 %y, 32\n%r = ashr i32 %x, %n", True),
            ("%r = shl i32 %x, %y", True),
            ("%r = shl i32 %x, 32", True),
            ("%r = shl <2 x i32> %x, splat (i32 1)", True),
        ):
            if drv.shift_may_be_poison(body) != want_poison:
                failures.append(f"shift_may_be_poison({body!r}) != {want_poison}")
        passing = [
            {"status": "NO_MISMATCH_FOUND", "coverage": "COMPLETE_FOR_DECLARED_SCOPE"}
        ]
        for sk, stats_in, want_status in (
            ([], {}, "PASS"),
            ([], {"extra_llc_failed": 1}, "INCOMPLETE"),
            (
                [{"file": "x.ll", "reason": "llc failed: both llc builds"}],
                {},
                "INCOMPLETE",
            ),
        ):
            got = drv.overall_status(passing, sk, stats_in)[0]
            if got != want_status:
                failures.append(
                    f"overall_status(pass, {sk}, {stats_in}) = {got}, expected {want_status}"
                )
        stderr = (
            "warning: codegen with no subarch in the target triple is deprecated\n"
            "intrinsic has incorrect number of args. Expected 9, but got 10\n"
            "LLVM ERROR: Broken module found, compilation aborted!\n"
            "Stack dump:\n0.\tProgram arguments: llc\n #0 0x1 llvm::foo\n"
        )
        want = (
            "LLVM ERROR: Broken module found, compilation aborted! | "
            "intrinsic has incorrect number of args. Expected 9, but got 10"
        )
        if drv.llc_error(stderr) != want:
            failures.append(f"llc_error: {drv.llc_error(stderr)!r}")
        # Nothing compared but a requested file failed to compile: incomplete, not
        # "nothing applicable".
        got = drv.overall_status(
            [], [{"file": "x.ll", "reason": "llc failed: llc after only"}], {}
        )[0]
        if got != "INCOMPLETE":
            failures.append(f"overall_status with only an llc failure = {got}")
        want = {
            "fadd_ab": "pass",
            "undef_elt": "pass",  # old stores the undefined value itself: exact
            "half_ret": "pass",
            "nsw_add": "mismatch",  # poison triage is a hint, not a verdict
            "masked_shift": "mismatch",
            "fadd_bits": "pass",
            "sgpr_undef": "pass-masked",
            "undef_and3": "pass-masked",
            "real_bug": "mismatch",
            "w32_fsel": "pass",
            "i8vec_ret": "pass",
            "w64_bug": "mismatch",
            "ps_i16": "pass",
            "ps_bug": "mismatch",
            "flag_add": "pass",
        }
        for fn, v in want.items():
            got = drv.verdict(rows[fn]) if fn in rows else "missing"
            if got != v:
                failures.append(
                    f"{fn}: verdict {got}, expected {v}: {json.dumps(rows.get(fn))[:600]}"
                )
        if "comment_only" in rows:
            failures.append("comment_only was tested; its code did not change")
        stats = json.loads((Path(tmp) / "out" / "summary.json").read_text())["stats"]
        if stats.get("flag_changes") != 1:
            failures.append(
                f"flag-change RUN pairs {stats.get('flag_changes')}, expected 1"
            )
        if stats.get("comment_only") != 1:
            failures.append(
                f"comment-only count {stats.get('comment_only')}, expected 1"
            )
        if rows.get("half_ret", {}).get("return_masks") != [0xFFFF]:
            failures.append(
                f"half_ret return masks {rows.get('half_ret', {}).get('return_masks')}"
            )
        if rows.get("undef_elt", {}).get("entry_vgprs") != 2:
            failures.append(
                f"undef_elt entry VGPRs {rows.get('undef_elt', {}).get('entry_vgprs')}"
            )
        if rows.get("nsw_add", {}).get("poison_triage", {}).get("kinds") != "nsw":
            failures.append(
                f"nsw_add triage {rows.get('nsw_add', {}).get('poison_triage')}"
            )
        if not drv.poison_sensitive(rows.get("nsw_add", {})):
            failures.append("nsw_add: the mismatch should be marked poison-sensitive")
        if "poison_triage" in rows.get("masked_shift", {}):
            failures.append(
                f"masked_shift: triaged {rows['masked_shift']['poison_triage']}; its IR "
                "shift amount is masked, never poison"
            )
        report_md = (Path(tmp) / "out" / "report.md").read_text()
        if "poison-only" in report_md or "(poison-sensitive)" not in report_md:
            failures.append(
                "report: poison-sensitive mismatches are mismatches, marked"
            )
        for fn, wave in (("w32_fsel", 32), ("i8vec_ret", 32), ("w64_bug", 64)):
            r = rows.get(fn, {})
            if r.get("run_as") != "gfx1100" or r.get("wave_size") != wave:
                failures.append(
                    f"{fn}: run as {r.get('run_as')} wave{r.get('wave_size')}"
                )
        ps = rows.get("ps_i16", {})
        if ps.get("cc") != "shader" or ps.get("return_sgpr_masks") != [0xFFFF]:
            failures.append(
                f"ps_i16: cc {ps.get('cc')}, masks {ps.get('return_sgpr_masks')}"
            )
        if rows.get("i8vec_ret", {}).get("return_masks") != [0xFF] * 4:
            failures.append(
                f"i8vec_ret masks {rows.get('i8vec_ret', {}).get('return_masks')}"
            )
        if code != 1:
            failures.append(f"exit code {code}, expected 1 (a mismatch)")
        summary = json.loads((Path(tmp) / "out" / "summary.json").read_text())
        if summary.get("status") != "MISMATCH":
            failures.append(f"status {summary.get('status')}, expected MISMATCH")
        if "range_md" in rows or not any(
            s.get("function") == "range_md" and "IR" in s["reason"]
            for s in summary["skipped"]
        ):
            failures.append("range_md: a changed !range must make the IR differ")
        dup_rows = [f for f in summary["functions"] if f["function"] == "dup_fn"]
        dup_verdicts = sorted(drv.verdict(f) for f in dup_rows)
        if (
            dup_verdicts != ["mismatch", "pass"]
            or len({f["dir"] for f in dup_rows}) != 2
        ):
            failures.append(
                f"dup_fn: verdicts {dup_verdicts}, dirs {[f['dir'] for f in dup_rows]}"
            )

        code, rows, _ = run(
            a.driver,
            repo,
            Path(tmp) / "out_strict",
            a.tool,
            a.llvm_bin,
            "--strict-nan",
            "--no-poison-triage",
        )
        if drv.verdict(rows["fadd_ab"]) != "mismatch":
            failures.append("fadd_ab under --strict-nan should mismatch")
        if drv.verdict(rows["fadd_bits"]) != "mismatch":
            failures.append("fadd_bits under --strict-nan should mismatch")
        if drv.verdict(rows["nsw_add"]) != "mismatch":
            failures.append("nsw_add without triage should mismatch")

        # A commit with nothing this tool can compare (a new test, a test that is not
        # autogenerated, a RUN line change, a target not executed): NO_APPLICABLE_TESTS.
        (test.parent / "added.ll").write_text(dup_file(False, False))
        (test.parent / "manual.ll").write_text(
            "; RUN: llc -mcpu=gfx950 < %s\n" + "define void @m() {\n  ret void\n}\n"
        )
        git(repo, "add", ".")
        git(repo, "commit", "-q", "-m", "setup")
        (test.parent / "manual.ll").write_text(
            "; RUN: llc -mcpu=gfx950 < %s\n; CHECK: x\n"
            + "define void @m() {\n  ret void\n}\n"
        )
        (test.parent / "added2.ll").write_text(dup_file(True, False))
        flags.write_text(flags_file(True).replace("-O3", "-O2 -mattr=+fast"))
        git(repo, "add", ".")
        git(repo, "commit", "-q", "-m", "nothing to compare")
        code, rows, _ = run(a.driver, repo, Path(tmp) / "out_none", a.tool, a.llvm_bin)
        none = json.loads((Path(tmp) / "out_none" / "summary.json").read_text())
        if code != 4 or none.get("status") != "NO_APPLICABLE_TESTS" or rows:
            failures.append(
                f"nothing to compare: exit {code}, status {none.get('status')}, rows {list(rows)}"
            )

        # Two llc builds (wrappers around one llc; the "after" one commutes v_add_u32
        # operands, an equivalent change): an unchanged hand-written test (--all-tests)
        # and a corpus file without RUN lines (--corpus) are compiled and compared.
        llc = Path(a.llvm_bin) / "llc" if a.llvm_bin else None
        if llc and llc.exists():
            before, after = Path(tmp) / "llc_before", Path(tmp) / "llc_after"
            before.write_text(f'#!/bin/sh\nexec "{llc}" "$@"\n')
            after.write_text(
                f'#!/bin/sh\n"{llc}" "$@" | '
                "sed -E 's/(v_add_u32_e32 v[0-9]+), (v[0-9]+), (v[0-9]+)/\\1, \\3, \\2/'\n"
            )
            before.chmod(0o755)
            after.chmod(0o755)
            add = "define i32 @{0}(i32 %a, i32 %b) {{\n  %c = add i32 %a, %b\n  ret i32 %c\n}}\n"
            (test.parent / "unchanged_add.ll").write_text(
                "; RUN: llc -mtriple=amdgcn -mcpu=gfx950 < %s | FileCheck %s\n; CHECK: u_add\n"
                + add.format("u_add")
            )
            git(repo, "add", ".")
            git(repo, "commit", "-q", "-m", "an unchanged test")
            (repo / "llvm" / "README.txt").write_text("not a test\n")
            git(repo, "add", ".")
            git(repo, "commit", "-q", "-m", "a change outside the tests")
            corpus = Path(tmp) / "corpus"
            corpus.mkdir()
            (corpus / "kernel.ll").write_text(add.format("c_add"))
            code, rows, _ = run(
                a.driver,
                repo,
                Path(tmp) / "out_llc",
                a.tool,
                a.llvm_bin,
                "--llc-before",
                str(before),
                "--llc-after",
                str(after),
                "--all-tests",
                "--tests",
                "*unchanged_add.ll",
                "--corpus",
                str(corpus),
                "--corpus-mcpu",
                "gfx950",
            )
            for fn in ("u_add", "c_add"):
                got = drv.verdict(rows[fn]) if fn in rows else "missing"
                if got != "pass":
                    failures.append(
                        f"{fn} (two llc builds): verdict {got}, expected pass"
                    )
            if code != 0:
                failures.append(f"two llc builds: exit {code}, expected 0")

            # The "after" llc (commuting like the one above) fails on one corpus file:
            # requested, not compared, and new in the after build. c_add still passes, but
            # the run is INCOMPLETE (not PASS) and the failure one-sided.
            after_fails = Path(tmp) / "llc_after_fails"
            after_fails.write_text(
                "#!/bin/sh\nin=$(cat)\n"
                'case "$in" in *fail_here*) echo "LLVM ERROR: injected" >&2; exit 1;; esac\n'
                f'printf \'%s\\n\' "$in" | "{llc}" "$@" | '
                "sed -E 's/(v_add_u32_e32 v[0-9]+), (v[0-9]+), (v[0-9]+)/\\1, \\3, \\2/'\n"
            )
            after_fails.chmod(0o755)
            (corpus / "bad.ll").write_text(add.format("fail_here"))
            code, rows, _ = run(
                a.driver,
                repo,
                Path(tmp) / "out_llc_fail",
                a.tool,
                a.llvm_bin,
                "--llc-before",
                str(before),
                "--llc-after",
                str(after_fails),
                "--corpus",
                str(corpus),
                "--corpus-mcpu",
                "gfx950",
            )
            summary = json.loads(
                (Path(tmp) / "out_llc_fail" / "summary.json").read_text()
            )
            bad = [x for x in summary["skipped"] if x["file"].endswith("bad.ll")]
            if code != 2 or summary["status"] != "INCOMPLETE":
                failures.append(
                    f"llc failure in the corpus: exit {code}, status {summary['status']}"
                )
            if (
                not bad
                or "llc after only" not in bad[0]["reason"]
                or bad[0].get("scope") != "corpus"
            ):
                failures.append(f"llc failure in the corpus: skipped {bad}")
            if summary["stats"].get("llc_one_sided_failures") != 1:
                failures.append(f"one-sided llc failures: {summary['stats']}")
            if drv.verdict(rows.get("c_add", {})) != "pass":
                failures.append(
                    f"c_add with a failing corpus neighbour: {rows.get('c_add')}"
                )

        # Each side assembles with the llvm-mc next to its llc (an LLVM PR's own build):
        # wrappers record which one ran.
        if llc and llc.exists():
            mc = Path(a.llvm_bin) / "llvm-mc"
            for side in ("before", "after"):
                d = Path(tmp) / f"bin_{side}"
                d.mkdir()
                sed = (
                    ""
                    if side == "before"
                    else " | sed -E 's/(v_add_u32_e32 v[0-9]+), (v[0-9]+), (v[0-9]+)/"
                    "\\1, \\3, \\2/'"
                )
                (d / "llc").write_text(f'#!/bin/sh\n"{llc}" "$@"{sed}\n')
                (d / "llvm-mc").write_text(
                    f'#!/bin/sh\necho {side} >> "{d}/mc.log"\nexec "{mc}" "$@"\n'
                )
                for t in ("llc", "llvm-mc"):
                    (d / t).chmod(0o755)
            (corpus / "bad.ll").unlink()
            code, rows, _ = run(
                a.driver,
                repo,
                Path(tmp) / "out_mc",
                a.tool,
                a.llvm_bin,
                "--llc-before",
                str(Path(tmp) / "bin_before" / "llc"),
                "--llc-after",
                str(Path(tmp) / "bin_after" / "llc"),
                "--corpus",
                str(corpus),
                "--corpus-mcpu",
                "gfx950",
            )
            summary = json.loads((Path(tmp) / "out_mc" / "summary.json").read_text())
            for side in ("before", "after"):
                log = Path(tmp) / f"bin_{side}" / "mc.log"
                if not log.exists() or set(log.read_text().split()) != {side}:
                    failures.append(
                        f"{side} listings not assembled by the {side} llvm-mc"
                    )
                want = str((Path(tmp) / f"bin_{side}" / "llvm-mc").resolve())
                if summary["meta"].get("assembler", {}).get(side) != want:
                    failures.append(
                        f"assembler {side}: {summary['meta'].get('assembler')}"
                    )
            if drv.verdict(rows.get("c_add", {})) != "pass" or code != 0:
                failures.append(
                    f"own assemblers: exit {code}, c_add {rows.get('c_add')}"
                )
            report_mc = (Path(tmp) / "out_mc" / "report.md").read_text()
            if (
                "assembler (llvm-mc): before "
                + str((Path(tmp) / "bin_before" / "llvm-mc").resolve())
                not in report_mc
            ):
                failures.append("report: the assemblers are not named")

            # The after LLVM's own llvm-mc rejects a listing the after llc emitted (as
            # upstream llvm-mc rejects a bf16 inline constant without op_sel): the change
            # emits invalid assembly. A defect (asm-rejected, MISMATCH), not UNSUPPORTED.
            (Path(tmp) / "bin_after" / "llvm-mc").write_text(
                "#!/bin/sh\n"
                'for a in "$@"; do case "$a" in *.s) if grep -q reject_me "$a"; then '
                'echo "$a:1:1: error: injected rejection" >&2; exit 1; fi;; esac; done\n'
                f'exec "{mc}" "$@"\n'
            )
            (corpus / "reject.ll").write_text(add.format("reject_me"))
            code, rows, _ = run(
                a.driver,
                repo,
                Path(tmp) / "out_mc_reject",
                a.tool,
                a.llvm_bin,
                "--llc-before",
                str(Path(tmp) / "bin_before" / "llc"),
                "--llc-after",
                str(Path(tmp) / "bin_after" / "llc"),
                "--corpus",
                str(corpus),
                "--corpus-mcpu",
                "gfx950",
            )
            r = rows.get("reject_me", {})
            if drv.verdict(r) != "asm-rejected" or code != 1:
                failures.append(
                    f"own assembler rejects the new listing: exit {code}, {r}"
                )
            if "injected rejection" not in r.get("detail", ""):
                failures.append(f"asm-rejected detail: {r.get('detail')}")
            if drv.verdict(rows.get("c_add", {})) != "pass":
                failures.append(
                    f"c_add next to a rejected listing: {rows.get('c_add')}"
                )

    if failures:
        print("FAILED:\n  " + "\n  ".join(failures))
        print(log[-3000:])
        return 1
    print("rj_isa_diff_pr end-to-end test: all verdicts as expected")
    return 0


if __name__ == "__main__":
    sys.exit(main())

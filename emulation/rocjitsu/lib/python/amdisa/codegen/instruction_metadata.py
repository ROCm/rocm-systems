"""Canonical operation identities and decoded classification shared by consumers.

Names are interpreted only while generating code. The emitted instruction model
contains numeric identities and facts; execution support and wait policy remain
owned by their existing providers and consumers.
"""

from pathlib import Path
import re

from amdisa.codegen.dbt.rule_gen import matrix_conversion_source_operations


def canonical_operation_name(name: str) -> str:
    """Normalize an MRISA name, excluding assembly-only encoding decorations."""
    return re.sub(r'_(?:E32|E64|SDWA|DPP)(?:_DPP)?$', '', name.upper())


def operation_names(specs) -> list[str]:
    """Collect names, including decoded FLAT aliases and dual-slot operations."""
    names = set(matrix_conversion_source_operations())
    for _, spec, _ in specs:
        for encoding in spec.inst_encodings:
            for inst in encoding.insts:
                name = canonical_operation_name(inst.name)
                names.add(name)
                if name.startswith('FLAT_'):
                    names.add('GLOBAL_' + name[5:])
                    names.add('SCRATCH_' + name[5:])
        for operation in getattr(spec.profile, 'vopd_slot_ops', ()):
            names.add(canonical_operation_name(operation.mnemonic))
        # Extended matrix encodings are emitted by dedicated templates rather
        # than the parser's ordinary instruction-class list.
        if spec.arch_name == 'cdna4':
            names.update(
                (
                    'V_MFMA_SCALE_F32_16X16X128_F8F6F4',
                    'V_MFMA_SCALE_F32_32X32X64_F8F6F4',
                )
            )
        if spec.arch_name == 'cdna5':
            names.update(
                f'V_WMMA_{scale}_F32_{shape}'
                for scale in ('SCALE', 'SCALE16')
                for shape in ('16X16X128_F8F6F4', '32X16X128_F4')
            )
    if any(re.fullmatch(r'[A-Z][A-Z0-9_]*', name) is None for name in names):
        raise ValueError('canonical operation names must be C++ identifiers')
    if len(names) >= 65535:
        raise ValueError('canonical operation catalog exceeds uint16_t')
    return sorted(names)


def emit_operations(output_dir: str, specs) -> list[str]:
    """Emit the shared catalog for the supplied generation input set.

    Like shared ISA properties, this file describes this invocation's complete
    input set. Production regeneration supplies all supported ISAs; focused
    generation should use a separate output directory.
    """
    names = operation_names(specs)
    output = Path(output_dir) / 'shared' / 'operations.h'
    output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        '// Copyright (c) 2026 Advanced Micro Devices, Inc.',
        '// SPDX-License-Identifier: MIT',
        '// AUTO-GENERATED by the amdisa codegen pipeline. DO NOT EDIT.',
        '',
        '#pragma once',
        '',
        '#include <cstdint>',
        '',
        'namespace rocjitsu::amdgpu {',
        '',
        '/// @brief Canonical operations shared across AMDGPU encoding families.',
        '/// @details Internal generated identities, not a stable serialization or ABI.',
        '/// Encoding aliases share an identity; target legality remains separate.',
        'enum class Operation : uint16_t {',
        '  Unknown,',
        *(f'  {name},' for name in names),
        '  Count,',
        '};',
        '',
        '} // namespace rocjitsu::amdgpu',
        '',
    ]
    output.write_text('\n'.join(lines))
    return names


def installed_operation_names() -> frozenset[str]:
    """Names representable by the checkout's shared instruction base.

    This only answers enum representability. Semantic classification never
    depends on a generated artifact. Installed standalone Python packages may
    have no C++ checkout, in which case custom operations remain Unknown.
    """
    root = Path(__file__).resolve().parents[3]
    header = (
        root / 'rocjitsu/src/rocjitsu/isa/arch/amdgpu/generated/shared/operations.h'
    )
    if not header.is_file():
        return frozenset()
    return frozenset(re.findall(r'^  ([A-Z][A-Z0-9_]*),$', header.read_text(), re.M))


def operation_expression(name: str, known_names: frozenset[str] | None = None) -> str:
    name = canonical_operation_name(name)
    if known_names is not None and name not in known_names:
        return 'amdgpu::Operation::Unknown'
    return f'amdgpu::Operation::{name}'


def memory_classification(name: str, semantic_class: str | None) -> tuple[str, str]:
    """Return orthogonal addressing and transaction categories at generation time."""
    name = name.upper()
    prefixes = (
        ('S_SCRATCH_', 'Scratch'),
        ('S_', 'Scalar'),
        ('FLAT_', 'Flat'),
        ('GLOBAL_', 'Global'),
        ('SCRATCH_', 'Scratch'),
        ('TBUFFER_', 'TypedBuffer'),
        ('BUFFER_', 'Buffer'),
        ('IMAGE_', 'Image'),
        ('TENSOR_', 'Tensor'),
        ('CLUSTER_', 'Cluster'),
        ('DS_', 'Lds'),
        ('LDS_', 'DirectLds'),
    )
    addressing = next(
        (value for prefix, value in prefixes if name.startswith(prefix)), 'None'
    )
    if name in ('DS_DIRECT_LOAD', 'DS_PARAM_LOAD'):
        addressing = 'DirectLds'
    if name.startswith('DS_GWS_') or name in (
        'DS_ORDERED_COUNT',
        'DS_ADD_GS_REG_RTN',
        'DS_SUB_GS_REG_RTN',
    ):
        addressing = 'Gds'
    if (
        addressing == 'Scalar'
        and not name.startswith(
            (
                'S_LOAD',
                'S_STORE',
                'S_BUFFER_',
                'S_ATOMIC_',
                'S_SCRATCH_',
                'S_DCACHE_',
                'S_PREFETCH_',
                'S_ATC_PROBE',
            )
        )
        and name not in ('S_GL1_INV', 'S_MEMTIME', 'S_MEMREALTIME')
    ):
        return 'None', 'None'
    if addressing == 'None':
        return addressing, 'None'
    if 'BVH' in name:
        kind = 'Bvh'
    elif '_ATOMIC_' in name or (
        semantic_class
        and semantic_class
        in (
            'ds_atomic',
            'ds_atomic2',
            'ds_mskor',
            'ds_append_consume',
            'ds_stack',
        )
    ):
        kind = 'Atomic'
    elif name.startswith(('IMAGE_SAMPLE', 'IMAGE_GATHER')):
        kind = 'Sample'
    elif '_PREFETCH' in name:
        kind = 'Prefetch'
    elif '_ATC_PROBE' in name:
        kind = 'Probe'
    elif any(token in name for token in ('_DCACHE_', '_INV', '_WB', '_DISCARD')):
        kind = 'Cache'
    elif '_LOAD' in name or name.startswith(('DS_READ', 'S_MEMTIME', 'S_MEMREALTIME')):
        kind = 'Load'
    elif '_STORE' in name or name.startswith('DS_WRITE'):
        kind = 'Store'
    else:
        kind = 'Other'
    return addressing, kind


def classification_flags(name: str, sem) -> list[str]:
    """Facts used by multiple analyses, independent of exact-operation policies."""
    name = name.upper()
    flags = []
    if name.startswith(('V_MFMA_', 'V_SMFMAC_', 'V_WMMA_', 'V_SWMMAC_')):
        flags.append('MATRIX_OP')
    if (
        sem is not None
        and sem.semantic_class
        in ('scalar_getpc', 'scalar_swappc', 'scalar_call', 'scalar_addpc')
    ) or name in (
        'S_GETPC_B64',
        'S_SWAPPC_B64',
        'S_CALL_B64',
        'S_ADDPC_I64',
        'S_GET_PC_I64',
        'S_SWAP_PC_I64',
        'S_CALL_I64',
        'S_ADD_PC_I64',
        'S_PREFETCH_INST_PC_REL',
        'S_PREFETCH_DATA_PC_REL',
    ):
        flags.append('READS_PC')
    if name.startswith('V_INTERP_'):
        flags.append('INTERPOLATION')
    if '_TO_LDS' in name or name.startswith(('GLOBAL_LOAD_LDS_', 'SCRATCH_LOAD_LDS_')):
        flags.append('MEMORY_TO_LDS')
    if '_FROM_LDS' in name:
        flags.append('MEMORY_FROM_LDS')
    if '_D16' in name:
        flags.append('D16_MEMORY_DATA')
    for prefix, source, destination in (
        ('S_', 'RELATIVE_SGPR_SOURCE', 'RELATIVE_SGPR_DESTINATION'),
        ('V_', 'RELATIVE_VGPR_SOURCE', 'RELATIVE_VGPR_DESTINATION'),
    ):
        if name.startswith((prefix + 'MOVRELS', prefix + 'SWAPREL')):
            flags.append(source)
        if name.startswith(
            (prefix + 'MOVRELD', prefix + 'MOVRELSD', prefix + 'SWAPREL')
        ):
            flags.append(destination)
    return flags

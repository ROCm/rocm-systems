uint64_t gfx11_msaa_address(uint64_t base, uint32_t x, uint32_t y, uint32_t layer, uint32_t sample,
                            uint32_t pitch, uint32_t height, uint32_t bytes, uint32_t sample_log2,
                            uint32_t swizzle) {
  const uint32_t block_log2 = swizzle >= 28 ? 18 : 16;
  const uint32_t elem = std::countr_zero(bytes);
  const uint32_t texel_bits = block_log2 - elem - sample_log2;
  const uint32_t x_bits = (texel_bits + ((sample_log2 & 1) == 0)) / 2;
  const uint32_t y_bits = texel_bits - x_bits;
  const uint32_t columns = (pitch + (1u << x_bits) - 1) >> x_bits;
  const uint32_t rows = (height + (1u << y_bits) - 1) >> y_bits;
  const uint64_t block = (uint64_t{layer} * rows + (y >> y_bits)) * columns + (x >> x_bits);
  const uint64_t inputs =
      x | (uint64_t{y} << 16) | (uint64_t{layer} << 32) | (uint64_t{sample} << 48);
  const auto &masks = kSelectors[swizzle >= 28][sample_log2 - 1][elem];
  uint32_t offset = 0;
  for (uint32_t bit = 0; bit < block_log2; ++bit)
    offset |= (std::popcount(inputs & masks[bit]) & 1u) << bit;
  return (base + (block << block_log2)) ^ offset;
}


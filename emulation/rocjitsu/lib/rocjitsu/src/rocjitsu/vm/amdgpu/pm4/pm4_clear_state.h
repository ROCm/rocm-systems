/// @brief Restore the GFX11 context-shadow ranges to their CLEAR_STATE values.
/// @details Register data follows InitializeContextRegistersGfx11 in PAL c5e8000,
/// src/core/hw/gfxip/gfx9/g_gfx9ShadowedRegistersInit.h. Registers outside those
/// ranges retain their values; shader and user-config registers are unaffected.

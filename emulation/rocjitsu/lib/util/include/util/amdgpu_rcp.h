/// @brief AMD FP32 reciprocal matching physical RDNA3/4 within the ISA 1-ULP bound.
/// @details Flushes input and output subnormals independently of MODE and host rounding.
/// Preserves signs and NaN payloads, quieting signaling NaNs.
inline float amdgpu_rcp_f32(float value) {
  const uint32_t bits = std::bit_cast<uint32_t>(value);
  const uint32_t sign = bits & 0x80000000u;
  const uint32_t magnitude = bits & 0x7fffffffu;
  if (magnitude > 0x7f800000u)
    return std::bit_cast<float>(bits | 0x00400000u);
  if (magnitude < 0x00800000u)
    return std::bit_cast<float>(sign | 0x7f800000u);
  if (magnitude == 0x7f800000u)
    return std::bit_cast<float>(sign);
  const uint32_t normalized = detail::amdgpu_rcp_normalized_bits(magnitude & 0x7fffffu);
  const int exponent = int(normalized >> 23) + 127 - int(magnitude >> 23);
  if (exponent <= 0)
    return std::bit_cast<float>(sign);
  if (exponent >= 255)
    return std::bit_cast<float>(sign | 0x7f800000u);
  return std::bit_cast<float>(sign | (uint32_t(exponent) << 23) | (normalized & 0x7fffffu));
}


inline uint32_t amdgpu_rcp_normalized_bits(uint32_t mantissa) {
  uint32_t result = amdgpu_rcp_polynomial(mantissa);
  const uint32_t bucket = mantissa >> 15;
  const uint16_t key = mantissa & 0x7fffu;
  uint32_t first = kAmdgpuRcpCorrectionOffsets[bucket];
  uint32_t last = kAmdgpuRcpCorrectionOffsets[bucket + 1];
  const uint32_t end = last;
  while (first < last) {
    const uint32_t middle = first + (last - first) / 2;
    if ((kAmdgpuRcpCorrections[middle] & 0x7fffu) < key)
      first = middle + 1;
    else
      last = middle;
  }
  if (first != end && (kAmdgpuRcpCorrections[first] & 0x7fffu) == key)
    result = (kAmdgpuRcpCorrections[first] & 0x8000u) ? result + 1 : result - 1;
  return result;
}


inline uint32_t amdgpu_rsq_normalized_bits(uint32_t index) {
  uint32_t result = amdgpu_rsq_polynomial(index);
  const uint32_t bucket = index >> 15;
  const uint16_t key = index & 0x7fffu;
  uint32_t first = kAmdgpuRsqCorrectionOffsets[bucket];
  uint32_t last = kAmdgpuRsqCorrectionOffsets[bucket + 1];
  const uint32_t end = last;
  while (first < last) {
    const uint32_t middle = first + (last - first) / 2;
    if ((kAmdgpuRsqCorrections[middle] & 0x7fffu) < key)
      first = middle + 1;
    else
      last = middle;
  }
  if (first != end && (kAmdgpuRsqCorrections[first] & 0x7fffu) == key)
    result = (kAmdgpuRsqCorrections[first] & 0x8000u) ? result + 1 : result - 1;
  return result;
}

inline uint32_t amdgpu_rsq_bits(uint32_t input) {
  const uint32_t magnitude = input & 0x7fffffffu;
  const uint32_t sign = input & 0x80000000u;
  if (magnitude > 0x7f800000u)
    return input | 0x00400000u;
  if (magnitude < 0x00800000u)
    return sign | 0x7f800000u;
  if (sign != 0)
    return 0xffc00000u;
  if (magnitude == 0x7f800000u)
    return 0;

  const int exponent = static_cast<int>(magnitude >> 23) - 127;
  const unsigned parity = exponent & 1;
  const uint32_t normalized =
      amdgpu_rsq_normalized_bits((parity << 23) | (magnitude & 0x007fffffu));
  const int result_exponent =
      static_cast<int>(normalized >> 23) - (exponent - static_cast<int>(parity)) / 2;
  return (static_cast<uint32_t>(result_exponent) << 23) | (normalized & 0x007fffffu);
}

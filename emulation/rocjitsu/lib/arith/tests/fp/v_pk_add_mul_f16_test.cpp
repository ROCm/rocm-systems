// Check captures in Compatibility (SIMD path) and both exact modes (scalar path).
template <size_t N, typename Call>
void check_packed_captures(Call call, const PackedCapture (&captures)[N], bool ieee) {
  using namespace rocjitsu::arith::test;
  for (uint64_t cpu : supported_cpu_levels()) {
    for (uint64_t semantics :
         {RJ_ARITH_SEMANTICS_COMPATIBILITY, RJ_ARITH_SEMANTICS_BIT_EXACT_EMPIRICAL_ALLOW_LOOSE,
          RJ_ARITH_SEMANTICS_BIT_EXACT_EMPIRICAL_NO_FP_STATUS}) {
      for (const auto &test : captures) {
        const uint32_t denorm = (test.mode >> 6) & 3;
        const uint64_t flags = cpu | semantics | (uint64_t((test.mode >> 2) & 3) << 24) |
                               (denorm & 1 ? 0 : RJ_ARITH_FP_FLUSH_INPUT_DENORMALS) |
                               (denorm & 2 ? 0 : RJ_ARITH_FP_FLUSH_OUTPUT_DENORMALS) |
                               ((test.mode >> 23) & 1 ? RJ_ARITH_FP16_OVFL : 0) |
                               (ieee ? RJ_ARITH_FP_IEEE_MODE : 0);
        Registers<3, 32> r;
        r.v[0][0] = test.a;
        r.v[1][0] = test.b;
        ASSERT_EQ(call(flags, 1, 0, r.v + 2, r.v, r.v + 1, nullptr), RJ_ARITH_SUCCESS);
        EXPECT_EQ(r.v[2][0], test.d)
            << std::hex << cpu << '/' << semantics << " mode 0x" << test.mode << " ieee " << ieee
            << ": 0x" << test.a << ", 0x" << test.b;
      }
    }
  }
}


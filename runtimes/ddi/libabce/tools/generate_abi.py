"""Regenerate ABCE value bindings and C exports, never implementation code.

Requires Clang and rustfmt only when updating/checking the checked-in bindings.
The declarations-only C headers are authoritative. Bitfield records are stored
as explicit 32-bit words; Rust encoders own the masks, not C bitfield access.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[3]
FRONTEND = ROOT / "ddi/libabce"
CORE = ROOT / "ddi/rocddi/src/device/gpu/abce"
LICENSE = "// Copyright (c) 2026 Advanced Micro Devices, Inc.\n// SPDX-License-Identifier: MIT\n\n"
GENERATED = "// Generated by ddi/libabce/tools/generate_abi.py; do not edit.\n\n"
KEYWORDS = {"type", "ref", "match", "loop", "in", "move", "fn", "self", "mod", "box", "use"}
BASE = {
    "void": "core::ffi::c_void", "_Bool": "bool", "bool": "bool",
    "char": "core::ffi::c_char", "signed char": "i8", "unsigned char": "u8",
    "short": "i16", "unsigned short": "u16", "int": "i32", "unsigned int": "u32",
    "long": "core::ffi::c_long", "unsigned long": "core::ffi::c_ulong",
    "long long": "i64", "unsigned long long": "u64",
    "size_t": "usize", "uintptr_t": "usize", "ptrdiff_t": "isize",
    **{f"{sign}int{width}_t": f"{'u' if sign else 'i'}{width}"
       for sign in ("", "u") for width in (8, 16, 32, 64)},
}


def run(command: list[str], source: str | None = None) -> str:
    return subprocess.run(command, input=source, text=True, check=True,
                          stdout=subprocess.PIPE).stdout


def name(identifier: str) -> str:
    return f"r#{identifier}" if identifier in KEYWORDS else identifier


class Bindings:
    def __init__(self, ast: dict, source: str):
        self.source = source
        self.records: dict[str, dict] = {}
        self.aliases: dict[str, str] = {}
        self.enums: dict[str, dict] = {}
        self.typedefs: dict[str, str] = {}
        self.functions: dict[str, dict] = {}
        self.data: set[str] = set()
        for node in ast["inner"]:
            identifier = node.get("name", "")
            if not identifier.startswith(("abce_", "SDMA_", "sdma_")):
                continue
            match node["kind"]:
                case "RecordDecl":
                    self.register(node)
                case "EnumDecl":
                    self.enums[identifier] = node
                case "TypedefDecl":
                    self.typedefs[identifier] = node["type"]["qualType"]
                case "FunctionDecl" if node.get("storageClass") == "extern":
                    self.functions[identifier] = node
                case "VarDecl" if node.get("storageClass") == "extern":
                    self.data.add(identifier)

    def location(self, node: dict) -> str:
        loc = node["loc"]
        line = loc.get("line", self.source[:loc["offset"]].count("\n") + 1)
        return f"{line}:{loc['col']}"

    def register(self, node: dict, suggested: str = "") -> None:
        if not node.get("completeDefinition"):
            return
        identifier = node.get("name", suggested)
        self.records[identifier] = node
        if not node.get("name"):
            self.aliases[self.location(node)] = identifier
        for child in node.get("inner", []):
            if child["kind"] != "RecordDecl":
                continue
            key = self.location(child)
            field = next((f for f in node["inner"] if f["kind"] == "FieldDecl"
                          and f":{key})" in f["type"]["qualType"]), None)
            suffix = field.get("name", "bits") if field else "nested"
            self.register(child, f"{identifier}_{suffix}")

    def rust_type(self, spelling: str) -> str:
        spelling = re.sub(r"\b(volatile|restrict)\b", "", spelling).strip()
        spelling = re.sub(r"\s+", " ", spelling)
        if match := re.fullmatch(r"(.*?)\(\*\)((?:\[\d+\])+)", spelling):
            qualifier = "const" if match[1].startswith("const ") else "mut"
            return f"*{qualifier} {self.rust_type(match[1] + match[2])}"
        if match := re.fullmatch(r"(.*?)\(\*\)\((.*)\)", spelling):
            result, args = match.groups()
            args = [] if args in ("", "void") else args.split(", ")
            arguments = ", ".join(map(self.rust_type, args))
            result = "" if result.strip() == "void" else f" -> {self.rust_type(result)}"
            return f'Option<unsafe extern "C" fn({arguments}){result}>'
        if spelling.endswith("const"):
            spelling = spelling[:-5].strip()
        if spelling.endswith("*"):
            pointee = spelling[:-1].strip()
            qualifier = "const" if pointee.startswith("const ") or pointee.endswith("const") else "mut"
            return f"*{qualifier} {self.rust_type(pointee)}"
        if match := re.fullmatch(r"(.*?)((?:\[\d+\])+)", spelling):
            element = self.rust_type(match[1])
            for count in reversed(re.findall(r"\[(\d+)\]", match[2])):
                element = f"[{element}; {count}]"
            return element
        spelling = re.sub(r"^(const |struct |union |enum )", "", spelling)
        if spelling.startswith(("struct ", "union ", "enum ")):
            return self.rust_type(spelling)
        if "(unnamed" in spelling or "(anonymous" in spelling:
            match = re.search(r":(\d+:\d+)\)", spelling)
            if not match:
                raise ValueError(f"unrecognized anonymous record: {spelling}")
            return self.aliases[match[1]]
        result = BASE.get(spelling, spelling)
        if not re.fullmatch(r"[\w:]+", result):
            raise ValueError(f"unsupported C type: {spelling}")
        return result

    def types(self) -> str:
        output = [LICENSE + GENERATED + "//! C ABI value records. The public C headers are authoritative.\n",
                  "#![allow(missing_docs, non_camel_case_types, non_snake_case)]\n"]
        for identifier, node in self.enums.items():
            output.append(f"pub type {identifier} = u32;")
            value = 0
            for child in node["inner"]:
                if child["kind"] != "EnumConstantDecl":
                    continue
                if child.get("inner"):
                    value = int(child["inner"][0]["value"])
                output.append(f"pub const {child['name']}: {identifier} = {value};")
                value += 1
        for identifier, node in self.records.items():
            fields = [f for f in node.get("inner", []) if f["kind"] == "FieldDecl"]
            aligned = [(i, int(a["inner"][0]["value"])) for i, field in enumerate(fields)
                       for a in field.get("inner", []) if a["kind"] == "AlignedAttr"]
            alignment = max((a for _, a in aligned), default=0)
            align_repr = f", align({alignment})" if alignment else ""
            output.extend([f"#[repr(C{align_repr})]", "#[derive(Clone, Copy)]",
                           f"pub {node['tagUsed']} {identifier} {{"])
            if any(f.get("isBitfield") for f in fields):
                # All current SDMA bitfields are complete, unsigned 32-bit words.
                if not all(f.get("isBitfield") and f["type"]["qualType"] in
                           ("unsigned int", "uint32_t") for f in fields):
                    raise ValueError(f"mixed/unsupported bitfields in {identifier}")
                if sum(int(f["inner"][0]["value"]) for f in fields) != 32:
                    raise ValueError(f"bitfields in {identifier} do not fill a dword")
                output.append("pub word: u32,")
            else:
                for index, field in enumerate(fields):
                    # Rust repr(align) affects the record, not interior members.
                    # This is the only current interior over-alignment. Refuse
                    # a new one until its padding is explicitly reviewed.
                    if any(i == index and i != 0 for i, _ in aligned):
                        if identifier != "abce_rect_count_state_t" or field.get("name") != "scratch" or aligned != [(1, 16)]:
                            raise ValueError(f"review interior alignment of {identifier}")
                        output.append("pub padding: [u8; 12],")
                    output.append(f"pub {name(field.get('name', 'bits'))}: {self.rust_type(field['type']['qualType'])},")
            output.append("}")
        for identifier, spelling in self.typedefs.items():
            if identifier not in self.records and identifier not in self.enums:
                output.append(f"pub type {identifier} = {self.rust_type(spelling)};")
        return "\n".join(output) + "\n"

    def frontend(self, core_functions: set[str]) -> str:
        output = [LICENSE + GENERATED + '''//! Existing ABCE host C API, implemented by the native rocddi engine.
//!
//! Records remain caller-owned. Entry points inherit their public header's
//! pointer, alignment, synchronization and lifetime preconditions.

#![allow(unsafe_code, missing_docs)]
#![allow(clippy::missing_safety_doc, clippy::too_many_arguments, clippy::wildcard_imports)]

#[cfg(all(target_os = "linux", not(test)))]
core::arch::global_asm!(include_str!("exports_linux.S"));

use rocddi::device::gpu::abce as native;
use native::abi::*;
''']
        for identifier, node in sorted(self.functions.items()):
            if identifier in core_functions:
                continue
            parameters = [p for p in node.get("inner", []) if p["kind"] == "ParmVarDecl"]
            arguments = ", ".join(name(p["name"]) for p in parameters)
            declaration = ", ".join(f"{name(p['name'])}: {self.rust_type(p['type']['qualType'])}" for p in parameters)
            result = node["type"]["qualType"].split("(")[0].strip()
            result = "" if result == "void" else f" -> {self.rust_type(result)}"
            output.append('#[unsafe(no_mangle)]')
            if identifier == "abce_host_abi_version":
                output.append('pub extern "C" fn abce_host_abi_version() -> u32 { ABCE_HOST_ABI_VERSION }\n')
            else:
                output.append(f'pub unsafe extern "C" fn {identifier}({declaration}){result} {{\n'
                              f"    unsafe {{ native::{identifier}({arguments}){';' if not result else ''} }}\n}}\n")
        return "\n".join(output)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clang", default=os.environ.get("CLANG", "clang"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    headers = ROOT / "api-headers/include"
    translation_unit = '\n'.join(f'#include <abce/{h}.h>' for h in ("abce_host", "abce_decode", "abce_device")) + '\n'
    command = [args.clang, "-std=c11", "-DABCE_ENABLE_IMPLEMENTATION=0", f"-I{headers}", "-x", "c"]
    source = run(command + ["-E", "-P", "-"], translation_unit)
    with tempfile.TemporaryDirectory(prefix="abce-bindings-") as directory:
        preprocessed = Path(directory) / "declarations.c"
        preprocessed.write_text(source)
        ast = json.loads(run([args.clang, "-std=c11", "-Xclang", "-ast-dump=json",
                              "-fsyntax-only", str(preprocessed)]))
    bindings = Bindings(ast, source)
    manifest = {tuple(line.split()) for line in (FRONTEND / "abi/exports.txt").read_text().splitlines()
                if line and not line.startswith("#")}
    declarations = {("function", n) for n in bindings.functions} | {("data", n) for n in bindings.data}
    normalized = {("function" if kind == "core-function" else kind, n) for kind, n in manifest}
    if normalized != declarations:
        raise ValueError(f"review export manifest drift: {sorted(normalized ^ declarations)}")
    core_functions = {n for kind, n in manifest if kind == "core-function"}
    macros = run(command + ["-dM", "-E", "-"], translation_unit)
    types = bindings.types()
    for constant in ("ABCE_HOST_ABI_VERSION", "ABCE_DEVICE_ABI_VERSION"):
        match = re.search(rf"^#define {constant} (\d+)u?\s*$", macros, re.MULTILINE)
        if not match:
            raise ValueError(f"invalid ABI version: {constant}")
        types += f"pub const {constant}: u32 = {match[1]};\n"
    outputs = {CORE / "abi.rs": types, FRONTEND / "src/lib.rs": bindings.frontend(core_functions)}
    for path in list(outputs):
        outputs[path] = run(["rustfmt", "--edition", "2024", "--emit", "stdout"], outputs[path])
    # Thin LTO can copy module assembly into a partition without a definition.
    # @@@ makes a default version only where the symbol is defined, and a
    # reference elsewhere. Removing the original alias also permits GNU static
    # linking of other frontends which carry rocddi's data/callback object.
    for kind, path in (("function", FRONTEND / "src/exports_linux.S"),
                       ("data", CORE / "data_exports_linux.S")):
        outputs[path] = LICENSE + GENERATED + "".join(
            f".symver {identifier},{identifier}@@@ABCE_1, remove\n"
            for symbol_kind, identifier in sorted(manifest) if symbol_kind == kind or (kind == "data" and symbol_kind == "core-function"))
    stale = False
    for path, content in outputs.items():
        if args.check:
            old = path.read_text() if path.exists() else ""
            if old != content:
                stale = True
                print("".join(list(difflib.unified_diff(old.splitlines(True), content.splitlines(True),
                                                     fromfile=str(path), tofile="generated"))[:80]))
        else:
            path.write_text(content)
    return int(stale)


if __name__ == "__main__":
    raise SystemExit(main())
